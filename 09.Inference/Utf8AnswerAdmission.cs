// ДОПУСК ЦЕЛОГО СИМВОЛА ДО ВЫБОРА ТОКЕНА.
//
// Что решает этот файл, по-человечески. Модель выдаёт ответ по одному номеру
// токена. Словарь здесь байтовый, то есть один номер часто равен одному байту, а
// одна русская буква занимает два байта, знак валюты — три, составной знак —
// четыре. Поэтому можно выбрать номер, который НАЧИНАЕТ символ, и на этом
// остановиться: ответ обрывается посреди символа. Прежняя починка обрезала такой
// хвост ПОСЛЕ порождения — ответ становился короче, но выбор уже был сделан.
// Здесь делается другое: негодные продолжения убираются ДО выбора, поэтому
// обрывать нечего.
//
// Чем это НЕ является, названо прямо. Это НЕ фильтр по латинице и не запрет
// байтов от 128. Такой запрет убил бы русский ответ: байт 182 незаконен в начале
// символа и совершенно законен сразу после байта 208 — вместе они и есть буква
// «ж». Поэтому решение здесь принимается по СОСТОЯНИЮ последовательности байтов,
// а не по номеру и не по диапазону номера.
//
// Абрревиатуры при первом употреблении. UTF-8 (Unicode Transformation Format,
// 8-bit — способ записи знаков Unicode цепочкой байтов переменной длины). BPE
// (Byte Pair Encoding — словарь, который склеивает часто встречающиеся пары
// байтов в один номер, поэтому у одного номера может быть много байтов).
// SHA-256 (Secure Hash Algorithm 256-bit — отпечаток содержимого длиной 256
// бит; здесь он служит удостоверением словаря).
//
// О виде возврата. В сборке этого файла конверта результата операции
// (`OperationResult<T>`) НЕТ: файл проекта 09.Inference ссылается только на
// 00.TensorCore, 01.Tokenizer и 03.TransformerModel, и ни одна из них его не
// объявляет. Вводить четырнадцатое объявление конверта или новую ссылку между
// сборками — отдельное архитектурное решение, а не часть этой починки. Поэтому
// здесь используется соглашение самого файла-владельца: состояние возвращается
// перечислением, а невозможное состояние сообщается броском с говорящим кодом,
// ровно как это уже делает `TextGenerator`. Это названо здесь, а не скрыто.

using Tokenizer;

namespace Inference;

// Чем кончилось добавление байтов кандидата к текущему состоянию ответа.
internal enum Utf8CandidateStatus
{
    // Байты легли законно, и ни один символ не остался недособранным: на таком
    // кандидате ответ можно ЗАВЕРШАТЬ.
    ValidComplete,

    // Байты законны, но последний символ ещё не дособран: продолжать можно,
    // завершать нельзя.
    ValidPrefix,

    // Байты не годятся ни как начало символа, ни как продолжение текущего:
    // кандидат непригоден совсем.
    Invalid
}

// Неизменный снимок «номер токена → его байты» для ОДНОГО принятого словаря.
//
// Зачем снимок, а не обращение к словарю на каждом шаге. Допуск опрашивает
// каждого кандидата на каждом шаге, то есть обходит словарь целиком много раз.
// Снимок берётся один раз за порождение, после чего шаг работает по уже готовым
// массивам байтов: ни одной новой сборки строки, ни одного обращения к
// генератору случайных чисел.
//
// Почему байты берутся сборкой байтов, а НЕ разбором в строку. Это измерено на
// чужой ошибке и записано в договоре приёмки: разбор одинокого байта 182 даёт
// знак замены, чьи собственные байты 239, 191, 189 образуют законный
// трёхбайтовый символ, и обломок ложно выглядел бы законченным. Сборка байтов
// отдаёт содержимое словаря напрямую, без превращения в строку, поэтому ложного
// законного вида не возникает.
internal sealed class Utf8TokenByteSnapshot
{
    // Байты каждого номера: место в массиве и есть номер токена.
    private readonly byte[][] _bytesByIdentifier;

    private Utf8TokenByteSnapshot(byte[][] bytesByIdentifier, string tokenizerStateSha256,
        long retainedByteCount)
    {
        // Готовая таблица байтов переходит во владение снимка и больше не меняется.
        _bytesByIdentifier = bytesByIdentifier;
        // Удостоверение словаря: по нему видно, что снимок принадлежит именно этому словарю.
        TokenizerStateSha256 = tokenizerStateSha256;
        // Сколько байтов словаря снимок держит в памяти — это цена снимка.
        RetainedByteCount = retainedByteCount;
    }

    // Отпечаток состояния словаря вида SHA-256: удостоверение, а не обучаемое состояние.
    internal string TokenizerStateSha256 { get; }

    // Сколько всего байтов удержано снимком: цена снимка в памяти.
    internal long RetainedByteCount { get; }

    // Граница допустимых номеров: законные номера лежат в промежутке от нуля до этого числа.
    internal int VocabularySize => _bytesByIdentifier.Length;

    // Сколько номеров снимок обошёл при построении — цена построения в опросах словаря.
    internal int ScannedIdentifierCount => _bytesByIdentifier.Length;

    // TryGetBytes отвечает отдельно на два РАЗНЫХ вопроса, и это ключ ко всему допуску.
    //
    // Первый вопрос — известен ли номер вообще. Возвращается ложь ровно тогда, когда номер
    // лежит ВНЕ промежутка известных номеров. Это отдельный признак, а не вывод из числа
    // байтов, и так сделано НАМЕРЕННО: сборка байтов отдаёт неизвестному номеру ноль байтов
    // МОЛЧА, поэтому по числу байтов неизвестный номер выглядел бы как «ничего не добавляет»,
    // то есть безопасным. Именно на этой ловушке наивная реализация была бы неверна.
    //
    // Второй вопрос — какие у номера байты. Ноль байтов у ИЗВЕСТНОГО номера остаётся законным
    // ответом: такой номер ничего не добавляет к ответу и поэтому не может разорвать символ.
    // Это нужно для знака конца ответа, который задаёт вызывающий и который обязан остаться
    // допустимым там, где он законен.
    internal bool TryGetBytes(int identifier, out byte[] bytes)
    {
        // Номер вне промежутка известных номеров: байтов за ним нет, и это отказ по признаку
        // промежутка, а не по числу байтов.
        if (identifier < 0 || identifier >= _bytesByIdentifier.Length)
        {
            // Пустой массив отдаётся только чтобы не оставлять переменную неназначенной;
            // решение принимает именно возвращённая ложь.
            bytes = [];
            return false;
        }

        // Номер известен: отдаются его байты, какими их держит снимок.
        bytes = _bytesByIdentifier[identifier];
        return true;
    }

    // Create строит снимок одним обходом словаря.
    //
    // Граница применимости названа прямо. Промежуток известных номеров берётся как «от нуля
    // до размера словаря», потому что строгий читатель сохранённого словаря требует
    // НЕПРЕРЫВНЫХ номеров. Для словаря с пропусками внутри промежутка понадобился бы
    // отдельный открытый вход «есть ли такой номер» на стороне словаря, то есть правка в
    // проекте 01.Tokenizer; здесь она не делается. Последствие пропуска названо честно: номер
    // из пропуска получил бы ноль байтов и был бы допущен как «ничего не добавляющий», то есть
    // потратил бы шаг, но разорвать символ не смог бы.
    internal static Utf8TokenByteSnapshot Create(BpeTokenizer tokenizer, CancellationToken cancellationToken)
    {
        // Словарь обязателен: без него допуск не знает байтов ни одного номера.
        ArgumentNullException.ThrowIfNull(tokenizer);

        // Размер словаря и задаёт промежуток законных номеров.
        var vocabularySize = tokenizer.VocabSize;
        // Пустой словарь означал бы, что допустимых кандидатов нет вовсе: это ошибка настройки.
        if (vocabularySize <= 0)
            throw new InvalidOperationException("TEXT_GENERATOR_UTF8_ADMISSION_VOCABULARY_EMPTY");

        // Удостоверение словаря снимается ОДИН раз, до обхода, чтобы снимок знал своего хозяина.
        var tokenizerStateSha256 = tokenizer.ComputeStateSha256();

        // Таблица байтов по номерам: место в массиве равно номеру токена.
        var bytesByIdentifier = new byte[vocabularySize][];
        // Общий счёт удержанных байтов — честная цена снимка в памяти.
        long retainedByteCount = 0;
        // Один список на весь обход: он переиспользуется, поэтому обход не создаёт список на номер.
        var singleIdentifier = new List<int> { 0 };

        for (int identifier = 0; identifier < vocabularySize; identifier++)
        {
            // Долгий обход большого словаря обязан слушать отмену, как и остальной генератор.
            cancellationToken.ThrowIfCancellationRequested();
            // Запрашиваемый номер подставляется в переиспользуемый список.
            singleIdentifier[0] = identifier;
            // Байты одного номера. Сборка байтов склеивает байты номеров по порядку и ничего
            // больше, поэтому байты одного номера здесь РАВНЫ тем, которые тот же номер даёт
            // внутри длинной последовательности, и возвращается всегда новый массив, то есть
            // снимок не ссылается на внутренние массивы словаря.
            var bytes = tokenizer.DecodeToBytes(singleIdentifier);
            // Байты запоминаются за своим номером.
            bytesByIdentifier[identifier] = bytes;
            // Цена снимка копится по факту, а не предполагается.
            retainedByteCount += bytes.Length;
        }

        // Готовый снимок неизменен: дальше он только отвечает на вопросы.
        return new Utf8TokenByteSnapshot(bytesByIdentifier, tokenizerStateSha256, retainedByteCount);
    }
}

// Состояние байтов ОТВЕТА: сколько байтов текущего символа ещё ожидается и какие значения
// законны следующими.
//
// Почему состояние ответа отдельно от подсказки. Законность считается по байтам ОТВЕТА:
// подсказка разбирается своим путём и своей проверкой номеров, а ответ начинается с чистого
// состояния. Иначе неполный конец подсказки молча разрешал бы начинать ответ с байта
// продолжения.
internal sealed class Utf8AnswerByteState
{
    // Сколько байтов продолжения ещё нужно текущему символу. Ноль означает, что ответ цел.
    private int _pendingContinuationBytes;
    // Нижняя граница законного значения следующего байта продолжения.
    private byte _nextContinuationLowerBound = 0x80;
    // Верхняя граница законного значения следующего байта продолжения.
    private byte _nextContinuationUpperBound = 0xBF;

    // Цел ли ответ прямо сейчас: на целом ответе его можно завершать.
    internal bool AnswerIsComplete => _pendingContinuationBytes == 0;

    // Сколько байтов текущего символа ещё ожидается — нужно для понятного доклада о состоянии.
    internal int PendingContinuationBytes => _pendingContinuationBytes;

    // Classify отвечает, чем кончится добавление ВСЕХ байтов кандидата, и при этом сам
    // состояние НЕ меняет: решение принимается до выбора, а менять состояние можно только
    // после того, как выбор действительно сделан.
    internal Utf8CandidateStatus Classify(byte[] candidateBytes)
        => Classify(candidateBytes, out _);

    // Та же проверка, но дополнительно отдаёт, СКОЛЬКО байтов символа осталось бы
    // недособранными. Это число нужно, чтобы решить, хватит ли оставшихся шагов ответа на
    // завершение символа: незаконченный префикс допустим только пока возможность завершить
    // ответ ещё есть.
    internal Utf8CandidateStatus Classify(byte[] candidateBytes, out int pendingAfterCandidate)
    {
        // Отсутствие массива байтов — ошибка вызывающего, а не свойство данных.
        ArgumentNullException.ThrowIfNull(candidateBytes);

        // Разбор идёт по КОПИЯМ полей, поэтому настоящее состояние ответа остаётся прежним.
        var pending = _pendingContinuationBytes;
        var lowerBound = _nextContinuationLowerBound;
        var upperBound = _nextContinuationUpperBound;

        foreach (var value in candidateBytes)
        {
            // Один байт продвигает разбор; ложь означает, что дальше последовательность незаконна.
            if (!Advance(ref pending, ref lowerBound, ref upperBound, value))
            {
                // На незаконной цепочке остаток не определён: решение принимает сам отказ.
                pendingAfterCandidate = 0;
                return Utf8CandidateStatus.Invalid;
            }
        }

        // Сколько байтов символа осталось бы недособранными после этого кандидата.
        pendingAfterCandidate = pending;

        // Ни одного недособранного символа не осталось — ответ можно завершать; иначе это
        // законное, но ещё не законченное продолжение.
        return pending == 0 ? Utf8CandidateStatus.ValidComplete : Utf8CandidateStatus.ValidPrefix;
    }

    // Append добавляет байты кандидата к состоянию ответа. Вызывается только после того, как
    // Classify признал кандидата годным, поэтому незаконный байт здесь — ошибка порядка вызовов.
    internal void Append(byte[] candidateBytes)
    {
        // Отсутствие массива байтов — ошибка вызывающего.
        ArgumentNullException.ThrowIfNull(candidateBytes);

        foreach (var value in candidateBytes)
        {
            // Тот же самый разбор, но уже по настоящим полям состояния.
            if (!Advance(ref _pendingContinuationBytes, ref _nextContinuationLowerBound,
                    ref _nextContinuationUpperBound, value))
                throw new InvalidOperationException("TEXT_GENERATOR_UTF8_ADMISSION_STATE_DESYNCHRONISED");
        }
    }

    // Advance продвигает разбор UTF-8 на ОДИН байт и говорит, законен ли он здесь.
    //
    // Как читается запись UTF-8, по-человечески. Первый байт символа говорит, сколько байтов
    // всего: ноль в старшем бите — один байт; биты 110 — два; биты 1110 — три; биты 11110 —
    // четыре. Остальные байты символа начинаются с битов 10 и сами по себе ничего не значат.
    //
    // Почему границы следующего байта хранятся, а не считаются общим правилом «от 0x80 до
    // 0xBF». Потому что общее правило пропустило бы записи, которых в UTF-8 не существует:
    // слишком длинную запись одного и того же знака, область слов-заменителей и знаки за
    // верхним пределом Unicode. Такие цепочки формально похожи на законные, но законным
    // текстом не являются, и допускать их нельзя. Поэтому для начальных байтов 0xE0, 0xED,
    // 0xF0 и 0xF4 границы следующего байта сужаются, а начальные байты 0xC0, 0xC1 и от 0xF5
    // отвергаются совсем.
    private static bool Advance(ref int pending, ref byte lowerBound, ref byte upperBound, byte value)
    {
        // Текущий символ ещё не дособран: сейчас законен ТОЛЬКО байт продолжения из нужных границ.
        if (pending > 0)
        {
            // Значение за пределами границ означает незаконную запись, а не другой символ.
            if (value < lowerBound || value > upperBound) return false;
            // Один ожидаемый байт получен.
            pending--;
            // Сужение границ действует только на первый байт продолжения; дальше обычные границы.
            lowerBound = 0x80;
            upperBound = 0xBF;
            return true;
        }

        // Однобайтовый знак: старший бит ноль, продолжения не требуется.
        if (value <= 0x7F) return true;

        // Байт продолжения там, где символ уже дособран: началом символа он быть не может.
        if (value <= 0xBF) return false;

        // Начальные байты 0xC0 и 0xC1 начинают только слишком длинную запись знака, которого в
        // законном тексте нет.
        if (value <= 0xC1) return false;

        // Двухбайтовый знак: ожидается один обычный байт продолжения.
        if (value <= 0xDF) { pending = 1; lowerBound = 0x80; upperBound = 0xBF; return true; }

        // Трёхбайтовый знак, начальный байт 0xE0: первый байт продолжения сужен снизу, иначе
        // запись была бы слишком длинной для своего знака.
        if (value == 0xE0) { pending = 2; lowerBound = 0xA0; upperBound = 0xBF; return true; }

        // Трёхбайтовый знак, начальные байты от 0xE1 до 0xEC: обычные границы продолжения.
        if (value <= 0xEC) { pending = 2; lowerBound = 0x80; upperBound = 0xBF; return true; }

        // Трёхбайтовый знак, начальный байт 0xED: первый байт продолжения сужен сверху, чтобы
        // в ответ не попала область слов-заменителей, которой в UTF-8 не существует.
        if (value == 0xED) { pending = 2; lowerBound = 0x80; upperBound = 0x9F; return true; }

        // Трёхбайтовый знак, начальные байты 0xEE и 0xEF: обычные границы продолжения.
        if (value <= 0xEF) { pending = 2; lowerBound = 0x80; upperBound = 0xBF; return true; }

        // Четырёхбайтовый знак, начальный байт 0xF0: первый байт продолжения сужен снизу.
        if (value == 0xF0) { pending = 3; lowerBound = 0x90; upperBound = 0xBF; return true; }

        // Четырёхбайтовый знак, начальные байты от 0xF1 до 0xF3: обычные границы продолжения.
        if (value <= 0xF3) { pending = 3; lowerBound = 0x80; upperBound = 0xBF; return true; }

        // Четырёхбайтовый знак, начальный байт 0xF4: первый байт продолжения сужен сверху,
        // чтобы не выйти за верхний предел Unicode.
        if (value == 0xF4) { pending = 3; lowerBound = 0x80; upperBound = 0x8F; return true; }

        // Начальные байты от 0xF5 и выше не начинают ни один существующий знак.
        return false;
    }
}

// Цена допуска, посчитанная по факту. Это диагностика: она ничего не решает и ни на один
// выбор не влияет, но позволяет назвать расход числом вместо «кажется, недорого».
internal sealed class Utf8AdmissionCost
{
    // Сколько раз строился снимок словаря за одно порождение. Обязан быть ровно один.
    internal int SnapshotBuilds { get; set; }
    // Сколько номеров обошло построение снимка.
    internal int SnapshotIdentifiersScanned { get; set; }
    // Сколько байтов словаря снимок удержал.
    internal long SnapshotRetainedBytes { get; set; }
    // Сколько шагов порождения строили маску допустимых кандидатов.
    internal int MaskBuilds { get; set; }
    // Сколько всего кандидатов опрошено за все шаги: главный множитель расхода.
    internal long CandidateClassifications { get; set; }
    // Сколько кандидатов оказалось исключено за все шаги.
    internal long MaskedCandidateTotal { get; set; }
    // Сколько шагов отдали выборщику ИСХОДНЫЙ вектор, потому что маска не исключила ничего.
    internal int StepsWithNothingExcluded { get; set; }
    // Сколько раз выборщик был вызван: по одному разу на шаг, как и прежде.
    internal int SamplerInvocations { get; set; }
    // Наименьшее число допущенных кандидатов среди всех шагов: доказательство конечности,
    // потому что ноль допущенных означал бы отказ, а не бесконечный цикл.
    internal int MinimumAdmittedCandidates { get; set; } = int.MaxValue;
}
