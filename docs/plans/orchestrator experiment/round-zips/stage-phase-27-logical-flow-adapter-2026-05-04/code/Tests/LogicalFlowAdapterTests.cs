using ExperimentsV2;
using ExperimentsV2.LogicalFlow;

namespace LlmFromScratch.Tests;

public sealed class LogicalFlowAdapterTests
{
    [Fact]
    public async Task T34LogicalFlowAdapter_MatchesDirectT34VerdictMetricsAndHumanResult()
    {
        // Build direct T34 evidence as the oracle.
        var direct = new T34PhaseTransitionProof().BuildEvidence();

        // Prove the direct oracle is available before comparing adapter behavior.
        Assert.True(direct.IsSuccess, direct.ErrorMessage);

        // Create the adapter that exposes T34 as a logical flow.
        var adapter = new T34LogicalFlowAdapter();

        // Build a request with default flags and the exact T34 scenario id.
        var request = BuildRequest(T34LogicalFlowAdapter.ScenarioId);

        // Execute through the logical-flow interface.
        var adapted = await adapter.ExecuteAsync(request);

        // The adapter must succeed through the shared operation envelope.
        Assert.True(adapted.IsSuccess, adapted.ErrorMessage);

        // The adapter verdict must match direct T34.
        Assert.Equal(direct.Value!.OverallVerdict, adapted.Value!.OverallVerdict);

        // The adapter final human result must match direct T34.
        Assert.Equal(direct.Value.FinalHumanResult, adapted.Value.FinalHumanResult);

        // The transition success metric must match direct T34.
        Assert.Equal(direct.Value.Metrics.TransitionSuccess.ToString(), adapted.Value.Metrics["transition_success"]);

        // The concern count must match direct T34.
        Assert.Equal(direct.Value.Metrics.ConcernCount.ToString(), adapted.Value.Metrics["concern_count"]);

        // The block count must match direct T34.
        Assert.Equal(direct.Value.Metrics.BlockCount.ToString(), adapted.Value.Metrics["block_count"]);
    }

    [Fact]
    public async Task T34LogicalFlowAdapter_RejectsUnknownScenario()
    {
        // Create the adapter under test.
        var adapter = new T34LogicalFlowAdapter();

        // Build a request with a scenario id that T34 does not prove.
        var request = BuildRequest("unknown-scenario");

        // Execute through the logical-flow interface.
        var result = await adapter.ExecuteAsync(request);

        // Unknown scenarios must fail cleanly instead of running the wrong flow.
        Assert.False(result.IsSuccess);

        // The failure must name the unsupported scenario.
        Assert.Contains("Unsupported scenario", result.ErrorMessage);
    }

    [Fact]
    public async Task T34LogicalFlowAdapter_RejectsUnknownFlowId()
    {
        // Create the adapter under test.
        var adapter = new T34LogicalFlowAdapter();

        // Build a request whose flow id does not match the adapter.
        var request = new LogicalFlowRequest<string>(
            "run-flow-adapter-test",
            "unknown-flow",
            T34LogicalFlowAdapter.ScenarioId,
            "run T34",
            new LogicalExecutionFlags(),
            new Dictionary<string, object>());

        // Execute through the logical-flow interface.
        var result = await adapter.ExecuteAsync(request);

        // Unknown flow ids must fail cleanly instead of running the wrong topology.
        Assert.False(result.IsSuccess);

        // The failure must name the unsupported flow.
        Assert.Contains("Unsupported flow", result.ErrorMessage);
    }

    [Fact]
    public async Task T34LogicalFlowAdapter_PreservesEvidenceIdentity()
    {
        // Create the adapter under test.
        var adapter = new T34LogicalFlowAdapter();

        // Execute the accepted T34 scenario through the adapter.
        var result = await adapter.ExecuteAsync(BuildRequest(T34LogicalFlowAdapter.ScenarioId));

        // The adapter must succeed before evidence ids are checked.
        Assert.True(result.IsSuccess, result.ErrorMessage);

        // The flow id must stay tied to the T34 experiment id.
        Assert.Equal(T34PhaseTransitionProof.Id, result.Value!.FlowId);

        // The scenario id must stay tied to the T34 scenario id.
        Assert.Equal(T34PhaseTransitionProof.ScenarioId, result.Value.ScenarioId);

        // Evidence ids must include the T34 run id generated by the wrapped proof.
        Assert.Single(result.Value.EvidenceIds);
    }

    [Fact]
    public async Task T34LogicalFlowAdapter_CanBeCancelled()
    {
        // Create the adapter under test.
        var adapter = new T34LogicalFlowAdapter();

        // Create a cancellation source that is already cancelled.
        using var cts = new CancellationTokenSource();

        // Cancel before execution so the adapter must return a cancellation failure.
        cts.Cancel();

        // Execute through the logical-flow interface.
        var result = await adapter.ExecuteAsync(BuildRequest(T34LogicalFlowAdapter.ScenarioId), cts.Token);

        // Cancelled flow execution must fail cleanly.
        Assert.False(result.IsSuccess);

        // The failure message must name cancellation.
        Assert.Contains("Cancelled", result.ErrorMessage);
    }

    private static LogicalFlowRequest<string> BuildRequest(string scenarioId)
    {
        // Build the standard request for the T34 logical-flow adapter.
        return new LogicalFlowRequest<string>(
            "run-flow-adapter-test",
            T34LogicalFlowAdapter.FlowId,
            scenarioId,
            "run T34",
            new LogicalExecutionFlags(),
            new Dictionary<string, object> { ["source"] = "phase27" });
    }
}
