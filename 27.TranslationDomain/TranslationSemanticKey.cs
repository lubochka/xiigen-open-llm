namespace TranslationDomain;

// Что это такое, по-человечески.
//
// У каждого выученного урока перевода есть рабочий ключ — строка структурного адреса вида
// "IMPERATIVE_V|ADD_OP|VALIDATE_CHECK". По этому ключу урок кладут в память при обучении и по
// нему же его ищут при обычном чтении. Ключ обязан зависеть ТОЛЬКО от смысла и структуры текста.
//
// Что было неправильно. Конструктор учебных партий в режиме точной пары приклеивал к ключу хвост
// с номером учебной пары, вида "<адрес>|PAIR:<номер пары>", и уже ПОСЛЕ этого добавлял проверенные
// грамматические пометки вида "|RULE:TENSE=PAST". Получалось, что номер пары сидел в середине
// рабочего ключа. Писатели складывали урок по ключу С номером, а читатели искали по ключу БЕЗ
// номера, потому что при обычном чтении номера взяться негде. Урок, записанный с номером,
// найти было нельзя никогда.
//
// Почему это плохо. Происхождение урока — это не смысл текста. Две одинаковые по смыслу строки из
// разных учебных пар получали разные ключи, а та же строка без урока — третий ключ. Кроме того
// наличие чужого номера в ключе само по себе уводило обычное направление в ветку без порога
// уверенности, то есть чужое происхождение фактически отменяло порог.
//
// Что стало. Рабочий ключ канонический: в нём нет ни одного отрезка происхождения. Происхождение
// урока живёт отдельным полем учебной строки. Этот вычислитель — единственное место, которое
// умеет убрать отрезок происхождения из ключа, и он нужен в двух случаях: конструктору партий,
// чтобы новый ключ собирался сразу каноническим, и загрузчику, чтобы ключи СТАРОЙ сохранённой
// контрольной точки привести к канонической форме при загрузке.
//
// Чего этот вычислитель НЕ делает. Он не выбирает слова, не хранит словарей и ничего не решает о
// переводе: он только вычисляет структурный адрес, как это требует запрет детерминизма в области
// перевода. Он не трогает ни один другой отрезок ключа и не меняет их порядок.
public static class TranslationSemanticKey
{
    // SchemaVersion называет форму рабочего ключа. Версия 1 — ключ мог нести отрезок
    // происхождения; версия 2 — ключ канонический, происхождение хранится отдельным полем.
    // Номер нужен загрузчику, чтобы отличить старую сохранённую память от новой.
    public const int SchemaVersion = 2;

    // LegacySchemaVersion называет прежнюю форму ключа: ту, в которой номер учебной пары
    // мог стоять внутри рабочего ключа.
    public const int LegacySchemaVersion = 1;

    // ProvenanceSegmentPrefix — начало отрезка происхождения внутри ключа.
    // Ровно этот отрезок и убирается; всё остальное остаётся на своих местах.
    public const string ProvenanceSegmentPrefix = "PAIR:";

    // SegmentSeparator — разделитель отрезков рабочего ключа.
    private const char SegmentSeparator = '|';

    // Canonicalize возвращает ключ без отрезков происхождения, сохраняя все остальные отрезки
    // в прежнем порядке. Отрезок происхождения убирается независимо от того, стоит он перед
    // грамматическими пометками или после них: наивная срезка "всё после номера пары" уничтожила
    // бы проверенные пометки, потому что конструктор партий добавляет их именно после номера.
    public static string Canonicalize(string? semanticKey)
    {
        // Пустой ключ канонизировать нечего: возвращается пустая строка, а не исключение.
        if (string.IsNullOrEmpty(semanticKey))
            return string.Empty;

        // Быстрый выход: в ключе нет ни одного отрезка происхождения, значит он уже канонический
        // и возвращается тем же экземпляром строки, без сборки заново.
        if (!CarriesProvenance(semanticKey))
            return semanticKey;

        // Ключ разбирается на отрезки по разделителю; пустые отрезки сохраняются, потому что
        // изменение их числа изменило бы адрес.
        var segments = semanticKey.Split(SegmentSeparator);

        // Остаются только отрезки, которые не являются происхождением; порядок прежний.
        var keptSegments = segments.Where(segment => !IsProvenanceSegment(segment));

        // Отрезки собираются обратно тем же разделителем: это и есть канонический ключ.
        return string.Join(SegmentSeparator, keptSegments);
    }

    // CarriesProvenance отвечает, несёт ли ключ хотя бы один отрезок происхождения.
    // Загрузчик по этому ответу понимает, что сохранённая память написана прежней формой ключа.
    public static bool CarriesProvenance(string? semanticKey)
    {
        // У пустого ключа происхождения нет.
        if (string.IsNullOrEmpty(semanticKey))
            return false;

        // Проверяется каждый отрезок целиком, а не подстрока: слово "PAIR:" внутри другого
        // отрезка не должно считаться происхождением.
        return semanticKey.Split(SegmentSeparator).Any(IsProvenanceSegment);
    }

    // ExtractProvenance возвращает номера учебных пар, найденные в прежней форме ключа, в том
    // порядке, в котором они стоят. Нужен загрузчику, чтобы при переносе старой памяти
    // происхождение не потерялось, а переехало в своё отдельное поле.
    public static IReadOnlyList<string> ExtractProvenance(string? semanticKey)
    {
        // У пустого ключа происхождения нет: возвращается пустой список.
        if (string.IsNullOrEmpty(semanticKey))
            return [];

        // Из каждого отрезка происхождения берётся то, что стоит после его начала.
        return semanticKey
            .Split(SegmentSeparator)
            .Where(IsProvenanceSegment)
            .Select(segment => segment[ProvenanceSegmentPrefix.Length..])
            .ToList();
    }

    // DeriveSchemaVersion выводит форму ключа ИЗ САМИХ ДАННЫХ, а не из заявки.
    //
    // Зачем это нужно. Объявить форму ключа можно неверно: строка со старым ключом, несущим
    // отрезок происхождения, легко помечается канонической. Поэтому единственная надёжная
    // величина — выведенная из содержимого ключа: есть отрезок происхождения, значит форма
    // прежняя; нет — каноническая. Заявленная версия сверяется с этой выведенной.
    public static int DeriveSchemaVersion(string? semanticKey)
        // Отрезок происхождения внутри ключа — признак прежней формы и ничего больше.
        => CarriesProvenance(semanticKey) ? LegacySchemaVersion : SchemaVersion;

    // Compose собирает рабочий ключ из канонического адреса: если на вход пришёл ключ прежней
    // формы, происхождение из него убирается. Это единственная точка входа для писателей,
    // чтобы ни один писатель не собирал ключ своим способом.
    public static string Compose(string? structuralAddress)
        // Сборка канонического ключа — это та же канонизация: других отличий между формами нет.
        => Canonicalize(structuralAddress);

    // IsProvenanceSegment отвечает, является ли ОДИН отрезок ключа отрезком происхождения.
    private static bool IsProvenanceSegment(string segment)
        // Сравнение точное по байтам: ключи в памяти сравниваются так же, поэтому регистр
        // здесь менять нельзя, иначе адрес записи и адрес чтения разойдутся снова.
        => segment.StartsWith(ProvenanceSegmentPrefix, StringComparison.Ordinal);
}
