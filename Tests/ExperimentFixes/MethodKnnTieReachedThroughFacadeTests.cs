// Приёмка того же переноса FIX-KNN-TIE-01, но через ОБЫЧНЫЙ ФАСАД, а не через
// предсказатель напрямую: «равные голоса соседей по методам разрешаются
// близостью» (строка очереди переносов `124-S08`, двадцать первая строка реестра
// исправлений по опытам, раздел обоснования пользы номер 75).
//
// Зачем нужен второй файл, если приёмка предсказателя уже принята. Соседний файл
// `MethodKnnTieIsResolvedByDistanceTests.cs` создаёт `MethodKnnPredictor` сам и
// задаёт ему число соседей. Он доказывает логику голоса, но НЕ доказывает, что до
// этой логики доходит боевая дорога. Карточка переноса требует именно второго:
// «Выполнить native targeted tests и обычный facade с достижением predictor».
// Этот файл закрывает вторую половину — тот же разрыв, но наблюдаемый там, где его
// увидит обычный потребитель: в поле `PredictedNextMethodType` результата обычной
// компиляции.
//
// Чем боевая дорога отличается от уже принятой проверки предсказателя:
//   - число соседей задаёт сам фасад, их ПЯТЬ, и здесь оно не подменяется
//     (`12.SemanticCompiler/SemanticCompilerFacade.cs`, строка 46);
//   - фасад отвечает только при включённом признаке, стеке C# и не менее ЧЕТЫРЁХ
//     обученных парах (там же, строка 370);
//   - запрос фасада — ПОСЛЕДНИЙ извлечённый метод исходника (`extracted.Value[^1]`,
//     строка 377), тогда как приёмка предсказателя берёт ПЕРВЫЙ;
//   - обучение идёт обычным входом `TrainMethodKnn`, а не прямым `Train`.
//
// НАХОДКА О ДОСТИЖИМОСТИ, обнаруженная первым прогоном этих проверок и сохранённая
// здесь, потому что она объясняет форму их входа. Четыре экзаменационных исходника
// панели восемьдесят пятого опыта, поданные в обычный фасад КАК ЕСТЬ, до предсказания
// метода не доходят вообще: обычная компиляция отбраковывает их гораздо раньше
// отказом `No predicates extracted`. Причина прочитана по живому коду: страж
// признаков `LogicExtractor.Extract` вызывается до предсказания
// (`SemanticCompilerFacade.cs`, строки 147–150), а `SemanticTokenizerPipeline`
// возвращает признаки дерева только при их числе не меньше четырёх и иначе отдаёт
// словесные токены, которые в таблицу признаков не отображаются
// (`Compression/SemanticTokenizerPipeline.cs`, строка 62). Поэтому каждый запрос
// здесь сопровождается ВЕДУЩИМ методом-носителем признака. Он стоит ПЕРВЫМ, а
// измеряемый панельный метод остаётся ПОСЛЕДНИМ, то есть именно он и попадает в
// запрос фасада. Что носитель не искажает измерение, проверка доказывает сама:
// набор признаков последнего метода сравнивается с набором признаков того же метода,
// извлечённого из исходного панельного исходника из одного метода.
//
// ВТОРАЯ НАХОДКА О ДОСТИЖИМОСТИ, обнаруженная вторым прогоном. Даже пройдя страж
// признаков, запрос всё равно получал ПУСТОЙ ответ. Причина прочитана по живому
// коду: предсказание метода выполняется только при стеке C#
// (`SemanticCompilerFacade.cs`, строка 370), а определитель стека в обычном фасаде
// не обучен и потому решает голосованием по ФИКСИРОВАННОМУ списку из семнадцати
// слов-примет (`Routing/StackDetector.cs`, набор примет и метод `PredictByMarkers`).
// Слов `class`, `void`, `int`, `if`, `return`, `for` в этом списке НЕТ, поэтому
// короткий панельный исходник опознаётся как `Generic`, и предсказание метода
// пропускается. Поэтому класс запроса объявлен словом `sealed` — это одна из
// семнадцати примет C#. Примета стоит в ОБЪЯВЛЕНИИ КЛАССА, а не в теле измеряемого
// метода, поэтому набор признаков метода она не меняет, и равенство наборов
// по-прежнему доказывается проверкой.
//
// ГРАНИЦА СРАВНЕНИЯ ПРИЗНАКОВ (дописано 10.11.2026 при ремонте улик слайса). Равенство
// наборов признаков голой и достижимой форм (`LastMethodFeatures`) считается на СЫРОМ
// тексте запроса: оба набора извлекаются вызовом `MethodExtractor.Extract` на исходнике
// как есть. Боевой фасад извлекает методы из НОРМАЛИЗОВАННОГО текста: обычная
// компиляция сначала прогоняет исходник через `RegexPreprocessor.Normalize`, когда
// признак предобработки включён и стек определён как C#
// (`12.SemanticCompiler/SemanticCompilerFacade.cs`, строки 132–135), а нормализация
// вырезает XML-документацию, блочные и строчные комментарии, строковые литералы и
// лишние пустые строки (`12.SemanticCompiler/RegexPreprocessor.cs`, строки 16–30).
// Для входов этого файла разницы нет: ни в одном из восьми текстов запросов (четыре
// голые формы и четыре достижимые) нет ни комментариев, ни строковых литералов, ни
// пустых строк, поэтому нормализованный текст совпадает с сырым и извлечённые методы
// те же. Но утверждение проверки ЭТОГО НЕ ДОКАЗЫВАЕТ: оно не вызывает нормализацию и
// не сравнивает признаки метода до и после неё. Попади в запрос комментарий или
// строковый литерал, фасад измерял бы метод, извлечённый из другого текста, чем тот,
// на котором проверка считает признаки, и равенство наборов этого бы не заметило.
//
// Эталоны не придуманы и не взяты из вывода продукта. Четыре обучающих текста и
// четыре запроса с метками `Guard`, `Guard`, `Loop`, `Loop` перенесены дословно из
// уже принятой приёмки предсказателя, которая в свою очередь взяла их из
// замороженного хозяина восемьдесят пятого опыта. Правка после первого красного
// прогона коснулась ТОЛЬКО входа, ни один ожидаемый ответ не изменён; основание и
// запись старого/нового ожидания — в файле ожиданий
// `artifacts/fbe/FIX-R21/attempt-0001/expectation-before-run.md`.
//
// ЧЕГО ЭТА ПРИЁМКА НЕ ДОКАЗЫВАЕТ. Отложенной выборки здесь нет: четыре запроса и
// четыре обученные пары — это панель опыта, а не отложенный набор. Контрольной
// точки нет. Абляции нет. Свежей загрузки нет. Продолжения обучения из сохранённого
// состояния нет. Качество обучения не измерено ни одним числом. Вес голоса по
// расстоянию не вводится и не проверяется — это отдельная непроверенная гипотеза.
// Состав и число соседей не проверяются и не меняются. Доказано ровно одно: на
// боевой дороге обычного фасада ровный голос разрешается расстоянием, а
// неровный по-прежнему решается числом голосов.

namespace LlmFromScratch.Tests.ExperimentFixes;

using System.Reflection;
using SemanticCompiler;
using SemanticCompiler.Prediction;

public sealed class MethodKnnTieReachedThroughFacadeTests
{
    // Четыре обучающих текста боевой панели восемьдесят пятого опыта, дословно из
    // уже принятой приёмки предсказателя. Каждый файл даёт ровно одну пару
    // «метод — следующий метод», поэтому на четырёх файлах выходит четыре пары.
    private const string TrainGuardAsync =
        "class GA{void A(int x){if(x<0)return;} async System.Threading.Tasks.Task B(int x){if(x<0)return;await System.Threading.Tasks.Task.Delay(1);}}";
    private const string TrainLoop =
        "class LP{void A(){for(int i=0;i<2;i++){}} void B(){for(int i=0;i<3;i++){}}}";
    private const string TrainErrorHandling =
        "class EH{void A(int x){try{}catch{}} void B(int x){try{}catch{}}}";
    private const string TrainSimple =
        "class SP{void A(){int a=1;} void B(){int b=2;}}";

    // Метка, которая идёт ПЕРВОЙ по алфавиту среди меток этой панели. До переноса
    // ровный голос отдавал ответ именно ей — здесь она служит отрицательным
    // ориентиром: ни один запрос панели не должен её получить.
    private const string LabelThatWonBeforeTheFix = "ErrorHandling";

    // Четыре экзаменационных запроса панели. У каждого две формы одного и того же
    // измеряемого метода: голая панельная форма — эталон признаков, и достижимая
    // форма с ведущим методом-носителем признака — то, что реально подаётся фасаду.
    private static (string Name, string Bare, string Reachable, string Gold)[] ExamQueries() =>
    [
        ("guard-0",
            "class Q{void Q1(int n){if(n<0)return;}}",
            "sealed class Q{void Carrier(string probe){if (probe == null) { return; }} void Q1(int n){if(n<0)return;}}",
            "Guard"),
        ("guard-1",
            "class Q{void Q2(int n){if(n<1)return;}}",
            "sealed class Q{void Carrier(string probe){if (probe == null) { return; }} void Q2(int n){if(n<1)return;}}",
            "Guard"),
        ("loop-0",
            "class Q{void Q3(){for(int j=0;j<4;j++){}}}",
            "sealed class Q{void Carrier(string probe){if (probe == null) { return; }} void Q3(){for(int j=0;j<4;j++){}}}",
            "Loop"),
        ("loop-1",
            "class Q{void Q4(){for(int j=1;j<5;j++){}}}",
            "sealed class Q{void Carrier(string probe){if (probe == null) { return; }} void Q4(){for(int j=1;j<5;j++){}}}",
            "Loop")
    ];

    // Обучающая панель с РОВНЫМ голосом: четыре файла дают четыре пары с четырьмя
    // РАЗНЫМИ метками, поэтому у каждой метки ровно один голос при пяти соседях.
    private static IReadOnlyList<string> TiedVotePanel() =>
        [TrainGuardAsync, TrainLoop, TrainErrorHandling, TrainSimple];

    // Обучающая панель с НЕРОВНЫМ голосом, собранная из той же панели: текст про
    // цикл подан дважды, поэтому метка цикла получает ДВА голоса против одного у
    // охраны и одного у обработки ошибок. Ничьей здесь нет вовсе.
    private static IReadOnlyList<string> UntiedMajorityPanel() =>
        [TrainLoop, TrainLoop, TrainGuardAsync, TrainErrorHandling];

    // Обычный фасад боевой дороги: конструктор без аргументов, то есть признак
    // включения методного предсказателя по умолчанию истинен, а число соседей
    // остаётся фасадным (пять). Свой предсказатель сюда НЕ подаётся намеренно.
    private static SemanticCompilerFacade TrainedOrdinaryFacade(IReadOnlyList<string> panel)
    {
        // Фасад создаётся ровно так, как его создаёт боевой потребитель.
        var facade = new SemanticCompilerFacade();

        // Обучение идёт обычным входом фасада, а не прямым вызовом предсказателя.
        facade.TrainMethodKnn(panel);

        // Готовый обученный фасад возвращается вызывающей проверке.
        return facade;
    }

    // Ответ обычной компиляции на один исходник: то самое поле, которое видит
    // обычный потребитель результата компиляции.
    private static string? FacadeAnswer(SemanticCompilerFacade facade, string source)
    {
        // Вызывается обычная полная компиляция, а не внутренний метод предсказания.
        var compiled = facade.Compile(source);

        // Компиляция обязана завершиться успехом: иначе ответа просто нет и
        // дальнейшее сравнение меток было бы сравнением с пустотой.
        Assert.True(compiled.IsSuccess, compiled.ErrorMessage);

        // Отдаётся предсказанная категория следующего метода — наблюдаемый выход.
        return compiled.Value!.PredictedNextMethodType;
    }

    // Обученность предсказателя, живущего ВНУТРИ фасада. Читается отражением тем же
    // приёмом, что и в существующей проверке признаков включения
    // (`Tests/E13E14FeatureFlagTests.cs`, вспомогательный метод чтения поля).
    // Нужно, чтобы пустой ответ фасада нельзя было спутать с необученностью.
    private static int FacadeTrainedPairs(SemanticCompilerFacade facade)
    {
        // Находится закрытое поле фасада, в котором лежит его собственный предсказатель.
        var field = facade.GetType().GetField("_methodKnn", BindingFlags.Instance | BindingFlags.NonPublic);

        // Поле обязано существовать: иначе оснастка проверки смотрит не туда.
        Assert.NotNull(field);

        // Значение поля приводится к типу методного предсказателя.
        var predictor = Assert.IsType<MethodKnnPredictor>(field.GetValue(facade));

        // Возвращается число обученных пар этого предсказателя.
        return predictor.TrainingSize;
    }

    // Набор структурных признаков ПОСЛЕДНЕГО метода исходника: ровно тот метод,
    // который обычный фасад берёт в запрос.
    private static HashSet<string> LastMethodFeatures(string source)
    {
        // Методы исходника извлекаются тем же извлекателем, которым их берёт фасад.
        var extracted = MethodExtractor.Extract(source);

        // Извлечение обязано удаться, иначе запрос не доходит до предсказателя.
        Assert.True(extracted.IsSuccess, extracted.ErrorMessage);

        // Возвращается набор признаков последнего метода в порядке объявления.
        return extracted.Value![^1].KindBag;
    }

    // Независимый оракул «какая метка у БЛИЖАЙШЕЙ пары»: предсказатель с ОДНИМ
    // соседом. При одном соседе ровного голоса не бывает вовсе, поэтому его ответ
    // по построению принадлежит ближайшей паре. Этот предсказатель НЕ подаётся в
    // фасад и в боевой дороге не участвует — он только оснастка проверки.
    private static string NearestPairLabel(IReadOnlyList<string> panel, string querySource)
    {
        // Методы панели собираются тем же правилом нумерации файлов, каким их
        // собирает обычный вход фасада: номер файла равен его позиции в списке.
        var methods = new List<PackedMethod>();

        // Номер файла растёт вместе с позицией исходника в панели.
        short fileId = 0;

        // Перебираются все тексты панели в их исходном порядке.
        foreach (var source in panel)
        {
            // Из каждого текста извлекаются его методы с его собственным номером.
            var extracted = MethodExtractor.Extract(source, fileId++);

            // Извлечение обязано удаться: иначе оснастка проверки недостоверна.
            Assert.True(extracted.IsSuccess, extracted.ErrorMessage);

            // Извлечённые методы добавляются в общий список в том же порядке.
            methods.AddRange(extracted.Value!);
        }

        // Создаётся оракул ровно с одним соседом.
        var oracle = new MethodKnnPredictor(k: 1);

        // Оракул обучается на тех же парах, что и боевой фасад.
        oracle.Train(methods);

        // Запрос берётся так же, как его берёт фасад: последний метод исходника.
        var queryMethods = MethodExtractor.Extract(querySource, fileId: 99);

        // Извлечение запроса обязано удаться по той же причине.
        Assert.True(queryMethods.IsSuccess, queryMethods.ErrorMessage);

        // Возвращается метка ближайшей обученной пары.
        return oracle.Predict(queryMethods.Value![^1]);
    }

    [Fact]
    public void ThroughOrdinaryFacade_ThePredictorIsActuallyReached()
    {
        // Этот случай доказывает ДОСТИЖИМОСТЬ: без него два следующих случая
        // могли бы «проходить» на пустом ответе, ничего не проверив. Он же
        // доказывает, что метод-носитель признака не искажает измерение.
        var facade = TrainedOrdinaryFacade(TiedVotePanel());

        // Обученность фасада ровно та, при которой боевой маршрут уже отвечает:
        // четыре пары — это и есть его порог ответа.
        Assert.Equal(4, FacadeTrainedPairs(facade));

        // Известные категории метода, которые умеет возвращать голос.
        var knownLabels = new[] { "Guard", "Loop", "Simple", "Mixed", "ErrorHandling", "Async" };

        // Проверяется каждый из четырёх экзаменационных запросов панели.
        foreach (var exam in ExamQueries())
        {
            // Голая панельная форма содержит ровно один метод — измеряемый.
            Assert.Single(MethodExtractor.Extract(exam.Bare).Value!);

            // Достижимая форма содержит два метода: носитель признака и измеряемый.
            Assert.Equal(2, MethodExtractor.Extract(exam.Reachable).Value!.Count);

            // Главное доказательство неискажённости: набор признаков последнего
            // метода достижимой формы совпадает с набором признаков единственного
            // метода голой панельной формы. Значит измеряется тот же метод с теми
            // же признаками, а расстояния до обученных пар не изменились.
            Assert.Equal(LastMethodFeatures(exam.Bare), LastMethodFeatures(exam.Reachable));

            // Фасад спрашивается обычной компиляцией на достижимой форме.
            var answer = FacadeAnswer(facade, exam.Reachable);

            // Ответ не пуст: признак включён, стек распознан как C#, обученность
            // достаточна — то есть боевая дорога действительно дошла до голоса.
            Assert.NotNull(answer);

            // Ответ принадлежит известному набору категорий, а не произвольной строке.
            Assert.Contains(answer, knownLabels);
        }
    }

    [Fact]
    public void ThroughOrdinaryFacade_EachExamQueryGetsItsNearestPairLabel()
    {
        // ПОЛОЖИТЕЛЬНЫЙ СЛУЧАЙ и единственный, который обязан покраснеть при
        // удалении правила близости. На этой панели голос РОВНЫЙ: по одному голосу
        // на метку при пяти соседях. До переноса побеждала первая по алфавиту метка,
        // и все четыре запроса получали `ErrorHandling`, хотя ближайшая пара у них
        // разная. После переноса при равных голосах выше та группа, в которой есть
        // сосед ближе к запросу.
        var facade = TrainedOrdinaryFacade(TiedVotePanel());

        // Проверяются все четыре экзаменационных запроса панели.
        foreach (var exam in ExamQueries())
        {
            // Ответ читается с боевой дороги обычного фасада.
            var answer = FacadeAnswer(facade, exam.Reachable);

            // Ответ равен эталонной метке ближайшей пары, а не первой по алфавиту.
            Assert.Equal(exam.Gold, answer);

            // То же утверждение с другой стороны: метка, побеждавшая до переноса
            // из-за написания имени, не должна достаться ни одному запросу панели.
            Assert.NotEqual(LabelThatWonBeforeTheFix, answer);
        }
    }

    [Fact]
    public void ThroughOrdinaryFacade_AnUntiedMajorityStillOutranksTheNearestNeighbour()
    {
        // КОНТРОЛЬНЫЙ (ОТРИЦАТЕЛЬНЫЙ) СЛУЧАЙ: «не ломает законное». Близость —
        // это разрешение НИЧЬЕЙ, а не новая власть над числом голосов. Если бы
        // перенос сделал расстояние главнее голосов, ответ здесь сменился бы с
        // метки большинства на метку ближайшего соседа. Этот случай обязан
        // оставаться зелёным и до переноса, и после него, и под мутацией продукта.
        var panel = UntiedMajorityPanel();

        // Берётся первый экзаменационный запрос: его ближайшая пара несёт охрану.
        var query = ExamQueries()[0];

        // Независимый оракул с одним соседом называет метку ближайшей пары.
        var nearestLabel = NearestPairLabel(panel, query.Reachable);

        // Сначала убеждаемся, что оснастка действительно про расхождение: ближайшая
        // пара несёт охрану, а большинством на этой панели владеет цикл. Без этой
        // проверки случай мог бы проходить по случайной причине.
        Assert.Equal("Guard", nearestLabel);

        // Тот же запрос задаётся обычному фасаду на панели с неровным голосом.
        var answer = FacadeAnswer(TrainedOrdinaryFacade(panel), query.Reachable);

        // Побеждает метка БОЛЬШИНСТВА, у неё два голоса против одного.
        Assert.Equal("Loop", answer);

        // И это НЕ метка ближайшего соседа: порядок правил механизма сохранён —
        // сначала число голосов, и только при их равенстве расстояние.
        Assert.NotEqual(nearestLabel, answer);
    }
