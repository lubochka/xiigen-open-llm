// Постоянное покрытие правки FIX-RF05 — ранний типизированный отказ в обученной
// перегрузке классификатора маршрута проекта 29. Источник наряда — пятая строка
// очереди адресных ремонтов (файл плана «108. Адресный план ремонта после
// проверки переносов», 1 ноября 2026), её первая малая правка.
//
// Что здесь проверяется по-человечески. Классификатор маршрута решает, к какой
// из пяти тем относится запрос, и делает это по набору числовых признаков:
// находит самые похожие выученные уроки и голосует их темами. Вопрос простой —
// что он отвечает, когда признаков во входе НЕТ ни одного.
//
// Что было сломано. Проверка стояла ровно одна: обучен ли классификатор. Запрос
// без признаков уходил прямо в поиск соседей, а мера несходства даёт пустому
// запросу РОВНО ЕДИНИЦУ до каждого урока: общих признаков ноль, объединение
// равно размеру урока. Все расстояния получались равными, упорядочивание в этой
// среде устойчиво, поэтому отбор брал первые уложенные строки памяти и
// голосование возвращало тему ПЕРВОГО уложенного урока. И возвращало её как
// УСПЕХ — без единого признака того, что решение ни на чём не основано. На
// фактических продуктовых уроках это измерено: ответом был «ошибка» (BUG),
// просто потому что урок про ошибку уложен первым. Отсутствующий массив вместо
// этого бросал исключение из построения набора, что нарушает первое правило
// проекта: для бизнес-логики не бросать, а возвращать отказ.
//
// Что стало. Отказ с названным кодом «нет свидетельства для решения» выдаётся
// ДО поиска соседей, и отсутствующий массив получает тот же отказ вместо
// исключения.
//
// ВТОРАЯ ПОЛОВИНА, добавлена 1 ноября 2026 тем же нарядом владельца. Тот же
// отказ выдаётся и при нулевом сходстве: когда ЛУЧШЕЕ, то есть наименьшее,
// расстояние равно единице — ни один выученный урок не разделяет с запросом ни
// одного признака. Это продуктово достижимая половина того же дефекта: пустой и
// отсутствующий профиль потребитель отсекает сам своей охраной непустого
// профиля, а запрос с неизвестными признаками эту охрану проходит. Единица здесь
// не подобранный порог, а определение пустого пересечения, и выше единицы мера
// не бывает; общий порог близости остаётся отдельной неизмеренной работой.
// Сравнивается именно наименьшее расстояние: если сравнивать первое, отказ
// сработает ошибочно на запросе, чей первый урок просто не пересекается.
//
// Почему порядок двух проверок здесь отдельно закреплён. Необученность
// проверяется первой, как и раньше. Если поменять порядок, необученный
// классификатор с пустым запросом начнёт отвечать новым кодом вместо прежнего
// «не обучен», то есть правка молча изменит уже принятый ответ. Отдельный случай
// проверки ниже это стережёт.
//
// Чего это покрытие НЕ доказывает, и почему именно так.
// Первое: третий случай той же правки — два набора без признаков, которым мера
// прежде давала расстояние ноль, то есть идеальное совпадение, — здесь проверить
// НЕЛЬЗЯ. Мера закрытая, а после раннего отказа этот случай из обученной
// перегрузки недостижим вовсе. Он доказан проверяемой программой рядом
// (`oracle-route-classifier-no-evidence.ps1`, панель 2), и это сказано прямо, а
// не умолчано.
// Второе: остаток, который правка НЕ чинит, здесь сознательно НЕ закрепляется
// утверждением. Запрос с признаками, ни один из которых не встречается ни в
// одном уроке, даёт те же равные расстояния и ту же тему первого урока.
// Закрепить это утверждением значило бы объявить сломанный инвариант
// правильным, что правилами проекта запрещено. Факт измерен проверяемой
// программой (панель 7) и записан отдельной строкой работ в реестре.
// Третье: это починка распознавания на границе узла. Качество маршрутизации на
// живом корпусе, время и память здесь не измеряются.
// Четвёртое, про вторую половину: цена этой правки измеряется НЕ здесь. Вторая
// половина меняет продуктовый ответ, поэтому во что именно превращается отказ —
// какая ветвь детерминированной цепочки потребителя срабатывает, какая получается
// тема, уверенность и доводы — измерено второй проверяемой программой
// (`oracle-route-classifier-zero-similarity.ps1`, панель 3) с дословным переносом
// цепочки потребителя. Здесь закреплён только отказ самого классификатора.
// Пятое: контрольная панель ниже показывает, что ответ на запросе с пересечением
// не изменился, но она НЕ доказывает, что этот ответ осмыслен. Измерено во второй
// проверяемой программе: при пяти соседях и семи уроках голос не взвешен по
// расстоянию, поэтому семь запросов из девяти контрольных получают одну и ту же
// тему «ошибка», включая запросы, дословно равные урокам других тем. Это отдельное
// семейство дефектов, правкой не затронутое.

using SemanticCompiler29;

namespace LlmFromScratch.Tests.ExperimentFixes;

public sealed class RouteClassifierNoEvidenceRefusalTests
{
    // Код отказа, назначенный нарядом: решение не на чем основать.
    private const string NoEvidenceCode = "NO_EVIDENCE_FOR_DECISION";

    // Прежний код отказа необученного классификатора: он обязан сохраниться.
    private const string NotTrainedCode = "NOT_TRAINED";

    // Число соседей продуктового пути: столько ставит оболочка совместимости
    // проекта 12 по умолчанию (12.SemanticCompiler/Routing/RouteClassifier.cs,
    // строка 15), а единица классификации темы проекта 23 создаёт её без довода.
    private const int ProductionNeighbours = 5;

    // ГЛАВНЫЙ СЛУЧАЙ. Запрос без признаков обязан получить названный отказ, а не
    // тему первого уложенного урока. На прежнем правиле здесь был успех с темой
    // «ошибка».
    [Fact]
    public void EmptyProfile_GetsNamedRefusal_NotTheLabelOfTheFirstLesson()
    {
        // Классификатор с продуктовым числом соседей и фактическими продуктовыми уроками.
        var classifier = TrainedOnSeededLessons();

        // Чтение ответа на запросе, у которого нет ни одного признака. Тип
        // массива назван явно: у классификатора есть вторая перегрузка по
        // строковым словам, и пустой набор без типа был бы неоднозначен.
        var answer = classifier.Classify(Array.Empty<int>());

        // Ожидания выписаны буквально: именно отказ и именно с назначенным кодом.
        Assert.False(answer.IsSuccess, "Запрос без признаков не должен давать успешный ответ.");
        Assert.Equal(NoEvidenceCode, answer.ErrorCode);
    }

    // ВТОРОЙ СЛУЧАЙ ПРАВКИ. Отсутствующий массив признаков обязан получить тот же
    // отказ, а не бросить исключение: правило проекта запрещает бросать для
    // бизнес-логики.
    [Fact]
    public void MissingProfile_GetsNamedRefusal_InsteadOfThrowing()
    {
        // Тот же обученный классификатор.
        var classifier = TrainedOnSeededLessons();

        // Чтение ответа на отсутствующем массиве признаков; тип назван явно по
        // той же причине — иначе отсутствующее значение подошло бы обеим
        // перегрузкам.
        var answer = classifier.Classify((int[])null!);

        // Ожидания выписаны буквально: отказ с тем же кодом, без исключения.
        Assert.False(answer.IsSuccess, "Отсутствующий массив признаков не должен давать успешный ответ.");
        Assert.Equal(NoEvidenceCode, answer.ErrorCode);
    }

    // КОНТРОЛЬ ПОРЯДКА ПРОВЕРОК. Необученный классификатор обязан отвечать
    // прежним кодом «не обучен» даже на пустом запросе: если порядок двух
    // проверок поменять, этот случай упадёт.
    [Theory]
    [InlineData(true)]
    [InlineData(false)]
    public void UntrainedClassifier_KeepsTheOldNotTrainedCode(bool emptyInsteadOfMissing)
    {
        // Классификатор без единого урока.
        var classifier = NewClassifier(ProductionNeighbours);

        // Оба негодных входа задаются одним случаем проверки: пустой и
        // отсутствующий. Тип массива назван явно у обеих ветвей выбора.
        var answer = classifier.Classify(emptyInsteadOfMissing ? Array.Empty<int>() : (int[])null!);

        // Ожидание выписано буквально: прежний код, а не новый.
        Assert.False(answer.IsSuccess);
        Assert.Equal(NotTrainedCode, answer.ErrorCode);
    }

    // ГЛАВНЫЙ СЛУЧАЙ ВТОРОЙ ПОЛОВИНЫ. Запрос с признаками, которых нет ни в одном
    // уроке, обязан получить тот же названный отказ. На прежнем правиле здесь был
    // успех с темой «ошибка» — темой первого уложенного урока.
    [Theory]
    [InlineData(6)]
    [InlineData(11)]
    [InlineData(20)]
    public void ProfileWithoutAnySharedFeature_GetsNamedRefusal(int unknownSlot)
    {
        // Тот же обученный классификатор на фактических продуктовых уроках.
        var classifier = TrainedOnSeededLessons();

        // Признак, которого нет ни в одном из семи уроков: пересечение пусто.
        var answer = classifier.Classify(new[] { unknownSlot });

        // Ожидания выписаны буквально: отказ и тот же назначенный код.
        Assert.False(answer.IsSuccess, "Запрос без общих признаков не должен давать успешный ответ.");
        Assert.Equal(NoEvidenceCode, answer.ErrorCode);
    }

    // КОНТРОЛЬ ЛУЧШЕГО, А НЕ ПЕРВОГО РАССТОЯНИЯ. У этого запроса первый урок
    // памяти не разделяет ни одного признака, а шестой разделяет все три. Если
    // сравнивать первое расстояние вместо наименьшего, здесь будет ошибочный
    // отказ — именно этот случай стережёт выбор «лучшее расстояние».
    [Fact]
    public void ProfileSharingFeaturesOnlyWithALaterLesson_StillAnswers()
    {
        // Тот же обученный классификатор.
        var classifier = TrainedOnSeededLessons();

        // Набор признаков шестого урока: первый урок с ним не пересекается.
        var answer = classifier.Classify(new[] { 12, 13, 14 });

        // Ожидание выписано буквально: это успех, а не отказ.
        Assert.True(answer.IsSuccess, $"Запрос с общими признаками не должен отказывать, код отказа «{answer.ErrorCode}».");
    }

    // КОНТРОЛЬ НЕТРОНУТОГО ПУТИ. Запрос, у которого есть общий признак с
    // выученным уроком, обязан отвечать ровно как до правки. Если бы ранний отказ
    // задел годный вход, этот случай упал бы.
    [Fact]
    public void ProfileWithOverlap_AnswersExactlyAsBefore()
    {
        // Тот же обученный классификатор.
        var classifier = TrainedOnSeededLessons();

        // Запрос совпадает с признаками второго продуктового урока про ошибку;
        // тип массива назван явно, как и в остальных случаях этого файла.
        var answer = classifier.Classify(new[] { 1 });

        // Ожидание выписано буквально, а не взято из самого же ответа.
        Assert.True(answer.IsSuccess, $"Годный запрос не должен отказывать, код отказа «{answer.ErrorCode}».");
        Assert.Equal(Domain.BUG, answer.Value);
    }

    // ДОСТИЖИМОСТЬ ПРАВКИ ДО ЕДИНСТВЕННОГО ВЫЗЫВАЮЩЕГО. Обученную перегрузку во
    // всём хранилище вызывает ровно одна сторона — оболочка совместимости проекта
    // 12 (её строка 35), и она переносит код отказа как есть. Этот случай
    // проверяет, что новый отказ действительно виден вызывающему, а не теряется
    // на границе двух проектов.
    [Fact]
    public void CompatibilityWrapper_PassesTheNamedRefusalThrough()
    {
        // Оболочка совместимости создаёт канонический классификатор сама.
        var wrapper = new SemanticCompiler.RouteClassifier(k: ProductionNeighbours);

        // Те же фактические продуктовые уроки передаются канону через оболочку.
        wrapper.Train(SeededLessons());

        // Чтение ответа оболочки на запросе без признаков. У оболочки вторая
        // перегрузка по словам отсутствует, но тип назван явно для единообразия.
        var answer = wrapper.Classify(Array.Empty<int>());

        // Ожидания выписаны буквально: отказ и тот же код, что у канона.
        Assert.False(answer.IsSuccess, "Оболочка не должна превращать отказ канона в успех.");
        Assert.Equal(NoEvidenceCode, answer.ErrorCode);
    }

    // Фактические уроки, которыми продукт засевает этот классификатор. Источник —
    // 21.AgentInfrastructure/Logical/PromptDomainClassifier.cs, строки 79-87.
    // Порядок строк важен: именно он определял, чья тема выдавалась на пустом
    // запросе до правки, поэтому он сохранён дословно.
    private static IReadOnlyList<(int[] Predicates, Domain Domain)> SeededLessons() =>
    [
        (new[] { 0, 1, 2 }, Domain.BUG),
        (new[] { 1 }, Domain.BUG),
        (new[] { 5, 8, 9, 10, 19 }, Domain.PLAN),
        (new[] { 0, 2 }, Domain.ARCH),
        (new[] { 0, 2, 3, 4, 21 }, Domain.ARCH),
        (new[] { 12, 13, 14 }, Domain.CODE_Q),
        (new[] { 5, 7 }, Domain.REFACTOR)
    ];

    // Канонический классификатор, обученный фактическими продуктовыми уроками.
    private static RouteClassifier TrainedOnSeededLessons()
    {
        // Классификатор с продуктовым числом соседей.
        var classifier = NewClassifier(ProductionNeighbours);

        // Приём партии: обучение здесь настоящее, а не подмена поля памяти.
        classifier.Train(SeededLessons());

        return classifier;
    }

    // Сборка канонического классификатора с пустыми хранилищем и журналом:
    // проверке нужен только ответ, сохранять и записывать нечего.
    private static RouteClassifier NewClassifier(int k) =>
        new(new NoopCompilerStorage(), new NoopCompilerEventLogger(), k);

    // Пустое хранилище: классификатору оно нужно по общему устройству служб
    // проекта, ни одна проверка здесь ничего не сохраняет.
    private sealed class NoopCompilerStorage : ICompilerStorage
    {
        // Сохранение ничего не делает: проверке нечего хранить между вызовами.
        public void Save(string key, PipelineOutput output)
        {
        }

        // Чтение всегда отвечает «ничего нет»: сохранений не было.
        public PipelineOutput? Load(string key) => null;
    }

    // Пустой журнал событий: проверке не нужны записи аудита.
    private sealed class NoopCompilerEventLogger : ICompilerEventLogger
    {
        // Запись события ничего не делает.
        public void Log(StandardEvent evt)
        {
        }
    }
}
