// Приёмка кандидата 3 девяносто девятого опыта: обычная ветвь генерации больше
// не выдумывает признак конца ответа из последней записи обученного словаря.
//
// ЭТОТ ФАЙЛ ПОДГОТОВЛЕН ЗАРАНЕЕ И НА НЫНЕШНЕМ КОДЕ ПАДАЕТ НАМЕРЕННО. Правка
// самого генератора ждёт освобождения файла: `09.Inference/TextGenerator.cs` и
// `01.Tokenizer/BpeTokenizer.cs` входят в опись измеряющего опыта, и правка
// посреди него лишила бы опыт доказательства неизменности источников.
//
// Что неверно сейчас. Признак конца ответа в словаре не выделен, а взят как
// ПОСЛЕДНЯЯ ЗАПИСЬ обученного словаря (`BpeTokenizer.EosToken` возвращает
// размер словаря минус один). Обычная ветвь генератора берёт признак именно
// оттуда, тогда как подробная берёт заданный вызывающим и проверенный. Поэтому
// когда модель выдаёт тот кусок слова, чей номер случайно оказался последним,
// обычная ветвь обрывает ответ.
//
// Точная граница вреда, измеренная и названная прямо, потому что первая оценка
// исполнителя была ШИРЕ действительной. Обычные перегрузки возвращают только
// текст: причина остановки у них вычисляется и ВЫБРАСЫВАЕТСЯ. Значит обычному
// вызывающему никто не говорит «модель закончила» — ему отдают более короткую
// строку и не сообщают причины вовсе. Это молчаливый обрыв, а не ложное
// объяснение. Ложное объяснение было бы хуже, но его на этом пути нет: причина
// «конец ответа» возвращается только подробными перегрузками, а там признак
// задан вызывающим и проверен, то есть она правдива. Поэтому приёмка ниже
// проверяет ТЕКСТ обычной ветви, а не её причину остановки.
//
// Какой кусок станет признаком конца, зависит от корпуса и меняется при каждом
// переобучении, поэтому проверка, закреплённая на старом словаре, этого не
// поймает. Девяносто девятый опыт нашёл это из промаха предсказания: он
// предсказал двадцать отказов из двадцати, получил девятнадцать, и разобрал
// единственное исключение до механизма — модель выбрала номер 335, который
// оказался куском слова ` close`, и обычная ветвь вышла по признаку конца.
//
// Что станет после правки (вариант В). Обычная ветвь перестаёт брать признак из
// словаря и использует заданный вызывающим либо никакой — тем же механизмом,
// которым продукт уже пользуется в подробной ветви. Формат сохранённого словаря
// не меняется, ни один из 3210 сохранённых артефактов не задет, служебный токен
// не нужен. Число 3210 измерено по ФОРМЕ артефакта, а не по имени файла: файлов
// с именем `tokenizer.json` в дереве 3383, но 173 из них — описатель полей
// обходчика кода на 147 байт, а не словарь. Прежняя запись исполнителя называла
// 3383, и это было завышением; вывод от поправки не меняется, потому что 3210
// больше нуля и цена остаётся владельческой.
//
// Почему это поведенческая приёмка, а не структурная. Источник токенов здесь
// подставляется: у генератора есть внутренний конструктор, принимающий функцию
// выбора знака, и площадка проверок видит внутренние члены проекта вывода.
// Значит поток номеров задаётся точно, и различение прямое: на нынешнем коде
// поток с номером признака в середине обрывается и получает причину «конец
// ответа», после правки доходит до предела длины и получает «предел длины».
// Обе версии этот файл компилируют, поэтому падение честное, а не «не
// собирается».
//
// Эталоны взяты из существующих проверок, а не придуманы:
//   - `Tests/TextGeneratorKvCacheIntegrationTests.cs` закрепляет, что у словаря
//     на 256 токенов признак конца равен 255;
//   - `Tests/TokenizerEdgeCaseTests.cs` закрепляет, что признак лежит внутри
//     диапазона словаря;
//   - `Tests/CodeDocumentationGenerationTests.cs` закрепляет, что подробная
//     ветвь без признака даёт «предел длины» и ровно четыре токена.
//
// Чего эта приёмка НЕ доказывает. Она не измеряет, как часто обрыв случается в
// работающем обученном продукте: девяносто девятый опыт доказал достижимость, а
// не частоту, и прямо сказал, что модель в его плече генератора не обучена и не
// воспроизводима между прогонами. Она не улучшает качество ответов и так не
// называется: цена правки — ответы станут длиннее, до предела длины, пока
// вызывающий не задаст признак, то есть больше процессорного времени.

namespace LlmFromScratch.Tests.ExperimentFixes;

using Inference;
using TensorCore.Core;
using Tokenizer;
using TransformerModel;
using TransformerModel.Caching;
using TransformerModel.Config;

public sealed class OrdinaryGenerationDoesNotInventAnEndOfAnswerMarkerTests
{
    // Крошечная настройка модели: она здесь только носитель формы, числа для
    // выбора знака подставляются источником ниже, а не берутся у модели.
    private static ModelConfig TinyConfig() => new()
    {
        VocabSize = 256,
        ContextLen = 64,
        HiddenDim = 32,
        NumLayers = 2,
        NumHeads = 4,
        NumKvHeads = 2,
        FfnHiddenDim = 64
    };

    // Словарь без обучения: 256 однобайтовых токенов, и последняя запись —
    // номер 255. Именно её нынешний код считает признаком конца ответа, и это
    // закреплено существующей проверкой целостности кеша.
    private static BpeTokenizer UntrainedTokenizer()
    {
        var tokenizer = new BpeTokenizer();
        tokenizer.Train("abc", 256);
        return tokenizer;
    }

    [Fact]
    public void VocabularyDeclaresNoEndOfAnswerMarkerAtAll()
    {
        // Вариант (Г): словарь перестаёт выдумывать признак конца и говорит
        // прямо, что его не объявляет. Прежде здесь вернулось бы 255 —
        // последняя запись словаря на 256 токенов, то есть обычный байтовый
        // токен; именно это число нынешний код принимал за служебный признак.
        // Существующие проверки, закреплявшие 255 и вхождение в диапазон
        // словаря, приведены к этой же правде в том же куске.
        var tokenizer = UntrainedTokenizer();
        Assert.Equal(256, tokenizer.VocabSize);
        Assert.Null(tokenizer.EosToken);
    }

    [Fact]
    public void OrdinaryGenerationRunsPastTheVocabularyLastEntryInsteadOfStopping()
    {
        // Поток номеров задан точно. Третьим идёт номер 255 — тот самый,
        // который нынешний код принимает за признак конца ответа; после него
        // поток продолжается буквами «C» и «D». Номера выбраны однобайтовыми
        // печатными знаками, чтобы различие было видно прямо в тексте: у
        // необученного словаря номер токена равен номеру байта.
        var stream = new[] { 65, 66, 255, 67, 68 };
        var index = 0;
        var generator = new TextGenerator(
            new LlmModel(TinyConfig()),
            UntrainedTokenizer(),
            layers => new KvCache(layers),
            (_, _, _, _, _) => stream[Math.Min(index++, stream.Length - 1)]);

        // Обычная ветвь: она возвращает ТОЛЬКО текст, причину остановки не
        // отдаёт вовсе. Поэтому различие ищется в тексте.
        var text = generator.Generate(
            "abc", stream.Length, 0f, 0, 1f, 7, CancellationToken.None);

        // НА НЫНЕШНЕМ КОДЕ эта строка падает: обычная ветвь обрывается на
        // третьем токене, и буквы после признака в текст не попадают вовсе.
        // После правки обычная ветвь признак из словаря не берёт, доходит до
        // предела длины, и «CD» оказывается в конце ответа.
        Assert.EndsWith("CD", text, StringComparison.Ordinal);

        // И начало ответа при этом не изменилось: правка убирает ложный обрыв,
        // а не переписывает выдачу.
        Assert.StartsWith("AB", text, StringComparison.Ordinal);
    }

    [Fact]
    public void DetailedGenerationWithADeclaredMarkerStillStopsOnIt()
    {
        // Законный случай обязан остаться законным: когда вызывающий ЗАДАЛ
        // признак и он проверен, остановка по нему — правильное поведение, и
        // правка его не трогает. Без этой проверки правку можно было бы принять
        // за «раннее завершение вообще убрали».
        var stream = new[] { 10, 20, 7, 30, 40 };
        var index = 0;
        var tokenizer = UntrainedTokenizer();
        var generator = new TextGenerator(
            new LlmModel(TinyConfig()),
            tokenizer,
            layers => new KvCache(layers),
            (_, _, _, _, _) => stream[Math.Min(index++, stream.Length - 1)]);

        var receipt = generator.GenerateDetailed(
            "abc", stream.Length, 0f, 0, 1f, 7, verifiedEosToken: 7, CancellationToken.None);

        // Остановка на третьем токене, и причина — именно конец ответа.
        Assert.Equal(3, receipt.GeneratedTokenCount);
        Assert.Equal("EOS", receipt.StopReason);
    }

    [Fact]
    public void DetailedGenerationWithoutAMarkerRunsToTheLengthLimit()
    {
        // Эталон из существующей проверки порождения документации: подробная
        // ветвь без заданного признака раннего завершения не делает НИКОГДА и
        // доходит до предела длины. Это и есть то поведение, к которому правка
        // приводит обычную ветвь, — поэтому после правки две ветви сходятся, а
        // не расходятся в разные стороны.
        var stream = new[] { 10, 20, 255, 30, 40 };
        var index = 0;
        var generator = new TextGenerator(
            new LlmModel(TinyConfig()),
            UntrainedTokenizer(),
            layers => new KvCache(layers),
            (_, _, _, _, _) => stream[Math.Min(index++, stream.Length - 1)]);

        var receipt = generator.GenerateDetailed(
            "abc", stream.Length, 0f, 0, 1f, 7, verifiedEosToken: null, CancellationToken.None);

        Assert.Equal(stream.Length, receipt.GeneratedTokenCount);
        Assert.Equal("LENGTH_LIMIT", receipt.StopReason);
    }
}
