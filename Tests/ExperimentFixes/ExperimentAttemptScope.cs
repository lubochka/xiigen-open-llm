using System.Text.Encodings.Web;
using System.Text.Json;
using System.Text.Json.Nodes;

// ОБЛАСТЬ ПОПЫТКИ ОПЫТА. Один маленький объект, который закрывает два разрыва владения попыткой.
//
// Первый разрыв, человеческими словами. Приёмник доказательств умеет неделимо захватывать каталог
// попытки, но испытания держали его в ленивом поле: приёмник рождался при ПЕРВОЙ записи улики.
// Расписка по смыслу пишется после измеренной работы, поэтому адрес попытки захватывался уже ПОСЛЕ
// подготовки данных и обучения. Проигравший в гонке за каталог узнавал об отказе, когда вся
// дорогая работа уже сделана, а иногда не успевал записать вообще ничего. Здесь захват перенесён в
// конструктор: он выполняется сразу и до любой подготовки.
//
// Второй разрыв. У приёмника есть готовый способ пометить попытку завершённой, но его не вызывал ни
// один вызывающий. Из-за этого любая успешно закончившаяся попытка навсегда оставалась «прерванной»:
// рядом с маркером владения не появлялся файл завершения, и следующий прогон обязан был отказаться
// и уйти в свежий каталог. Здесь завершение ставится ровно один раз, в освобождении области.
//
// Почему это именно класс-область, а не вызов внутри теста. Испытание получает эту область как
// фикстуру класса: испытательная оснастка создаёт фикстуру РАНЬШЕ конструктора тестового класса и
// раньше любой подготовки данных, а освобождает её ОДИН раз после последнего теста класса. Значит
// «захват до обучения» и «одно завершение на попытку» обеспечиваются самим порядком жизни объекта,
// а не дисциплиной автора каждого отдельного теста.
//
// Чего этот механизм НЕ обещает. Он не обещает стойкости к потере питания: если машину выключить
// посреди записи, файловая система может оставить каталог в любом промежуточном состоянии. Он также
// не меняет НИ ОДНОГО байта содержимого улик — нормализацию по-прежнему делает само испытание, а
// адрес публикуемых улик остаётся тем, который назначила карточка опыта.

/// <summary>Отказ занять область попытки: у этого владельца уже есть незавершённая область.</summary>
public sealed class ExperimentAttemptScopeAlreadyOwnedException : Exception
{
    /// <summary>Создаёт отказ с готовым человеческим объяснением.</summary>
    /// <param name="message">Текст отказа: кто владелец, что уже занято и почему повтор запрещён.</param>
    public ExperimentAttemptScopeAlreadyOwnedException(string message) : base(message)
    {
    }
}

/// <summary>Отказ писать улику после завершения попытки: счёт улик уже снят.</summary>
public sealed class ExperimentAttemptScopeCompletedException : Exception
{
    /// <summary>Создаёт отказ с готовым человеческим объяснением.</summary>
    /// <param name="message">Текст отказа: кто владелец, куда писали и почему поздно.</param>
    public ExperimentAttemptScopeCompletedException(string message) : base(message)
    {
    }
}

/// <summary>Захваченная попытка опыта: владение берётся сразу, завершение ставится один раз.</summary>
public class ExperimentAttemptScope : IDisposable
{
    /// <summary>Имя файла-подсказки приёмника: он служебный и уликой опыта не является.</summary>
    //
    // Почему здесь ССЫЛКА, а не строка. Раньше у имени было два владельца: приёмник вписывал его
    // литералом в месте использования, а область попытки держала собственную копию, потому что
    // читать у приёмника было нечего. Теперь у приёмника есть ОТКРЫТАЯ постоянная — открытая
    // именно потому, что охрана отражением ищет её среди открытых статических полей и приватную
    // не нашла бы, — и этот член оставлен её псевдонимом. Литерал в дереве остаётся ровно один.
    //
    // Чего псевдоним НЕ делает: он не отменяет копию значения. Постоянная подставляется во время
    // сборки и укладывается в метаданные потребителя, поэтому значение физически присутствует
    // дважды. Единственность владельца держится не на устройстве постоянной, а на раскладке
    // сборок: оба типа компилируются в одну сборку и всегда пересобираются вместе, так что
    // разойтись им негде. Если их когда-нибудь разнесут по разным сборкам, копия здесь может
    // устареть относительно постоянной приёмника; живых случаев у охраны равенства поэтому два,
    // и второй — ровно этот. Подробный разбор лежит у самого утверждения равенства в проверках
    // владения.
    //
    // Почему член вообще оставлен, а не удалён. На него опираются места употребления вне охраны:
    // построение пути к подсказке и текст отказа в проверках владения, а также перечисление
    // служебных имён ниже в этом же классе — подсказка служебная и уликой опыта не является,
    // поэтому счёт улик её не считает. Удаление члена переписывало бы эти места без выигрыша.
    public const string EvidenceLocationHintFileName = ExperimentEvidenceSink.EvidenceLocationHintFileName;

    /// <summary>Хвост имени временного файла записи: такие файлы ещё не доказательства.</summary>
    //
    // Открыто наружу по той же причине: охрана сверяет этот хвост с постоянной приёмника
    // отражением, и ожидание обязано жить в одном месте, а не повторяться в самой охране.
    public const string TemporaryWriteSuffix = ".частичная-запись";

    /// <summary>Настройки записи завершения: русский текст остаётся читаемым человеку.</summary>
    private static readonly JsonSerializerOptions CompletionJsonOptions = new()
    {
        WriteIndented = true,                             // Файл завершения читает человек, поэтому отступы нужны.
        Encoder = JavaScriptEncoder.UnsafeRelaxedJsonEscaping, // Русские пояснения не превращаются в \uXXXX.
    };

    /// <summary>Занятые владельцы в этом процессе: один владелец — одна незавершённая область.</summary>
    //
    // Зачем нужен этот список. Статическое поле области в тестовом классе заполняется конструктором
    // фикстуры. Если фикстура того же класса будет построена в этом процессе второй раз, пока первая
    // область ещё не завершена, молчаливый перехват поля стёр бы ссылку на живую попытку. Тогда
    // завершение ушло бы не туда, и попытка снова выглядела бы прерванной. Поэтому второй захват
    // того же владельца отклоняется заметным исключением ДО того, как поле будет переписано.
    private static readonly Dictionary<string, ExperimentAttemptScope> ActiveOwners =
        new(StringComparer.Ordinal);

    /// <summary>Приёмник доказательств этой попытки: он уже захватил каталог записи.</summary>
    private readonly ExperimentEvidenceSink _evidence;

    /// <summary>Человеческое имя владельца области: по нему человек узнаёт испытание.</summary>
    private readonly string _ownerName;

    /// <summary>Время захвата попытки в едином времени: оно попадает в файл завершения.</summary>
    private readonly DateTime _capturedUtc;

    /// <summary>Защёлка однократности завершения: второе освобождение не пишет второй файл.</summary>
    private int _completionAlreadyAttempted;

    /// <summary>Полный путь записанного файла завершения либо null, пока завершения не было.</summary>
    private string? _completionFilePath;

    /// <summary>Захватывает каталог попытки немедленно, до подготовки данных и обучения.</summary>
    /// <param name="repositoryRoot">Корень рабочей копии проекта.</param>
    /// <param name="declaredDirectory">Каталог улик, назначенный карточкой опыта.</param>
    /// <param name="ownerName">Человеческое имя владельца: обычно имя тестового класса.</param>
    //
    // Почему захват стоит прямо в конструкторе, а не в первом обращении к приёмнику. Захват адреса
    // обязан быть первым действием попытки: только тогда проигравший в гонке узнаёт об отказе до
    // того, как подготовит данные и начнёт обучение. Ленивое поле этого не даёт по определению.
    public ExperimentAttemptScope(string repositoryRoot, string declaredDirectory, string ownerName)
    {
        // Пустое имя владельца не даёт человеку понять, какое испытание держит попытку.
        if (string.IsNullOrWhiteSpace(ownerName))
            throw new ArgumentException("Имя владельца области попытки пусто.", nameof(ownerName));

        // Имя владельца запоминается для сообщений и для файла завершения.
        _ownerName = ownerName;

        // Слот владельца занимается ДО захвата каталога: так второй захват отклоняется раньше работы.
        ClaimOwnerSlot(ownerName);

        try
        {
            // Это и есть ранний захват: приёмник неделимо занимает каталог записи этой попытки.
            _evidence = ExperimentEvidenceSink.ForDeclaredDirectory(repositoryRoot, declaredDirectory);
        }
        catch
        {
            // Захват не удался — слот владельца освобождается, иначе повтор был бы заблокирован навсегда.
            ReleaseOwnerSlot(ownerName);

            // Исходный отказ приёмника уходит наружу без подмены: его текст уже человеческий.
            throw;
        }

        // Время захвата фиксируется сразу после успешного владения каталогом.
        _capturedUtc = DateTime.UtcNow;
    }

    /// <summary>Приёмник доказательств этой попытки: испытание пишет улики только через него.</summary>
    //
    // Зачем область отдаёт приёмник наружу. Испытание не должно создавать второй приёмник: второй
    // приёмник означал бы вторую попытку захвата того же адреса. Поэтому захваченный приёмник
    // отдаётся как есть, и все записи улик идут через него.
    //
    // Почему после завершения приёмник больше не отдаётся. Счёт улик снимается в момент завершения.
    // Улика, записанная после завершения, в этот счёт не войдёт, и файл завершения станет неверным
    // без всякого признака — то есть число опять начнёт тихо врать. Поэтому поздняя запись
    // отклоняется заметным отказом, а не допускается молча.
    public ExperimentEvidenceSink Evidence
    {
        get
        {
            // Защёлка завершения уже закрыта — значит счёт улик снят и дописывать улики поздно.
            if (Volatile.Read(ref _completionAlreadyAttempted) != 0)
                throw new ExperimentAttemptScopeCompletedException(string.Join("\n",
                    "ОБРАЩЕНИЕ К ПРИЁМНИКУ ПОСЛЕ ЗАВЕРШЕНИЯ ПОПЫТКИ ОТКЛОНЕНО.",
                    "Владелец: " + _ownerName,
                    "Каталог записи: " + _evidence.WriteRoot,
                    "Почему нельзя: счёт улик снят в момент завершения, и улика, записанная после," +
                    " в него не войдёт; завершение стало бы неверным без признака.",
                    "Что делать: писать улики до освобождения области либо начать новую попытку."));

            // До завершения приёмник отдаётся как есть: все записи улик идут через него.
            return _evidence;
        }
    }

    /// <summary>Человеческое имя владельца этой области попытки.</summary>
    public string OwnerName => _ownerName;

    /// <summary>Каталог, в который эта попытка фактически пишет улики.</summary>
    public string WriteRoot => _evidence.WriteRoot;

    /// <summary>Истина после того, как завершение попытки записано ровно один раз.</summary>
    public bool AttemptCompleted => _completionFilePath is not null;

    /// <summary>Полный путь файла завершения попытки либо null, пока завершения не было.</summary>
    public string? CompletionFilePath => _completionFilePath;

    /// <summary>Ставит точку в попытке: один файл завершения и освобождение слота владельца.</summary>
    //
    // Почему ошибка завершения пробрасывается наружу, а не глушится. Потерянное завершение — это
    // ровно тот дефект, который здесь и чинится: без файла завершения завершённая попытка снова
    // выглядит прерванной. Поэтому причина сначала дописывается в журнал прогона, чтобы она осталась
    // рядом с уликами, и только затем исключение уходит наружу заметным отказом.
    public void Dispose()
    {
        // Повторное освобождение не пишет второй файл завершения и не падает.
        if (Interlocked.Exchange(ref _completionAlreadyAttempted, 1) != 0) return;

        try
        {
            // Полезная нагрузка завершения готовится до записи: кто завершил, когда и сколько улик.
            var payload = BuildCompletionPayload();

            // Однократная запись файла завершения: вторая попытка завершить ту же попытку — ошибка.
            _completionFilePath = _evidence.CompleteAttempt(payload);
        }
        catch (Exception error)
        {
            // Причина отказа сохраняется рядом с уликами, чтобы человек увидел её без транскрипта.
            TryAppendCompletionFailureToJournal(error);

            // Отказ завершения виден наружу: молча потерянное завершение здесь недопустимо.
            throw;
        }
        finally
        {
            // Слот владельца освобождается в любом исходе, иначе повтор в этом процессе был бы закрыт.
            ReleaseOwnerSlot(_ownerName);

            // Освобождение управляемых ресурсов запрашивать не нужно: область их не держит.
            GC.SuppressFinalize(this);
        }
    }

    /// <summary>Занимает слот владельца или отклоняет второй захват заметным исключением.</summary>
    /// <param name="ownerName">Человеческое имя владельца области попытки.</param>
    private void ClaimOwnerSlot(string ownerName)
    {
        // Список владельцев общий на процесс, поэтому доступ к нему идёт под замком.
        lock (ActiveOwners)
        {
            // Уже занятый слот означает живую незавершённую область того же владельца.
            if (ActiveOwners.TryGetValue(ownerName, out var existing))
                throw new ExperimentAttemptScopeAlreadyOwnedException(string.Join("\n",
                    "ВТОРАЯ ОБЛАСТЬ ПОПЫТКИ ТОГО ЖЕ ВЛАДЕЛЬЦА ОТКЛОНЕНА.",
                    "Владелец: " + ownerName,
                    "Незавершённая область уже пишет сюда: " + existing.WriteRoot,
                    "Почему нельзя: перехват статического поля стёр бы ссылку на живую попытку," +
                    " и её завершение ушло бы не туда; попытка снова выглядела бы прерванной.",
                    "Что делать: завершить первую область до создания второй."));

            // Слот занимается этой областью: с этого момента владелец считается живым.
            ActiveOwners[ownerName] = this;
        }
    }

    /// <summary>Освобождает слот владельца, если он всё ещё принадлежит этой области.</summary>
    /// <param name="ownerName">Человеческое имя владельца области попытки.</param>
    private void ReleaseOwnerSlot(string ownerName)
    {
        // Список владельцев общий на процесс, поэтому доступ к нему идёт под замком.
        lock (ActiveOwners)
        {
            // Снимается только собственный слот: чужую живую область эта проверка не трогает.
            if (ActiveOwners.TryGetValue(ownerName, out var existing) && ReferenceEquals(existing, this))
                ActiveOwners.Remove(ownerName);
        }
    }

    /// <summary>Собирает человекочитаемый итог попытки для файла завершения.</summary>
    private string BuildCompletionPayload()
    {
        // Файлы каталога записи пересчитываются на момент завершения: служебные считаются отдельно.
        //
        // Почему здесь различаются удача и неудача пересчёта. Если перечисление каталога отказало,
        // настоящее число файлов НЕИЗВЕСТНО. Записать вместо неизвестного числа ноль означало бы
        // сказать читателю «каталог пуст», то есть соврать ровно тем способом, который этот ремонт
        // и чинит. Поэтому при неудаче счётчики уходят в файл завершения пустыми значениями, рядом
        // появляется поле о неудаче пересчёта с родом ошибки, а причина дописывается в журнал.
        var counted = TryCountWriteRootFiles(out var totalFiles, out var evidenceFiles, out var countFailure);

        // Причина неудачного пересчёта сохраняется рядом с уликами, иначе она терялась бы совсем.
        if (!counted && countFailure is not null) TryAppendCountFailureToJournal(countFailure);

        // Итог связывает владельца, прогон, время и наблюдаемый объём улик этой попытки.
        var completion = new JsonObject
        {
            ["владелец"] = _ownerName,                                              // Кто завершил попытку.
            ["прогон"] = _evidence.OwnerRunIdentifier,                              // Опознание прогона-владельца.
            ["захвачено_utc"] = FormatUtc(_capturedUtc),                            // Когда попытка была захвачена.
            ["завершено_utc"] = FormatUtc(DateTime.UtcNow),                         // Когда попытка завершена.
            ["назначенный_каталог"] = _evidence.DeclaredDirectory,                  // Что назначила карточка опыта.
            ["каталог_записи"] = _evidence.WriteRoot,                               // Куда попытка фактически писала.
            ["уведён_из_опубликованного"] = _evidence.RedirectedFromPublishedEvidence, // Проверочный прогон поверх публикации.
            ["уведён_из_занятого"] = _evidence.RedirectedFromOccupiedAttempt,        // Уход из занятой попытки.
            // Счёт файлов каталога записи либо наблюдённое число, либо пустота при неудаче пересчёта.
            ["файлов_всего"] = counted ? totalFiles : null,

            // То же для счёта улик: пустота означает «неизвестно», а не «улик нет».
            ["файлов_доказательств"] = counted ? evidenceFiles : null,

            // Поле появляется только при неудаче пересчёта и называет род ошибки человеку.
            ["пересчёт_не_удался"] = counted
                ? null
                : "Пересчёт файлов каталога записи отказал, поэтому счёт неизвестен. Род ошибки: "
                    + (countFailure?.GetType().Name ?? "неизвестен") + ". Сообщение: "
                    + (countFailure?.Message.Replace("\r", " ").Replace("\n", " ") ?? "нет") + ".",

            // Пояснение для человека; при неудаче пересчёта оно прямо говорит, что счёт неизвестен.
            ["пояснение"] = "Этот файл означает завершённую попытку." +
                " Пока его нет рядом с маркером владения, попытка считается прерванной." +
                (counted
                    ? " Счёт файлов снят в момент завершения; сам файл завершения в него не входит."
                    : " Счёт файлов НЕИЗВЕСТЕН: пересчёт каталога записи отказал, поэтому счётчики" +
                      " оставлены пустыми, а не нулевыми; причина отказа дописана в журнал прогона." +
                      " Само завершение при этом записано: неудачный пересчёт не отменяет завершения.") +
                " Стойкость к потере питания не обещается.",
        };

        // Итог отдаётся текстом с переводом строки на конце: так его читают и человек, и машина.
        return completion.ToJsonString(CompletionJsonOptions) + "\n";
    }

    /// <summary>Пробует посчитать файлы каталога записи: все и отдельно те, что являются уликами.</summary>
    /// <param name="totalFiles">Сколько файлов видно в каталоге записи; при неудаче значение не осмысленно.</param>
    /// <param name="evidenceFiles">Сколько из них не служебные; при неудаче значение не осмысленно.</param>
    /// <param name="failure">Причина неудачного пересчёта либо пустота, если пересчёт удался.</param>
    /// <returns>Истина, если пересчёт удался и счётчикам можно верить.</returns>
    //
    // Почему возвращается признак удачи, а не просто числа. Отказ перечисления каталога означает,
    // что число файлов неизвестно. Прежняя форма поглощала отказ и оставляла нули, а ноль читается
    // как «каталог пуст» — то есть неизвестное выдавалось за наблюдённое. Теперь неудача видна
    // вызывающему, и он обязан записать пустое значение вместо нуля.
    private bool TryCountWriteRootFiles(out int totalFiles, out int evidenceFiles, out Exception? failure)
    {
        // До пересчёта счётчики обнулены, но верить им можно только при успешном возврате.
        totalFiles = 0;
        evidenceFiles = 0;

        // Пока отказа не было, причина пуста.
        failure = null;

        try
        {
            // Отсутствующий каталог записи — это удачно наблюдённый ноль, а не неудача пересчёта.
            if (!Directory.Exists(_evidence.WriteRoot)) return true;

            // Перечисляются все файлы каталога записи, включая вложенные подкаталоги.
            foreach (var file in EnumerateWriteRootFiles(_evidence.WriteRoot))
            {
                // Каждый найденный файл увеличивает общий счёт.
                totalFiles++;

                // Служебные файлы приёмника уликой опыта не являются и в счёт улик не входят.
                if (!IsServiceFile(Path.GetFileName(file))) evidenceFiles++;
            }

            // Перечисление дошло до конца, значит обоим счётчикам можно верить.
            return true;
        }
        catch (IOException error)
        {
            // Отказ ввода-вывода: счёт неизвестен, и причина уходит наружу вместо тихого нуля.
            failure = error;
        }
        catch (UnauthorizedAccessException error)
        {
            // Отказ прав: тоже неизвестный счёт, а не пустой каталог.
            failure = error;
        }

        // Любой перехваченный отказ означает неизвестный счёт: счётчикам верить нельзя.
        return false;
    }

    /// <summary>Перечисляет файлы каталога записи: шов для проверок самой области попытки.</summary>
    /// <param name="writeRoot">Каталог записи этой попытки.</param>
    /// <returns>Полные пути всех файлов каталога, включая вложенные подкаталоги.</returns>
    //
    // Зачем здесь шов. Ветку «пересчёт файлов отказал» иначе нечем проверить: настоящий отказ прав
    // потребовал бы менять права в рабочем каталоге, а это запрещено. Перечисление вынесено в
    // отдельный защищённый метод, и проверка объявляет наследника, который бросает отказ
    // ввода-вывода. Отказ там СМОДЕЛИРОВАН переопределением перечисления, а не настоящим отказом
    // прав — так и сказано в отчёте. Шов законен, потому что область попытки живёт в испытаниях,
    // а не в продуктовом коде, и служит проверкам самой области.
    protected virtual string[] EnumerateWriteRootFiles(string writeRoot)
        // Обычное перечисление каталога: единственное место, где оно выполняется.
        => Directory.GetFiles(writeRoot, "*", SearchOption.AllDirectories);

    /// <summary>Отвечает, служебный ли это файл приёмника, а не улика опыта.</summary>
    /// <param name="fileName">Имя файла без каталога.</param>
    private static bool IsServiceFile(string fileName)
        // Маркер владения, завершение, статус владельца, журнал, подсказка и временные файлы служебные.
        => string.Equals(fileName, ExperimentEvidenceSink.AttemptOwnerMarkerFileName, StringComparison.Ordinal)
            || string.Equals(fileName, ExperimentEvidenceSink.AttemptCompletionFileName, StringComparison.Ordinal)
            || string.Equals(fileName, ExperimentEvidenceSink.OwnerStatusFileName, StringComparison.Ordinal)
            || string.Equals(fileName, ExperimentEvidenceSink.RunJournalFileName, StringComparison.Ordinal)
            || string.Equals(fileName, EvidenceLocationHintFileName, StringComparison.Ordinal)
            || fileName.EndsWith(TemporaryWriteSuffix, StringComparison.Ordinal);

    /// <summary>Дописывает причину неудачного пересчёта файлов в журнал прогона.</summary>
    /// <param name="error">Исходная ошибка, из-за которой счёт файлов остался неизвестным.</param>
    //
    // Почему причина пишется в журнал, а не только в файл завершения. Файл завершения говорит, что
    // счёт неизвестен, но не всегда объясняет обстоятельства; журнал прогона лежит рядом с уликами
    // и сохраняет род ошибки и её сообщение, чтобы человек увидел причину без транскрипта.
    // Завершение при этом продолжает записываться: неудачный пересчёт не отменяет завершения.
    private void TryAppendCountFailureToJournal(Exception error)
    {
        try
        {
            // Журнал прогона дописывается, поэтому прежние строки остаются целыми.
            _evidence.AppendJournalLine(string.Join(" ",
                FormatUtc(DateTime.UtcNow),
                "ПЕРЕСЧЁТ ФАЙЛОВ КАТАЛОГА ЗАПИСИ НЕ УДАЛСЯ, СЧЁТ НЕИЗВЕСТЕН.",
                "Владелец: " + _ownerName + ".",
                "Род ошибки: " + error.GetType().Name + ".",
                "Сообщение: " + error.Message.Replace("\r", " ").Replace("\n", " ") + ".",
                "Завершение попытки при этом записывается."));
        }
        catch (Exception)
        {
            // Если и журнал недоступен, неизвестный счёт всё равно виден в файле завершения.
        }
    }

    /// <summary>Дописывает причину неудачного завершения в журнал прогона, не скрывая отказ.</summary>
    /// <param name="error">Исходная ошибка, из-за которой завершение не записалось.</param>
    private void TryAppendCompletionFailureToJournal(Exception error)
    {
        try
        {
            // Журнал прогона дописывается, поэтому прежние строки остаются целыми.
            _evidence.AppendJournalLine(string.Join(" ",
                FormatUtc(DateTime.UtcNow),
                "ЗАВЕРШЕНИЕ ПОПЫТКИ НЕ ЗАПИСАНО.",
                "Владелец: " + _ownerName + ".",
                "Род ошибки: " + error.GetType().Name + ".",
                "Сообщение: " + error.Message.Replace("\r", " ").Replace("\n", " ") + "."));
        }
        catch (Exception)
        {
            // Если и журнал недоступен, отказ всё равно уйдёт наружу исключением из Dispose.
        }
    }

    /// <summary>Приводит время к единому читаемому виду для файлов и журнала.</summary>
    /// <param name="moment">Момент времени в едином времени.</param>
    private static string FormatUtc(DateTime moment)
        // Формат совпадает с форматом маркера владения, чтобы человек сравнивал их глазами.
        => moment.ToString("yyyy-MM-dd'T'HH:mm:ss.fff'Z'");
}
