namespace LlmFromScratch.Tests.ExperimentFixes;

using TensorCore.Core;

// Договорные проверки переноса «суммировать последнюю ось нормализации без
// массивов координат» (строка очереди 217 реестра исправлений по опытам;
// карточка переноса сокращения строки нормы, раздел «Contract tests и
// действующие тесты, которые сохраняются»).
//
// Что защищают эти шесть проверок человеческими словами. Нормализация длины
// вектора складывает числа по последней оси. Прежний код для КАЖДОГО слагаемого
// собирал массив координат и переводил его обратно в плоский номер. При
// сохранённой последней оси нужные числа уже лежат в памяти подряд: строка
// выходной клетки начинается с её номера, умноженного на длину строки. Новый
// узкий путь читает строку напрямую. Порядок сложения прежний, поэтому сумма
// обязана выйти бит в бит той же; убраны только вычисления адресов.
//
// Откуда взяты ожидаемые числа, и почему они независимы. Ни одна проверка ниже
// не зовёт новый внутренний цикл, чтобы посчитать им же своё ожидание. Средние
// выписаны руками из входных чисел; производная среднего по одному слагаемому
// равна единице, делённой на длину оси, и выведена математически, поэтому
// ожидаемый градиент — это заданное сверху число, умноженное на эту постоянную
// долю, а не результат изменённого метода.
//
// Что эти шесть проверок НЕ закрывают. Они не являются доказательством
// обучения: настоящие учебные обновления на восстановленном обученном старте —
// отдельная учебная приёмка этой же карточки. Обратное распространение
// проверяется только там, где последняя ось сохранена, и у неизменённой
// средней оси; граница без сохранения оси проверяется лишь по прямому проходу,
// потому что карточка отдельно называет известный риск обратного прохода при
// уменьшенном числе осей и запрещает его чинить этим переносом.
public sealed class RmsRowReductionContractTests
{
    // Длина последней оси в основном наборе входных чисел: три слагаемых в строке.
    private const int RowLength = 3;

    // Длина средней оси в основном наборе входных чисел: два слагаемых в столбце.
    private const int MiddleLength = 2;

    // Готовит входной тензор формы [2,2,3] с числами от одного до двенадцати по
    // порядку их расположения в памяти; это общий вход четырёх первых проверок.
    private static Tensor OneToTwelve()
    {
        // Форма «две группы по две строки из трёх чисел» — та же, что в карточке.
        var shape = new TensorShape(2, 2, RowLength);

        // Место под двенадцать чисел входа.
        var data = new float[shape.TotalElements];

        // Заполняем числами 1..12 в порядке хранения: строки идут подряд.
        for (var i = 0; i < data.Length; i++)
            data[i] = i + 1;

        // Отдаём продуктовый тензор, а не копию вычислений нормализации.
        return new Tensor(data, shape);
    }

    [Fact]
    public void LastAxisNegativeIndex_PreservesValuesAndGradients()
    {
        // Вход — те самые числа от одного до двенадцати формы [2,2,3].
        var x = OneToTwelve();

        // Просим считать градиент по входу: иначе обратный проход не построится.
        x.RequiresGrad = true;

        // Берём среднее по последней оси, названной отрицательным номером, и
        // сохраняем эту ось длиной один — это ровно тот вход, на котором
        // включается новый узкий путь.
        var mean = TensorOps.Mean(x, axis: -1, keepDims: true);

        // Форма обязана остаться трёхосной с единицей на последней оси.
        Assert.Equal([2, 2, 1], mean.Shape.Dimensions);

        // Четыре ожидаемых средних выписаны руками: (1+2+3)/3, (4+5+6)/3,
        // (7+8+9)/3 и (10+11+12)/3. Все четыре — целые, поэтому сравниваем точно.
        Assert.Equal(2f, mean.Data[0]);
        Assert.Equal(5f, mean.Data[1]);
        Assert.Equal(8f, mean.Data[2]);
        Assert.Equal(11f, mean.Data[3]);

        // Назначенные сверху числа обратного прохода: по одному на каждую из
        // четырёх строк. Они нарочно различаются, чтобы перепутанная или
        // потерянная строка не спряталась за одинаковыми единицами.
        var upstreamValues = new[] { 1f, 2f, 3f, 4f };

        // Упаковываем их в тензор формы выхода — обратный проход требует совпадения.
        var upstream = new Tensor(upstreamValues.ToArray(), mean.Shape);

        // Запускаем обратное распространение от результата с этими числами.
        mean.Backward(upstream);

        // Градиент по входу обязан появиться.
        Assert.NotNull(x.Grad);

        // Проверяем каждое из двенадцати чисел градиента.
        for (var row = 0; row < upstreamValues.Length; row++)
        for (var k = 0; k < RowLength; k++)
        {
            // Математический вывод: производная среднего по одному слагаемому
            // равна единице, делённой на длину оси. Значит каждое из трёх чисел
            // строки получает назначенное сверху число, делённое на три. Это
            // постоянная доля, выведенная заранее, а не вызов изменённого метода.
            var expected = upstreamValues[row] / RowLength;

            // Место этого числа в памяти входа: строка row, слагаемое k.
            var actual = x.Grad!.Data[(row * RowLength) + k];

            // Одна треть не представима в двоичной дроби точно, поэтому
            // сравниваем с точностью до шестого знака, не ослабляя сам эталон.
            Assert.Equal(expected, actual, precision: 6);
        }
    }

    [Fact]
    public void LastAxisWithoutKeepDims_PreservesForwardFallback()
    {
        // Те же числа от одного до двенадцати формы [2,2,3].
        var x = OneToTwelve();

        // Градиент здесь не запрашиваем: карточка прямо не назначает обратный
        // проход этой неизменённой ветви и запрещает чинить его этим переносом.
        x.RequiresGrad = false;

        // Последняя ось названа прямым номером два, но ось НЕ сохраняется.
        // Число осей результата меньше числа осей входа, поэтому условие входа
        // в узкий путь не выполняется и работает прежняя общая ветвь. Это
        // проверка границы: прежнее поведение обязано сохраниться.
        var mean = TensorOps.Mean(x, axis: 2, keepDims: false);

        // Форма обязана стать двухосной, без оси длиной один.
        Assert.Equal([2, 2], mean.Shape.Dimensions);

        // Средние те же четыре целых числа, выписанные руками из входа.
        Assert.Equal(2f, mean.Data[0]);
        Assert.Equal(5f, mean.Data[1]);
        Assert.Equal(8f, mean.Data[2]);
        Assert.Equal(11f, mean.Data[3]);

        // Обратный проход этой ветви не назначен, поэтому граф не строился.
        Assert.False(mean.RequiresGrad);
    }

    [Fact]
    public void MiddleAxisKeepDims_PreservesValuesAndGradients()
    {
        // Те же числа от одного до двенадцати формы [2,2,3].
        var x = OneToTwelve();

        // Просим считать градиент: средняя ось — неизменённая ветвь, и её
        // обратный проход карточка проверяет при сохранённой оси.
        x.RequiresGrad = true;

        // Среднее по средней оси с сохранением этой оси длиной один. Последняя
        // ось здесь НЕ суммируется, поэтому узкий путь не включается.
        var mean = TensorOps.Mean(x, axis: 1, keepDims: true);

        // Форма обязана остаться трёхосной с единицей на средней оси.
        Assert.Equal([2, 1, RowLength], mean.Shape.Dimensions);

        // Шесть ожидаемых средних выписаны руками. Первая группа складывает
        // строки [1,2,3] и [4,5,6] поэлементно и делит на два, вторая — строки
        // [7,8,9] и [10,11,12]. Половины представимы точно, сравниваем точно.
        Assert.Equal(2.5f, mean.Data[0]);
        Assert.Equal(3.5f, mean.Data[1]);
        Assert.Equal(4.5f, mean.Data[2]);
        Assert.Equal(8.5f, mean.Data[3]);
        Assert.Equal(9.5f, mean.Data[4]);
        Assert.Equal(10.5f, mean.Data[5]);

        // Шесть назначенных сверху чисел обратного прохода, все разные.
        var upstreamValues = new[] { 1f, 2f, 3f, 4f, 5f, 6f };

        // Упаковываем их в тензор формы выхода [2,1,3].
        var upstream = new Tensor(upstreamValues.ToArray(), mean.Shape);

        // Запускаем обратное распространение от результата с этими числами.
        mean.Backward(upstream);

        // Градиент по входу обязан появиться.
        Assert.NotNull(x.Grad);

        // Проверяем все двенадцать чисел градиента.
        for (var group = 0; group < 2; group++)
        for (var middle = 0; middle < MiddleLength; middle++)
        for (var k = 0; k < RowLength; k++)
        {
            // Та же математика: производная среднего по одному слагаемому равна
            // единице, делённой на длину оси, то есть на два. Обе исходные
            // строки группы получают один и тот же вектор назначенных сверху
            // чисел, делённый на два.
            var expected = upstreamValues[(group * RowLength) + k] / MiddleLength;

            // Место этого числа в памяти входа: группа group, строка middle.
            var actual = x.Grad!.Data[(((group * MiddleLength) + middle) * RowLength) + k];

            // Половины представимы точно, но оставляем ту же точность сравнения,
            // что и у первой проверки, чтобы правило эталона было одно.
            Assert.Equal(expected, actual, precision: 6);
        }
    }

    [Fact]
    public void FirstAxisWithoutKeepDims_PreservesForwardFallback()
    {
        // Те же числа от одного до двенадцати формы [2,2,3].
        var x = OneToTwelve();

        // Градиент не запрашиваем: это проверка прямого прохода на границе.
        x.RequiresGrad = false;

        // Среднее по первой оси без сохранения этой оси. Ни последняя ось, ни
        // сохранение числа осей здесь не выполнены, значит работает прежняя
        // общая ветвь — вторая половина проверки границы узкого пути.
        var mean = TensorOps.Mean(x, axis: 0, keepDims: false);

        // Форма обязана стать двухосной.
        Assert.Equal([MiddleLength, RowLength], mean.Shape.Dimensions);

        // Шесть ожидаемых средних выписаны руками: поэлементная полусумма
        // первой группы [1..6] и второй группы [7..12]. Все шесть целые.
        Assert.Equal(4f, mean.Data[0]);
        Assert.Equal(5f, mean.Data[1]);
        Assert.Equal(6f, mean.Data[2]);
        Assert.Equal(7f, mean.Data[3]);
        Assert.Equal(8f, mean.Data[4]);
        Assert.Equal(9f, mean.Data[5]);
    }

    [Fact]
    public void LeftToRightRounding_IsPreserved()
    {
        // Форма «одна группа, одна строка, четыре числа»: всё лежит подряд.
        var shape = new TensorShape(1, 1, 4);

        // Нарочно подобранные четыре числа. Большое число — это два в двадцать
        // четвёртой степени: соседнее с ним целое уже не представимо в этом типе.
        var data = new[] { 16777216f, 1f, -16777216f, 1f };

        // Продуктовый тензор с этими числами.
        var x = new Tensor(data, shape);

        // Просим считать градиент, чтобы заодно проверить обратный проход.
        x.RequiresGrad = true;

        // Среднее по последней оси с сохранением оси — это узкий путь.
        var mean = TensorOps.Mean(x, axis: -1, keepDims: true);

        // Почему ожидание именно такое. Складывая строго слева направо, большое
        // число поглощает прибавленную единицу: результат остаётся тем же
        // большим числом. Затем вычитание большого числа даёт ноль, и последняя
        // единица даёт сумму один. Среднее — одна четверть, и она представима
        // в двоичной дроби точно.
        var expectedMean = 0.25f;

        // Сравниваем ПОБИТОВО, а не с допуском: перегруппировка слагаемых
        // (попарное или векторное сложение) дала бы другую сумму, и допуск мог
        // бы её спрятать. Побитовое равенство запрещает такую перегруппировку.
        Assert.Equal(
            BitConverter.SingleToInt32Bits(expectedMean),
            BitConverter.SingleToInt32Bits(mean.Data[0]));

        // Одно назначенное сверху число обратного прохода.
        var upstream = new Tensor([8f], mean.Shape);

        // Запускаем обратное распространение от результата.
        mean.Backward(upstream);

        // Градиент по входу обязан появиться.
        Assert.NotNull(x.Grad);

        // Производная среднего по одному слагаемому — одна четвёртая, поэтому
        // каждое из четырёх чисел входа получает восемь, делённые на четыре.
        var expectedGradient = 8f / 4f;

        // Все четыре числа градиента обязаны быть ровно двойкой; двойка
        // представима точно, поэтому сравниваем точно.
        for (var k = 0; k < data.Length; k++)
            Assert.Equal(expectedGradient, x.Grad!.Data[k]);
    }

    [Fact]
    public void PreCancelledLastAxis_Throws()
    {
        // Строка длиной четыре тысячи девяносто семь чисел выбрана нарочно:
        // внутренняя проверка отмены срабатывает на каждом четырёхтысячном с
        // небольшим слагаемом, поэтому такая длина задевает и проверку в начале
        // строки, и проверку внутри её цикла.
        var shape = new TensorShape(1, 1, 4097);

        // Место под эти числа; значения здесь не важны, важна сама отмена.
        var data = new float[shape.TotalElements];

        // Заполняем единицами, чтобы вход был осмысленным, а не нулевым.
        for (var i = 0; i < data.Length; i++)
            data[i] = 1f;

        // Продуктовый тензор с этой длинной строкой.
        var x = new Tensor(data, shape);

        // Положительный контроль законного пути: та же длинная строка и тот же
        // вызов, но БЕЗ отмены, обязаны спокойно досчитаться. Без этого контроля
        // отказ ниже мог бы объясняться чем угодно — например недостижимым
        // входом, — а не самой отменой.
        var lawful = TensorOps.Mean(x, axis: -1, keepDims: true, cancellationToken: CancellationToken.None);

        // Все слагаемые равны единице, значит среднее обязано быть единицей.
        Assert.Equal(1f, lawful.Data[0]);

        // Источник отмены, отменённый ЗАРАНЕЕ, до вызова нормализации.
        using var cancellation = new CancellationTokenSource();

        // Отменяем сразу: сокращение не должно успеть завершиться.
        cancellation.Cancel();

        // Ожидание: вызов обязан прерваться отменой, а не вернуть готовый
        // результат. Это проверка отмены именно внутри узкого пути, потому что
        // последняя ось названа отрицательным номером и сохранена.
        Assert.Throws<OperationCanceledException>(
            () => TensorOps.Mean(x, axis: -1, keepDims: true, cancellationToken: cancellation.Token));
    }
}
