namespace LlmFromScratch.Tests;

using TensorCore.Core;

// Договорные проверки переноса «локальность вычисления правого градиента
// умножения матриц» (идентификатор работы FIX-GB, карточка переноса номер 29
// в папке исправлений по опытам, файл 29-matmul-right-gradient-locality.md,
// раздел «Существующие тесты, новый контракт и ремонт падений»). Карточка
// назначает этому классу ровно три случая, задаёт их входы и ожидаемые числа;
// имена случаев и числа взяты из неё дословно.
//
// ЧТО ЗАЩИЩАЮТ ЭТИ ТРИ СЛУЧАЯ ЧЕЛОВЕЧЕСКИМИ СЛОВАМИ. Умножение матриц в
// обратном проходе считает два градиента: по левому множителю и по правому.
// Перенос меняет только ПОРЯДОК обхода вложенных циклов в ветви правого
// градиента, чтобы одно число левой матрицы читалось один раз на целую строку
// работы вместо чтения заново на каждую клетку. Набор слагаемых каждой клетки
// правого градиента и порядок их сложения при этом обязаны остаться теми же.
// Значит и числа обязаны выйти бит в бит прежними.
//
// ПОЧЕМУ ЭТИ СЛУЧАИ НУЖНЫ ДОПОЛНИТЕЛЬНО. Существующая проверка обратного
// прохода умножения (класс TensorCoreTests, случай
// Backward_MatMul_GradMatchesPyTorchReference) держит только ЛЕВЫЙ градиент:
// правый множитель в ней не обучаемый, поэтому ветвь правого градиента там
// вообще не исполняется. Карточка называет эту дыру прямо: «в текущем тесте B
// не trainable, поэтому он один не покрывает gradB». Три случая ниже закрывают
// именно её.
//
// ОТКУДА ВЗЯТЫ ОЖИДАЕМЫЕ ЧИСЛА И ПОЧЕМУ ОНИ НЕЗАВИСИМЫ ОТ ПРОВЕРЯЕМОГО КОДА.
// Ни один случай не зовёт проверяемый метод, чтобы посчитать им же своё
// ожидание. Все ожидания выписаны руками по школьным формулам производной
// матричного произведения: для произведения левой матрицы на правую градиент
// по правой равен произведению транспонированной левой матрицы на градиент
// сверху, а градиент по левой равен произведению градиента сверху на
// транспонированную правую матрицу. Те же самые числа дословно напечатаны в
// таблице карточки, поэтому ожидание независимо и от кода, и от моего
// собственного счёта: два независимых источника совпали.
//
// ПОЧЕМУ СРАВНЕНИЕ ПОБИТОВОЕ, А НЕ С ДОПУСКОМ. Перенос обязан сохранить
// значения БЕЗ изменения; допуск спрятал бы перегруппировку суммы или другой
// порядок накопления, а побитовое сравнение её запрещает. Все ожидаемые числа
// ниже — небольшие целые, представимые в одинарной точности точно, поэтому
// побитовое сравнение здесь законно и не придирчиво.
//
// ЧТО ЭТИ ТРИ СЛУЧАЯ НЕ ЗАКРЫВАЮТ. Они не обучают модель, не делают ни одного
// обновления оптимизатора и не являются доказательством обучения или допуска в
// продукт. Учебная приёмка на восстановленном обученном старте и сравнение
// расхода времени и памяти — отдельные части той же карточки. Прямой проход и
// проверки несовместимых размеров здесь тоже не дублируются: за них отвечают
// уже существующие случаи, которые карточка велит сохранить без изменений.
public sealed class GradBLocalityContractTests
{
    // Сравнивает одно число побитово и называет в тексте ошибки точное место.
    private static void AssertExactBits(float expected, float actual, string place)
    {
        // Берём целочисленное представление ожидаемого числа: допуск невозможен.
        var expectedBits = BitConverter.SingleToInt32Bits(expected);

        // То же представление для полученного числа.
        var actualBits = BitConverter.SingleToInt32Bits(actual);

        // Сравниваем представления и в случае расхождения называем клетку и оба числа.
        Assert.True(
            expectedBits == actualBits,
            $"{place}: ожидалось {expected}, получено {actual} " +
            $"(побитово {expectedBits} против {actualBits})");
    }

    // Сверяет весь градиент целиком: длину и каждое число по порядку хранения.
    private static void AssertExactGradient(
        float[] expected,
        Tensor? actual,
        int[] expectedDimensions,
        string name)
    {
        // Градиент обязан существовать: отсутствие градиента — тоже дефект ветви.
        Assert.NotNull(actual);

        // Форма градиента обязана совпадать с формой самого тензора.
        Assert.Equal(expectedDimensions, actual!.Shape.Dimensions);

        // Количество чисел обязано совпасть, иначе дальше сверять нечего.
        Assert.Equal(expected.Length, actual.Data.Length);

        // Каждое число сверяется побитово с ручным ожиданием.
        for (var flat = 0; flat < expected.Length; flat++)
            AssertExactBits(expected[flat], actual.Data[flat], $"{name}, клетка {flat}");
    }

    // Левая матрица двух первых случаев: две строки по три числа, значения 1..6.
    private static Tensor LeftTwoByThree(bool requiresGrad)
    {
        // Форма «две строки по три числа» — ровно та, что названа в карточке.
        var shape = new TensorShape(2, 3);

        // Числа выписаны явно, а не вычислены циклом: вход виден читателю целиком.
        var data = new[] { 1f, 2f, 3f, 4f, 5f, 6f };

        // Обучаемость задаётся случаем: в первом левая матрица заморожена.
        return new Tensor(data, shape, requiresGrad);
    }

    // Правая матрица двух первых случаев: три строки по два числа, разные знаки.
    private static Tensor RightThreeByTwo(bool requiresGrad)
    {
        // Форма «три строки по два числа»: её последняя ось станет осью столбцов.
        var shape = new TensorShape(3, 2);

        // Нули и отрицательные числа нарочно внутри: перепутанный порядок не спрячется.
        var data = new[] { 2f, -1f, 0f, 3f, -2f, 4f };

        // Правая матрица обучаема во всех трёх случаях — это проверяемая ветвь.
        return new Tensor(data, shape, requiresGrad);
    }

    // Градиент сверху двух первых случаев: четыре РАЗНЫХ числа, не единицы.
    private static Tensor UpstreamTwoByTwo()
    {
        // Форма совпадает с формой произведения: две строки по два числа.
        var shape = new TensorShape(2, 2);

        // Неоднородность здесь принципиальна: на единицах ошибка индексации
        // правого градиента могла бы остаться незаметной.
        var data = new[] { 1f, 2f, 3f, 4f };

        // Градиент сверху сам не обучается: это внешнее условие задачи.
        return new Tensor(data, shape);
    }

    // Ожидаемый правый градиент двух первых случаев в порядке хранения.
    // Руками: транспонированная левая матрица [[1,4],[2,5],[3,6]] умножена на
    // градиент сверху [[1,2],[3,4]]; строки дают (13,18), (17,24), (21,30).
    private static float[] ExpectedRightGradient()
        => new[] { 13f, 18f, 17f, 24f, 21f, 30f };

    // Ожидаемый левый градиент второго случая в порядке хранения.
    // Руками: градиент сверху [[1,2],[3,4]] умножен на транспонированную правую
    // матрицу [[2,0,-2],[-1,3,4]]; строки дают (0,6,6) и (2,12,10).
    private static float[] ExpectedLeftGradient()
        => new[] { 0f, 6f, 6f, 2f, 12f, 10f };

    [Fact]
    public void RightGradient_NonUniformUpstreamMatchesAnalyticalResult()
    {
        // Левая матрица НЕ обучается: так проверяется ровно ветвь правого градиента.
        var left = LeftTwoByThree(requiresGrad: false);

        // Правая матрица обучается: именно её градиент и считает проверяемая ветвь.
        var right = RightThreeByTwo(requiresGrad: true);

        // Зовём продуктовое умножение матриц — то самое, чей обратный проход меняется.
        var product = TensorOps.MatMul(left, right);

        // Форма произведения обязана быть «две строки по два числа».
        Assert.Equal(new[] { 2, 2 }, product.Shape.Dimensions);

        // Произведение обязано быть обучаемым: иначе обратный проход не построен.
        Assert.True(product.RequiresGrad);

        // Запускаем обратный проход с НЕОДНОРОДНЫМ градиентом сверху.
        product.Backward(UpstreamTwoByTwo());

        // Правый градиент обязан совпасть с аналитическим ответом побитово.
        AssertExactGradient(
            ExpectedRightGradient(),
            right.Grad,
            new[] { 3, 2 },
            "правый градиент");

        // У замороженной левой матрицы градиента быть не должно вовсе:
        // это отрицательный контроль того, что проверялась нужная ветвь.
        Assert.Null(left.Grad);
    }

    [Fact]
    public void BothGradients_PreserveAccumulation()
    {
        // Теперь обучаются ОБЕ стороны: проверяются обе ветви обратного прохода.
        var left = LeftTwoByThree(requiresGrad: true);

        // Правая матрица та же, что и в первом случае.
        var right = RightThreeByTwo(requiresGrad: true);

        // Первое свежее произведение тех же двух матриц.
        var firstProduct = TensorOps.MatMul(left, right);

        // Первый обратный проход с тем же неоднородным градиентом сверху.
        firstProduct.Backward(UpstreamTwoByTwo());

        // Левый градиент после первого прохода — аналитический ответ.
        AssertExactGradient(
            ExpectedLeftGradient(),
            left.Grad,
            new[] { 2, 3 },
            "левый градиент после первого обратного прохода");

        // Правый градиент после первого прохода — тот же, что в первом случае.
        AssertExactGradient(
            ExpectedRightGradient(),
            right.Grad,
            new[] { 3, 2 },
            "правый градиент после первого обратного прохода");

        // Второе СВЕЖЕЕ произведение тех же самых листовых матриц.
        var secondProduct = TensorOps.MatMul(left, right);

        // Это действительно новый узел графа, а не повторный проход по старому.
        Assert.NotSame(firstProduct, secondProduct);

        // Обнуления градиентов между проходами НЕТ намеренно: проверяется
        // именно накопление, то есть добавление к уже накопленному градиенту.
        secondProduct.Backward(UpstreamTwoByTwo());

        // Ожидание левого градиента после второго прохода: ровно удвоение,
        // выписанное руками из первого ответа (0,6,6,2,12,10).
        var leftDoubled = new[] { 0f, 12f, 12f, 4f, 24f, 20f };

        // Ожидание правого градиента после второго прохода: тоже ровно удвоение
        // первого ответа (13,18,17,24,21,30).
        var rightDoubled = new[] { 26f, 36f, 34f, 48f, 42f, 60f };

        // Левый градиент обязан удвоиться точно, без допуска.
        AssertExactGradient(
            leftDoubled,
            left.Grad,
            new[] { 2, 3 },
            "левый градиент после второго обратного прохода");

        // Правый градиент обязан удвоиться точно: накопление ветви сохранено.
        AssertExactGradient(
            rightDoubled,
            right.Grad,
            new[] { 3, 2 },
            "правый градиент после второго обратного прохода");
    }

    [Fact]
    public void BatchedRightGradient_PreservesBatchMapping()
    {
        // Левый вход: две партии по две строки из трёх чисел, значения 1..12.
        var leftShape = new TensorShape(2, 2, 3);

        // Первая партия — числа 1..6, вторая — числа 7..12, выписаны явно.
        var leftData = new[] { 1f, 2f, 3f, 4f, 5f, 6f, 7f, 8f, 9f, 10f, 11f, 12f };

        // Левая матрица обучаема: карточка требует обе стороны обучаемыми.
        var left = new Tensor(leftData, leftShape, requiresGrad: true);

        // Правый вход: две партии по три строки из двух чисел.
        var rightShape = new TensorShape(2, 3, 2);

        // Первая партия повторяет правую матрицу первых случаев, вторая — другая.
        var rightData = new[] { 2f, -1f, 0f, 3f, -2f, 4f, 1f, 2f, -1f, 0f, 3f, -2f };

        // Правая матрица обучаема: это проверяемая ветвь.
        var right = new Tensor(rightData, rightShape, requiresGrad: true);

        // Зовём продуктовое умножение матриц на партиях.
        var product = TensorOps.MatMul(left, right);

        // Форма произведения обязана быть «две партии по две строки из двух чисел».
        Assert.Equal(new[] { 2, 2, 2 }, product.Shape.Dimensions);

        // Градиент сверху: две партии по четыре числа, во второй партии знаки иные,
        // чтобы перепутанная привязка партий не могла совпасть случайно.
        var upstreamData = new[] { 1f, 2f, 3f, 4f, -1f, 1f, 2f, -2f };

        // Форма градиента сверху совпадает с формой произведения.
        var upstream = new Tensor(upstreamData, new TensorShape(2, 2, 2));

        // Обратный проход на партиях.
        product.Backward(upstream);

        // Ожидаемый правый градиент. Первая партия — прежний ответ (13,18,17,24,21,30).
        // Вторая партия руками: транспонированная левая [[7,10],[8,11],[9,12]]
        // умножена на [[-1,1],[2,-2]]; строки дают (13,-13), (14,-14), (15,-15).
        var expectedRight = new[]
        {
            13f, 18f, 17f, 24f, 21f, 30f,
            13f, -13f, 14f, -14f, 15f, -15f
        };

        // Ожидаемый левый градиент. Первая партия — прежний ответ (0,6,6,2,12,10).
        // Вторая партия руками: [[-1,1],[2,-2]] умножено на транспонированную
        // правую [[1,-1,3],[2,0,-2]]; строки дают (1,1,-5) и (-2,-2,10).
        var expectedLeft = new[]
        {
            0f, 6f, 6f, 2f, 12f, 10f,
            1f, 1f, -5f, -2f, -2f, 10f
        };

        // Правый градиент обязан совпасть побитово в обеих партиях: это и есть
        // сохранение привязки партии к своей клетке правого градиента.
        AssertExactGradient(
            expectedRight,
            right.Grad,
            new[] { 2, 3, 2 },
            "правый градиент на партиях");

        // Левый градиент обязан совпасть побитово в обеих партиях.
        AssertExactGradient(
            expectedLeft,
            left.Grad,
            new[] { 2, 2, 3 },
            "левый градиент на партиях");
    }
}
