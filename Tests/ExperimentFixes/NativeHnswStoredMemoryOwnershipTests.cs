// Постоянное покрытие владения вектором и метаданными в штатном указателе
// ближайших соседей (продолжение работы R11 плана ремонта 98 из папки
// docs/plans/replanning-possible-diffs/fixes-based-on-experiments; хвост,
// названный самой же проверкой формы: «указатель по-прежнему хранит тот самый
// массив, который дала вызывающая сторона»).
//
// Что здесь проверяется по-человечески. Указатель соседей принимает готовый
// массив чисел, опознаватель и необязательный словарь пометок, а потом
// отвечает на запросы ближайшими строками. Вопрос простой: чьи это массив и
// словарь после приёма — указателя или того, кто их передал.
//
// Что было сломано. Метод добавления клал в свои списки ровно тот массив и
// ровно тот словарь, которые дала вызывающая сторона. Она держит их у себя и
// может изменить свои же ячейки в любой момент. Тогда содержимое памяти
// указателя менялось вместе с ними: ответ на прежний запрос становился другим
// без единого добавления, без переобучения и без перезагрузки, и никакого
// события, по которому это можно было бы заметить, не происходило. Для
// обученной памяти это тихая порча. Тот же дефект на соседнем обычном блоке
// ближайших соседей закрыт накануне тем же способом — собственными копиями на
// границе.
//
// Почему это была именно несогласованность, а не новое решение. Загрузка
// сохранённого указателя уже отдаёт ему собственные массивы: разобранные
// строки чисел превращаются в новые массивы. То есть указатель, пришедший с
// диска, своими векторами владел, а собранный добавлениями — нет. Теперь обе
// дороги ведут к одному: указатель хранит своё.
//
// Как это доказывается. Два маленьких указателя, собранных прямо здесь, с
// буквально выписанными числами. Сначала обычный ответ. Потом нападение со
// стороны входа: меняются те самые ячейки, которые вызывающая сторона
// передала в приём. Между нападением и повторным чтением НЕТ ни добавления,
// ни сохранения с загрузкой, ни перестройки — иначе проверка просто скрыла бы
// порчу. Ожидаемые значения выписаны буквально, а оценки сравниваются по
// битам, чтобы сдвиг в последнем разряде не прошёл молча.
//
// Про пометки отдельно. Через ответ на запрос они наружу не выходят вообще —
// указатель возвращает только опознаватель и оценку. Единственная дверь, за
// которой их видно, — штатное сохранение. Поэтому нападение на словарь
// доказывается сравнением сохранённых байтов: сохранение состояние не меняет,
// это чтение, а не перестройка.
//
// Бюджет этой проверки. Ноль обучений, ноль пар предпочтений, ноль обращений
// к модели. Пять добавлений всего, шесть запросов и два сохранения в отдельную
// временную папку прогона.
//
// Чего это покрытие НЕ доказывает. Оно не закрывает не-числа и бесконечности:
// вектор нужной длины из таких значений по-прежнему принимается. Оно не
// доказывает отката на середине добавления. Оно не доказывает владения у
// соседнего простого указателя `BruteForceIndex`, где приём устроен так же, —
// это отдельная работа. И оно ничего не говорит о работе из нескольких
// потоков: у класса такого договора нет.

namespace LlmFromScratch.Tests.ExperimentFixes;

using VectorSearch;

public sealed class NativeHnswStoredMemoryOwnershipTests
{
    // ── Нападение на массив со стороны входа ─────────────────────────────────

    [Fact]
    public void StoredVectorKeepsItsOwnMemory_WhenCallerChangesTheSameArray()
    {
        // Массив вызывающей стороны: именно его ячейки потом и будут менять.
        var callerVector = new[] { 1f, 0f };

        // Два указателя-строки: первая совпадает с запросом, вторая заметно
        // в стороне, поэтому порядок ответа однозначен и устойчив.
        var index = new HnswIndex(m: 4, efConstruction: 10, efSearch: 10);
        index.Add(callerVector, "совпадает");
        index.Add([0.6f, 0.8f], "в-стороне");

        // Чтение первое: обычный ответ до любого нападения.
        var before = Answer(index, [1f, 0f]);
        // Ожидание выписано буквально: сначала точное совпадение с оценкой 1,
        // затем дальняя строка с оценкой 0,6.
        Assert.Equal("совпадает:1;в-стороне:0.6", before);

        // Нападение со стороны входа: вызывающая сторона разворачивает свой
        // массив в другую сторону, прямо в тех же ячейках.
        callerVector[0] = 0f;
        callerVector[1] = 1f;

        // Чтение второе: между нападением и этим чтением не было ни добавления,
        // ни сохранения с загрузкой, ни перестройки указателя.
        var after = Answer(index, [1f, 0f]);
        // Ответ обязан быть прежним. При общем массиве первая строка стала бы
        // перпендикулярной запросу, её оценка упала бы с 1 до 0, и первой
        // оказалась бы «в-стороне» — то есть сменились бы и порядок, и числа.
        Assert.Equal(before, after);
        Assert.Equal("совпадает:1;в-стороне:0.6", after);
    }

    // ── Нападение на словарь пометок со стороны входа ────────────────────────

    [Fact]
    public void StoredMetadataKeepsItsOwnValues_WhenCallerChangesTheSameDictionary()
    {
        // Словарь вызывающей стороны: его и будут менять после приёма. Ключи и
        // значения записаны латиницей намеренно: сохранение экранирует буквы
        // вне латиницы в вид \uXXXX, и тогда поиск подстроки в сохранённых
        // байтах ничего бы не доказал.
        var callerMetadata = new Dictionary<string, string>
        {
            ["source"] = "original",
            ["lock"] = "original"
        };

        // Один указатель с одной строкой и этими пометками.
        var index = new HnswIndex(m: 4, efConstruction: 10, efSearch: 10);
        index.Add([1f, 0f], "row", callerMetadata);

        // Снимок состояния до нападения: сохранение только читает состояние.
        var before = SaveToBytes(index, "до");
        // Пометки действительно попали в сохранённое состояние.
        Assert.Contains("original", System.Text.Encoding.UTF8.GetString(before));

        // Нападение со стороны входа: меняется прежнее значение и добавляется
        // ключ, которого при приёме не было.
        callerMetadata["source"] = "BROKEN";
        callerMetadata["added-key"] = "BROKEN";

        // Снимок после нападения: между ними не было ни добавления, ни загрузки.
        var after = SaveToBytes(index, "после");

        // Байт в байт то же состояние: ни изменённое значение, ни новый ключ
        // внутрь не прошли.
        Assert.Equal(before, after);
        var text = System.Text.Encoding.UTF8.GetString(after);
        Assert.DoesNotContain("BROKEN", text);
        Assert.DoesNotContain("added-key", text);
        Assert.Contains("original", text);
    }

    // ── Выдача: наружу не уходит ничего из памяти указателя ──────────────────

    [Fact]
    public void AnswerIsNotTheIndexOwnState_AndNothingStoredLeavesThroughIt()
    {
        // Маленький указатель из двух строк.
        var index = new HnswIndex(m: 4, efConstruction: 10, efSearch: 10);
        index.Add([1f, 0f], "первая");
        index.Add([0f, 1f], "вторая");

        // Обычный ответ: это список пар «опознаватель и оценка».
        var hits = index.Search([1f, 0f], topK: 2);
        Assert.Equal(2, hits.Count);

        // Нападение со стороны выхода: вызывающая сторона распоряжается
        // полученным списком как своим — меняет и опустошает его.
        hits[0] = ("СЛОМАНО", -1f);
        hits.Clear();

        // Повторное чтение без переобучения и перезагрузки даёт прежний ответ:
        // отданный список был собственным списком вызывающей стороны, а не
        // внутренним состоянием указателя.
        Assert.Equal("первая:1;вторая:0", Answer(index, [1f, 0f]));

        // Два разных ответа не делят между собой один и тот же список.
        Assert.NotSame(index.Search([1f, 0f], topK: 2), index.Search([1f, 0f], topK: 2));

        // Больше у указателя наружу ничего и не выходит. Открытых членов ровно
        // шесть: счётчик строк, задание ширины поиска, приём, запрос,
        // сохранение в файл и загрузка из файла. Счётчик — число; задание
        // ширины ничего не возвращает; приём ничего не возвращает; запрос
        // возвращает новый список из неизменяемых строк и чисел; сохранение
        // пишет байты в файл; загрузка строит новый указатель. Ни один из них
        // не отдаёт наружу ни хранимый массив, ни словарь пометок, ни
        // внутренний список — поэтому на выдаче закрывать нечего.
        var surface = typeof(HnswIndex)
            .GetMethods(System.Reflection.BindingFlags.Public
                | System.Reflection.BindingFlags.Instance
                | System.Reflection.BindingFlags.Static
                | System.Reflection.BindingFlags.DeclaredOnly)
            .Where(method => !method.IsSpecialName)
            .Select(method => method.Name)
            .OrderBy(name => name, StringComparer.Ordinal)
            .ToArray();
        // Если у класса появится новый открытый член, эта проверка остановит
        // работу и потребует заново решить вопрос владения на выдаче.
        Assert.Equal(["Add", "Load", "Save", "Search", "SetEfSearch"], surface);
        // Открытое свойство ровно одно, и это число: счётчик хранимых строк.
        var properties = typeof(HnswIndex)
            .GetProperties(System.Reflection.BindingFlags.Public
                | System.Reflection.BindingFlags.Instance
                | System.Reflection.BindingFlags.Static
                | System.Reflection.BindingFlags.DeclaredOnly);
        Assert.Equal(["Count"], properties.Select(property => property.Name).ToArray());
        Assert.Equal(typeof(int), properties[0].PropertyType);
        // Открытых полей у класса нет вовсе: вся память спрятана.
        Assert.Empty(typeof(HnswIndex).GetFields(System.Reflection.BindingFlags.Public
            | System.Reflection.BindingFlags.Instance
            | System.Reflection.BindingFlags.Static
            | System.Reflection.BindingFlags.DeclaredOnly));
    }

    // ── Вспомогательное ──────────────────────────────────────────────────────

    // Один ответ указателя в виде строки: опознаватели и оценки. Оценка
    // печатается до пятого знака и всегда с точкой как разделителем, чтобы
    // запись читалась человеком и не зависела от языка машины; сравнение при
    // этом ловит и смену порядка, и смену значения.
    private static string Answer(HnswIndex index, float[] query) =>
        string.Join(
            ";",
            index.Search(query, topK: 3)
                .Select(hit => hit.id + ":" + hit.score.ToString(
                    "0.#####", System.Globalization.CultureInfo.InvariantCulture)));

    // Полный снимок состояния через штатное сохранение: пометки видны только так.
    private static byte[] SaveToBytes(HnswIndex index, string label)
    {
        var path = Path.Combine(RunDirectory.Value, $"state-{label}-{Guid.NewGuid():N}.json");
        index.Save(path);
        return File.ReadAllBytes(path);
    }

    // Отдельная временная папка прогона: в хранилище эта проверка ничего не пишет.
    private static readonly Lazy<string> RunDirectory = new(() =>
    {
        var path = Path.Combine(Path.GetTempPath(), $"xiigen-r29-hnsw-ownership-{Guid.NewGuid():N}");
        Directory.CreateDirectory(path);
        return path;
    });
}
