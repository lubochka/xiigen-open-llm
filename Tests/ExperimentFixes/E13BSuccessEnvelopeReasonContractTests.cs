// Постоянное покрытие договора «признак исхода в УСПЕШНОМ конверте ответа памяти
// формул не имеет права означать воздержание» для проверки опыта на закрытых
// формулах (файл 35.ExperimentsV2/Experiments/E13BHeldOutValidation.cs).
//
// Что здесь проверяется по-человечески. В проекте есть маленькая обучаемая
// память формул: её учат целыми записями вида «Выручка минус Затраты равно
// Прибыль», а потом по левой части она возвращает правую. Опыт на закрытых
// формулах для каждого предъявления записывает признак исхода — короткое слово о
// том, что именно случилось. Таких исходов по сути три, а не два:
//   1. память ответила и ответ зачтён совпадением — «точное совпадение»;
//   2. память честно отказалась отвечать, потому что такой формулы не учила, —
//      «формула не встречалась», и это и есть воздержание;
//   3. память ответила, но ответ не зачтён совпадением — «ответ есть, но не
//      совпал».
//
// Что было сломано. В успешном конверте ответа признак выбирался всего из двух
// значений: совпало — «точное совпадение», не совпало — «формула не
// встречалась». Третий исход сливался со вторым, то есть неверный ответ памяти
// записывался в графу честных отказов. Это прямая ошибка диагностики: «память
// промолчала» и «память ответила неверно» — разные события, и отчёт запускателя
// печатает именно это слово.
//
// Чем это опасно по числам. Опубликованная 31.10 починка считает долю
// воздержания ПО ЭТОМУ признаку, а не как «единица минус доля совпадений» —
// ровно для того, чтобы сорванное обращение к памяти не засчитывалось успехом.
// Поэтому ошибочный признак в успешной ветке напрямую раздувает долю
// воздержания неответами, и условие успеха прогона закрылось бы само собой.
//
// Насколько это действующая поломка. Не действующая. Через настоящую рабочую
// поверхность успешный конверт без совпадения сегодня недостижим: память формул
// отвечает успехом только когда нашла значение, и тогда уверенность всегда
// единица, а значение ответа непусто; промах она сообщает типизированным
// отказом. Значит, это неверное значение по умолчанию в защите, а не ошибка в
// сегодняшних числах опыта. Чинится оно до того, как путь станет достижимым.
//
// Как недостижимая ветка стала проверяемой. Подделывать путь правкой
// продуктовой логики наряд запрещает. Поэтому сам разрешитель признака для
// успешного конверта вынесен в отдельный метод продукта, и проверки обращаются
// ровно к нему, а не к общему прогону опыта. Вынос — законная часть починки: он
// и делает поведение проверяемым.
//
// Бюджет. Ни одного прогона опыта, ни одного обучения, ни одного обращения к
// памяти формул, ни одного обращения к диску, ни одной внешней модели, ни одной
// пары предпочтений. Проверки вызывают два коротких подсчётных метода продукта.
//
// Чего это покрытие НЕ доказывает. Оно не доказывает, что память формул умеет
// выводить новые формулы, и не измеряет качество обучения. Оно также не
// доказывает, что обе успешные ветки записи результата действительно зовут
// вынесенный разрешитель, а не хранят прежнее выражение на месте: недостижимую
// ветку нельзя предъявить через рабочую поверхность, а подмену поверхности
// заглушкой наряд запрещает. Для этого одного вопроса доказательством остаётся
// чтение правки продукта.

using System.Reflection;

using ExperimentsV2;

namespace LlmFromScratch.Tests.ExperimentFixes;

public sealed class E13BSuccessEnvelopeReasonContractTests
{
    // Признак воздержания: формула в уроках не встречалась. Именно по нему
    // считается доля воздержания, поэтому в успешном конверте его быть не может.
    private const string NotSeenReason = "expression_not_seen";

    // Признак совпадения: ответ пришёл из выученной памяти.
    private const string ExactMatchReason = "exact_match";

    // Признак сбоя: обращение к памяти сорвалось. Это не воздержание и не ответ.
    private const string ExecutionFailedReason = "execution_failed";

    // Третий признак, которого не хватало: память ответила, но ответ не зачтён
    // совпадением. Человеческое значение обязано отличать «ответил неверно» от
    // «не ответил», поэтому слово «не встречалась» здесь недопустимо.
    private const string AnsweredNotMatchedReason = "answered_not_matched";

    // Имя вынесенного разрешителя признака для успешного конверта. Берётся по
    // имени, а не через точку: до правки продукта такого метода нет вовсе, и
    // красным обязано стать утверждение проверки, а не сборка проекта проверок.
    private const string SuccessEnvelopeReasonName = "SuccessEnvelopeReason";

    // Имя подсчётного метода доли воздержания. Это уже работающий метод
    // опубликованной 31.10 починки; он здесь не меняется, а используется как
    // настоящий потребитель признака.
    private const string AbstainRateName = "AbstainRate";

    // ── Главные проверки починки ─────────────────────────────────────────────
    // Проверка первая. Разрешитель признака для успешного конверта обязан
    // существовать отдельным методом: иначе недостижимую ветку нельзя
    // предъявить ни одной проверке, и неверное значение по умолчанию живёт в
    // защите вечно.
    [Fact]
    public void SuccessEnvelopeReason_IsASeparateResolverWithExpectedShape()
    {
        var method = SuccessEnvelopeReasonMethod();

        Assert.Equal(typeof(string), method.ReturnType);

        var parameters = method.GetParameters();

        Assert.Single(parameters);

        Assert.Equal(typeof(bool), parameters[0].ParameterType);
    }

    // Проверка вторая. Главная. Успешный конверт без совпадения не имеет права
    // получить признак воздержания: память в этом случае ОТВЕТИЛА, просто ответ
    // не зачтён совпадением, а воздержание — это отказ отвечать.
    [Fact]
    public void SuccessEnvelopeWithoutMatch_DoesNotGetTheAbstentionReason()
    {
        var reason = ResolveSuccessEnvelopeReason(matched: false);

        Assert.False(
            string.Equals(reason, NotSeenReason, StringComparison.Ordinal),
            "В успешном конверте память формул ответила, поэтому её исход не " +
            "имеет права называться воздержанием «формула не встречалась». " +
            $"Разрешитель вернул '{reason}'.");
    }

    // Проверка третья. У этого исхода обязан быть СВОЙ признак, а не чужой: ни
    // признак совпадения, ни признак сбоя исполнения сюда не подходят, и пустое
    // слово тоже не подходит. Значение выписано буквально, потому что отчёт
    // запускателя печатает именно его.
    [Fact]
    public void SuccessEnvelopeWithoutMatch_GetsItsOwnThirdReason()
    {
        var reason = ResolveSuccessEnvelopeReason(matched: false);

        Assert.False(
            string.IsNullOrWhiteSpace(reason),
            "Признак исхода не имеет права быть пустым: отчёт опыта печатает " +
            "его как слово о том, что случилось.");

        Assert.False(
            string.Equals(reason, ExactMatchReason, StringComparison.Ordinal),
            "Несовпавший ответ не имеет права называться точным совпадением. " +
            $"Разрешитель вернул '{reason}'.");

        Assert.False(
            string.Equals(reason, ExecutionFailedReason, StringComparison.Ordinal),
            "Успешный конверт означает, что обращение к памяти состоялось, " +
            "поэтому его исход не имеет права называться сбоем исполнения. " +
            $"Разрешитель вернул '{reason}'.");

        Assert.Equal(AnsweredNotMatchedReason, reason);
    }

    // Проверка четвёртая. Доля воздержания обязана остаться нулевой на строке
    // «ответ есть, но не совпал»: такая строка не промолчала, значит в долю
    // честного молчания она не входит. Подсчёт берётся настоящий, продуктовый.
    [Fact]
    public void AbstainRate_DoesNotCountTheAnsweredNotMatchedRow()
    {
        var row = RowWithReason(ResolveSuccessEnvelopeReason(matched: false));

        var abstainRate = AbstainRate(row);

        Assert.Equal(0.0, abstainRate);
    }

    // Проверка пятая. Та же беда на смешанном наборе, где видно само раздувание:
    // одна строка честно промолчала, вторая ответила не тем — доля воздержания
    // обязана быть половиной, а не единицей.
    [Fact]
    public void AbstainRate_OnMixedRows_IsOneHalf_NotOne()
    {
        var abstained = RowWithReason(NotSeenReason);
        var answeredNotMatched = RowWithReason(ResolveSuccessEnvelopeReason(matched: false));

        var abstainRate = AbstainRate(abstained, answeredNotMatched);

        Assert.Equal(0.5, abstainRate);
    }

    // ── Защита от перекоррекции ──────────────────────────────────────────────
    // Проверка шестая. Совпавший успешный конверт не имеет права пострадать от
    // починки: его признак остаётся точным совпадением. Если бы починка назвала
    // третьим признаком любой успешный конверт вообще, эта проверка покраснела
    // бы, и вместе с ней покраснели бы обучающее плечо и выученные варианты
    // записи в соседних классах проверок.
    [Fact]
    public void SuccessEnvelopeWithMatch_StillGetsExactMatch()
    {
        var reason = ResolveSuccessEnvelopeReason(matched: true);

        Assert.Equal(ExactMatchReason, reason);
    }

    // Проверка седьмая. Опора проверок четвёртой и пятой: сам подсчёт доли
    // воздержания по-прежнему умеет считать воздержание. Без этой опоры нулевая
    // доля в проверке четвёртой могла бы означать не починку признака, а
    // сломанный подсчёт, который не считает вообще ничего.
    [Fact]
    public void AbstainRate_StillCountsTheAbstentionRow()
    {
        var abstainRate = AbstainRate(RowWithReason(NotSeenReason));

        Assert.Equal(1.0, abstainRate);
    }

    // ── Общие вызовы продуктовых методов ─────────────────────────────────────
    // Разрешитель признака для успешного конверта. Имя ищется среди закрытых
    // статических методов единицы опыта.
    private static MethodInfo SuccessEnvelopeReasonMethod()
    {
        var method = typeof(E13BHeldOutValidation).GetMethod(
            SuccessEnvelopeReasonName,
            BindingFlags.NonPublic | BindingFlags.Static);

        Assert.True(
            method is not null,
            $"Разрешитель признака исхода для успешного конверта ('{SuccessEnvelopeReasonName}') " +
            "не вынесен в отдельный метод единицы опыта на закрытых формулах. " +
            "Пока он остаётся выражением внутри ветки записи результата, " +
            "недостижимый случай «ответ есть, но не совпал» нельзя предъявить " +
            "ни одной проверке.");

        return method!;
    }

    // Вызов разрешителя признака с одним признаком совпадения на входе.
    private static string ResolveSuccessEnvelopeReason(bool matched)
        => (string)SuccessEnvelopeReasonMethod().Invoke(null, [matched])!;

    // Вызов настоящего продуктового подсчёта доли воздержания на выписанном
    // наборе строк результата.
    private static double AbstainRate(params E13BExpressionEvaluation[] rows)
    {
        var method = typeof(E13BHeldOutValidation).GetMethod(
            AbstainRateName,
            BindingFlags.NonPublic | BindingFlags.Static);

        Assert.True(
            method is not null,
            $"Подсчёт доли воздержания ('{AbstainRateName}') не найден в единице " +
            "опыта на закрытых формулах: без него нельзя показать, что новый " +
            "признак исхода не попадает в долю честного молчания.");

        return (double)method!.Invoke(null, [rows])!;
    }

    // Строка результата с заданным признаком исхода. Остальные поля заполнены
    // согласованно для случая «память ответила, но ответ не зачтён совпадением»:
    // значения ответа нет, уверенности нет, правильной строка не считается.
    // Подсчёт доли воздержания читает только признак исхода, поэтому именно он
    // здесь и важен.
    private static E13BExpressionEvaluation RowWithReason(string reason)
        => new(
            Expression: "Signal + Threshold = Alert",
            Partial: "Signal + Threshold =",
            Expected: "Alert",
            Predicted: "",
            Matched: false,
            Correct: false,
            Confidence: 0.0,
            Reason: reason);
}
