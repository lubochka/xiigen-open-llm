// ОБЩИЙ ПРИЁМНИК ДОКАЗАТЕЛЬСТВ ОПЫТОВ. Одно место, где решается ЕДИНСТВЕННЫЙ вопрос:
// куда испытанию опыта разрешено писать свои файлы доказательств.
//
// Какую беду это закрывает, человеческими словами. Испытания опытов сами пишут файлы
// доказательств, и каждое испытание до этой правки держало свой приватный способ записи с
// жёстко названным каталогом попытки. Пока попытка не опубликована, это безвредно. Но как
// только попытка закоммичена, каталог становится опубликованным наблюдением — и следующий
// прогон того же испытания молча перезаписывает чужие опубликованные байты. Проверить опыт
// становится невозможно, не испортив его. Ровно это наблюдалось лично: проверочный прогон
// опыта о тёплом старте пробной сети переписал три из восьми опубликованных файлов третьей
// попытки, и байты пришлось восстанавливать из коммита руками.
//
// Что здесь делается вместо этого. Перед первой записью приёмник спрашивает хранилище,
// отслеживает ли оно файлы внутри назначенного каталога. Отслеживает — значит каталог
// опубликован, и писать в него запрещено. Дальше поведение задаёт политика: либо прогон
// заметно перенаправляется в свежий каталог результатов испытаний, либо запись заметно
// отклоняется исключением. Молчаливое «ничего не записал» невозможно ни в одном из двух
// путей.
//
// Что здесь НЕ делается, и это важно для честности измерений. Приёмник не меняет НИ ОДНОГО
// байта содержимого: он не добавляет заголовков, не переписывает переводы строк и не
// нормализует текст. Нормализацию по-прежнему делает само испытание до вызова записи.
// Поэтому побитовое сравнение нового прогона с опубликованным файлом остаётся законным
// способом доказать точное воспроизведение — именно так и проверялся опыт о тёплом старте.
// Меняется только КУДА пишется прогон, а не ЧТО он измеряет.

/// <summary>Что делать, когда назначенный каталог доказательств уже опубликован.</summary>
public enum PublishedEvidencePolicy
{
    /// <summary>Перенаправить прогон в свежий каталог и заметно сообщить об этом.</summary>
    RedirectToFreshRunDirectory = 0,

    /// <summary>Отклонить запись заметным исключением с точным путём и причиной.</summary>
    RefuseToWrite = 1,
}

/// <summary>Отказ записи в опубликованный каталог доказательств: виден как исключение.</summary>
public sealed class PublishedEvidenceWriteRefusedException : Exception
{
    /// <summary>Создаёт отказ с готовым человеческим объяснением.</summary>
    /// <param name="message">Текст отказа: что нельзя, где именно и почему.</param>
    public PublishedEvidenceWriteRefusedException(string message) : base(message)
    {
    }
}

// ИСКЛЮЧИТЕЛЬНОЕ ВЛАДЕНИЕ ПОПЫТКОЙ. Вторая беда, которую закрывает этот файл, отличается от
// первой. Первая была про ОПУБЛИКОВАННЫЙ каталог: его защищает вопрос к хранилищу. Вторая —
// про каталог, который хранилище ещё не отслеживает, но который уже занят: в него прямо сейчас
// пишет другой прогон того же опыта, либо в нём лежит прерванная попытка, которую никто не
// завершил. Проверка «каталога нет» и «хранилище про него не знает» обе отвечают «свободно», и
// два прогона спокойно пишут в один адрес, а прерванная попытка молча затирается. После этого
// сказать, какой прогон оставил какие байты, невозможно.
//
// Что делается вместо этого. Владелец получает каталог записи и СРАЗУ создаёт в нём файл-маркер
// владения режимом «создать только если файла ещё нет». Такое создание файла неделимо на уровне
// файловой системы, поэтому из двух одновременных прогонов маркер получает ровно один, а второй
// узнаёт об отказе до того, как подготовит данные и начнёт обучение. Проверка «файл есть?» с
// последующей обычной записью исключительностью НЕ является и здесь запрещена: между проверкой и
// записью успевает вклиниться другой прогон.
//
// Чего этот ремонт НЕ обещает. Он не обещает стойкости к потере питания. Если машину выключат
// посреди записи, файловая система может оставить каталог в любом промежуточном состоянии; такая
// гарантия требует отдельного протокола долговечной фиксации и здесь не заявляется.

/// <summary>Отказ занять попытку: каталог записи принадлежит другому прогону или прерван.</summary>
public sealed class ExperimentAttemptOwnershipRefusedException : Exception
{
    /// <summary>Создаёт отказ с готовым человеческим объяснением.</summary>
    /// <param name="message">Текст отказа: какой каталог занят, кем и почему перезапись запрещена.</param>
    public ExperimentAttemptOwnershipRefusedException(string message) : base(message)
    {
    }

    /// <summary>Создаёт отказ с человеческим объяснением и сохранённой причиной файловой системы.</summary>
    /// <param name="message">Текст отказа: какой каталог или файл занят и почему запись запрещена.</param>
    /// <param name="innerException">Исходная ошибка файловой системы: она не теряется.</param>
    public ExperimentAttemptOwnershipRefusedException(string message, Exception innerException)
        : base(message, innerException)
    {
    }
}

/// <summary>Отказ записи за пределы каталога записи: относительный путь уводил наружу.</summary>
public sealed class EvidencePathEscapesWriteRootException : Exception
{
    /// <summary>Создаёт отказ с готовым человеческим объяснением.</summary>
    /// <param name="message">Текст отказа: какой путь просили, какой каталог записи разрешён.</param>
    public EvidencePathEscapesWriteRootException(string message) : base(message)
    {
    }
}

/// <summary>Куда испытанию опыта разрешено писать доказательства этого прогона.</summary>
public sealed class ExperimentEvidenceSink
{
    /// <summary>Сколько миллисекунд ждать ответа хранилища о отслеживаемых файлах.</summary>
    private const int RepositoryProbeTimeoutMilliseconds = 20_000;

    /// <summary>Кодировка записи: метка порядка байтов не пишется никогда.</summary>
    private static readonly UTF8Encoding Utf8WithoutByteOrderMark = new(encoderShouldEmitUTF8Identifier: false);

    /// <summary>Имя файла-маркера владения: его неделимое создание и есть захват каталога.</summary>
    public const string AttemptOwnerMarkerFileName = "владение-попыткой.json";

    /// <summary>Имя файла завершения попытки: без него попытка считается прерванной.</summary>
    public const string AttemptCompletionFileName = "завершение-попытки.json";

    /// <summary>Имя файла промежуточного статуса владельца: он перезаписывается намеренно.</summary>
    public const string OwnerStatusFileName = "статус-владельца.json";

    /// <summary>Имя дописываемого журнала прогона: он растёт, а не перезаписывается.</summary>
    public const string RunJournalFileName = "журнал-прогона.log";

    /// <summary>Имя файла-подсказки: он объясняет человеку, где лежат улики этого прогона.</summary>
    public const string EvidenceLocationHintFileName = "где-лежат-доказательства.txt";

    /// <summary>Хвост имени временного файла: по нему уборка узнаёт свои файлы и только их.</summary>
    private const string TemporaryWriteSuffix = ".частичная-запись";

    /// <summary>Настройки записи маркера: русский текст остаётся читаемым, перевод строки один.</summary>
    private static readonly JsonSerializerOptions MarkerJsonOptions = new()
    {
        WriteIndented = true,                             // Человек читает маркер глазами, поэтому отступы нужны.
        Encoder = JavaScriptEncoder.UnsafeRelaxedJsonEscaping, // Русские пояснения не превращаются в \uXXXX.
    };

    /// <summary>Опознание этого прогона: одно на процесс, чтобы все приёмники звались одинаково.</summary>
    //
    // Почему опознание берётся из окружения, когда оно задано. Внешний запускатель знает больше
    // приёмника: он знает номер наряда, сборку и фильтр проверок. Если он передал опознание, в
    // маркере будет именно оно, и человек свяжет каталог с конкретным запуском. Если не передал,
    // опознание рождается здесь и всё равно отличает этот процесс от любого другого.
    private static readonly string CurrentRunIdentifier =
        ReadEnvironmentOrDefault("XIIGEN_EVIDENCE_RUN_ID", () => "run-" + Guid.NewGuid().ToString("N"));

    /// <summary>Назначенный каталог доказательств: он же опубликованный, если уже в хранилище.</summary>
    private readonly string _declaredDirectory;

    /// <summary>Каталог, в который этот прогон действительно пишет.</summary>
    private readonly string _writeRoot;

    /// <summary>Человеческая причина решения: почему каталог признан опубликованным или нет.</summary>
    private readonly string _reason;

    /// <summary>Чем кончился выбор каталога записи для этого прогона.</summary>
    private readonly WriteRootDecision _decision;

    /// <summary>Опознание прогона, который владеет этим каталогом записи.</summary>
    private readonly string _runIdentifier;

    /// <summary>Защёлка однократного показа сообщения: оно не дублируется на каждый файл.</summary>
    private int _noticeAlreadyShown;

    /// <summary>Собирает приёмник из уже принятого решения о каталоге записи.</summary>
    /// <param name="declaredDirectory">Каталог, назначенный карточкой опыта.</param>
    /// <param name="writeRoot">Каталог, в который фактически пишет этот прогон.</param>
    /// <param name="reason">Человеческая причина выбора каталога записи.</param>
    /// <param name="decision">Чем кончился выбор каталога записи: назначенный или уход.</param>
    /// <param name="runIdentifier">Опознание прогона, захватившего каталог записи.</param>
    private ExperimentEvidenceSink(
        string declaredDirectory, string writeRoot, string reason, WriteRootDecision decision, string runIdentifier)
    {
        _declaredDirectory = declaredDirectory; // Назначенный каталог запоминается для сообщений.
        _writeRoot = writeRoot;                 // Фактический каталог записи этого прогона.
        _reason = reason;                       // Причина решения, читаемая человеком.
        _decision = decision;                   // Остался прогон в назначенном каталоге или был уведён.
        _runIdentifier = runIdentifier;         // Кто именно владеет этим каталогом записи.
    }

    /// <summary>Три возможных исхода выбора каталога записи для одного прогона.</summary>
    private enum WriteRootDecision
    {
        /// <summary>Назначенный каталог был свободен и захвачен этим прогоном.</summary>
        DeclaredDirectoryOwned = 0,

        /// <summary>Назначенный каталог отслеживается хранилищем, прогон уведён в свежий каталог.</summary>
        RedirectedFromPublishedEvidence = 1,

        /// <summary>Назначенный каталог занят чужой или прерванной попыткой, прогон уведён.</summary>
        RedirectedFromOccupiedAttempt = 2,
    }

    /// <summary>Опознание прогона-владельца: им подписаны маркер и завершение попытки.</summary>
    public string OwnerRunIdentifier => _runIdentifier;

    /// <summary>Полный путь файла-маркера владения внутри каталога записи этого прогона.</summary>
    public string AttemptOwnerMarkerPath => Path.Combine(_writeRoot, AttemptOwnerMarkerFileName);

    /// <summary>Каталог, в который этот прогон пишет файлы доказательств.</summary>
    public string WriteRoot => _writeRoot;

    /// <summary>Назначенный карточкой каталог доказательств, как он объявлен в испытании.</summary>
    public string DeclaredDirectory => _declaredDirectory;

    /// <summary>Истина, когда прогон уведён из уже опубликованного каталога.</summary>
    public bool RedirectedFromPublishedEvidence => _decision == WriteRootDecision.RedirectedFromPublishedEvidence;

    /// <summary>Истина, когда прогон уведён из каталога, занятого чужой или прерванной попыткой.</summary>
    public bool RedirectedFromOccupiedAttempt => _decision == WriteRootDecision.RedirectedFromOccupiedAttempt;

    /// <summary>Истина для любого ухода из назначенного каталога, независимо от причины ухода.</summary>
    public bool RedirectedFromDeclaredDirectory => _decision != WriteRootDecision.DeclaredDirectoryOwned;

    /// <summary>Человеческая причина выбора каталога записи.</summary>
    public string Reason => _reason;

    /// <summary>Готовое человеческое сообщение о том, куда и почему пишется этот прогон.</summary>
    //
    // Почему сообщение называет род прогона, а не только путь. Прямое правило владельца:
    // доказательства и проверки подаются в хранилище, а не стираются. Поэтому запись опыта и
    // проверка опыта — два разных рода прогона, и читатель обязан видеть, какой из них перед
    // ним. Запись опыта создаёт наблюдение и остаётся в хранилище. Проверочный прогон только
    // перечитывает уже опубликованное наблюдение и не имеет права его трогать; его файлы
    // новым наблюдением опыта не являются и в хранилище как попытка не подаются.
    //
    // Почему у ухода две разные причины и два разных текста. Уход из ОПУБЛИКОВАННОГО каталога —
    // это проверочный прогон поверх чужого наблюдения, уже поданного в хранилище. Уход из
    // ЗАНЯТОГО каталога — это столкновение двух прогонов за один адрес или прерванная попытка,
    // которую никто не завершил. Для человека это разные события, поэтому сообщение называет
    // именно то, что произошло, а не общее слово «перенаправлено».
    public string Notice => _decision switch
    {
        WriteRootDecision.RedirectedFromOccupiedAttempt => string.Join("\n",
            "КАТАЛОГ ПОПЫТКИ ЗАНЯТ: чужая или прерванная попытка не перезаписывается.",
            "Назначенный каталог оставлен без изменений ни на байт: " + _declaredDirectory,
            "Почему так решено: " + _reason,
            "Файлы этого прогона пишутся сюда: " + _writeRoot,
            "Опознание прогона-владельца: " + _runIdentifier,
            "Чтобы записать НОВОЕ наблюдение опыта, назначьте в карточке свободный номер попытки.",
            "Стойкость к потере питания этим механизмом не обещается."),

        WriteRootDecision.RedirectedFromPublishedEvidence => string.Join("\n",
            "ПРОВЕРОЧНЫЙ ПРОГОН ОПЫТА: опубликованное наблюдение не перезаписывается.",
            "Это проверка уже опубликованной попытки, а НЕ новая запись опыта.",
            "Опубликованный каталог оставлен без изменений ни на байт: " + _declaredDirectory,
            "Почему так решено: " + _reason,
            "Файлы этого проверочного прогона пишутся сюда: " + _writeRoot,
            "Этот каталог игнорируется хранилищем намеренно: проверка не публикуется как попытка опыта.",
            "Сравнение с опубликованным наблюдением делается чтением обоих каталогов.",
            "Чтобы записать НОВОЕ наблюдение опыта, назначьте в карточке свободный номер попытки:" +
            " тогда прогон снова пишет в хранилище и подаётся как доказательство."),

        _ => string.Join("\n",
            "ЗАПИСЬ ОПЫТА: доказательства пишутся в назначенную попытку и остаются в хранилище.",
            "Каталог записи: " + _writeRoot,
            "Почему так решено: " + _reason,
            "Опознание прогона-владельца: " + _runIdentifier,
            "Эти файлы — наблюдение опыта; они подаются в хранилище, а не стираются."),
    };

    /// <summary>Решает, куда писать доказательства, и при опубликованном каталоге уводит прогон.</summary>
    /// <param name="repositoryRoot">Корень хранилища проекта.</param>
    /// <param name="declaredDirectory">Каталог доказательств, назначенный карточкой опыта.</param>
    /// <param name="policy">Что делать, если назначенный каталог уже опубликован.</param>
    public static ExperimentEvidenceSink ForDeclaredDirectory(
        string repositoryRoot,
        string declaredDirectory,
        PublishedEvidencePolicy policy = PublishedEvidencePolicy.RedirectToFreshRunDirectory)
    {
        // Пути приводятся к полному виду: решение не должно зависеть от места запуска.
        var root = Path.GetFullPath(repositoryRoot);
        var declared = Path.GetFullPath(declaredDirectory);

        // Единственный вопрос: отслеживает ли хранилище файлы внутри назначенного каталога.
        var published = IsPublishedEvidenceDirectory(root, declared, out var reason);

        // Каталог не опубликован хранилищем. Это ещё не значит, что он свободен: в него может
        // прямо сейчас писать другой прогон или в нём может лежать прерванная попытка.
        if (!published)
        {
            // Второй, независимый вопрос: занят ли каталог записи кем-то ещё.
            var occupied = DescribeOccupiedAttempt(declared);

            // Каталог свободен — пробуем неделимо захватить его файлом-маркером владения.
            if (occupied is null)
            {
                // Захват владения выполняется ДО подготовки данных и обучения: проигравший
                // прогон узнаёт об отказе здесь и не делает ни одного учебного вызова.
                if (TryCaptureAttemptOwnership(root, declared, declared, out var captureFailure))
                    return new ExperimentEvidenceSink(
                        declared, declared, reason, WriteRootDecision.DeclaredDirectoryOwned, CurrentRunIdentifier);

                // Гонку за маркер проиграл этот прогон: причина отказа берётся из попытки захвата.
                occupied = captureFailure;
            }

            // Каталог занят. Политика отказа обязана дать заметное исключение с точным путём.
            if (policy == PublishedEvidencePolicy.RefuseToWrite)
                throw new ExperimentAttemptOwnershipRefusedException(string.Join("\n",
                    "ЗАПИСЬ В ЗАНЯТУЮ ПОПЫТКУ ОПЫТА ОТКЛОНЕНА.",
                    "Каталог попытки принадлежит другому прогону либо содержит прерванную попытку.",
                    "Каталог: " + declared,
                    "Почему нельзя: " + occupied + "; перезапись стёрла бы чужое наблюдение.",
                    "Опознание этого прогона: " + CurrentRunIdentifier,
                    "Что делать: назначить свободный номер попытки либо запустить прогон с" +
                    " перенаправлением в свежий каталог результатов испытаний.",
                    "Стойкость к потере питания этим механизмом не обещается."));

            // Политика разрешает уход — прогон получает свежий каталог и захватывает уже его.
            return RedirectToFreshRunDirectory(
                root, declared, occupied, WriteRootDecision.RedirectedFromOccupiedAttempt);
        }

        // Каталог опубликован, а политика требует заметного отказа — отказываем исключением.
        if (policy == PublishedEvidencePolicy.RefuseToWrite)
            throw new PublishedEvidenceWriteRefusedException(string.Join("\n",
                "ЗАПИСЬ В ОПУБЛИКОВАННУЮ ПОПЫТКУ ОПЫТА ОТКЛОНЕНА.",
                "Это был бы проверочный прогон поверх уже опубликованного наблюдения," +
                " а не новая запись опыта.",
                "Каталог: " + declared,
                "Почему нельзя: " + reason + ";" +
                " перезапись стёрла бы чужое опубликованное наблюдение.",
                "Что делать: назначить в карточке свободный номер попытки, и тогда запись опыта" +
                " снова идёт в хранилище; либо запустить прогон с перенаправлением проверки."));

        // Каталог опубликован, политика разрешает уход — выбираем свежий каталог прогона.
        return RedirectToFreshRunDirectory(
            root, declared, reason, WriteRootDecision.RedirectedFromPublishedEvidence);
    }

    /// <summary>Уводит прогон в свежий каталог результатов испытаний и захватывает его владение.</summary>
    /// <param name="repositoryRoot">Корень хранилища проекта.</param>
    /// <param name="declaredDirectory">Назначенный каталог: он остаётся нетронутым.</param>
    /// <param name="reason">Человеческая причина ухода, уже готовая для сообщения.</param>
    /// <param name="decision">Причина ухода в машинном виде: опубликован или занят.</param>
    //
    // Зачем здесь повторные попытки. Имя свежего каталога содержит метку времени и случайный
    // хвост, поэтому столкновение крайне маловероятно. Но «маловероятно» — не «невозможно», а
    // молчаливого «ничего не записал» быть не должно ни в одной ветке. Поэтому несколько попыток,
    // и только потом заметный отказ исключением.
    private static ExperimentEvidenceSink RedirectToFreshRunDirectory(
        string repositoryRoot, string declaredDirectory, string reason, WriteRootDecision decision)
    {
        // Собираются человеческие причины всех неудачных попыток захвата: их увидит человек.
        var failures = new List<string>();

        // Три попытки: каждая берёт новое уникальное имя каталога прогона.
        for (var attempt = 1; attempt <= 3; attempt++)
        {
            // Свежий каталог прогона внутри игнорируемых хранилищем результатов испытаний.
            var freshRunDirectory = BuildFreshRunDirectory(repositoryRoot, declaredDirectory);

            // Свежий каталог тоже обязан быть захвачен: владение держится на каталоге записи.
            if (TryCaptureAttemptOwnership(
                    repositoryRoot, declaredDirectory, freshRunDirectory, out var captureFailure))
                return new ExperimentEvidenceSink(
                    declaredDirectory, freshRunDirectory, reason, decision, CurrentRunIdentifier);

            // Неудача запоминается вместе с номером попытки и уходит в текст отказа.
            failures.Add("попытка " + attempt + ": " + captureFailure);
        }

        // Все попытки исчерпаны — отказ виден исключением, а не молчаливым отсутствием файлов.
        throw new ExperimentAttemptOwnershipRefusedException(string.Join("\n",
            "СВЕЖИЙ КАТАЛОГ ПРОГОНА ЗАХВАТИТЬ НЕ УДАЛОСЬ.",
            "Назначенный каталог: " + declaredDirectory,
            "Почему пришлось уходить: " + reason,
            "Что мешало захвату: " + string.Join("; ", failures),
            "Опознание этого прогона: " + CurrentRunIdentifier));
    }

    /// <summary>Пишет текст доказательства как есть: содержимое не изменяется ни на байт.</summary>
    /// <param name="relativePath">Имя файла внутри каталога записи этого прогона.</param>
    /// <param name="exactPayload">Готовый текст; нормализацию делает вызывающее испытание.</param>
    public string WriteTextExactly(string relativePath, string exactPayload)
    {
        // Текст превращается в байты той же кодировкой без метки порядка байтов, что и раньше.
        var bytes = Utf8WithoutByteOrderMark.GetBytes(exactPayload);

        // Дальше действует общий однократный путь записи: без перезаписи и видимый целиком.
        return WriteSingleShotBytes(relativePath, bytes);
    }

    /// <summary>Отдаёт полный путь файла в разрешённом каталоге и один раз сообщает о месте записи.</summary>
    /// <param name="relativePath">Имя файла внутри каталога записи этого прогона.</param>
    //
    // Зачем отдельный способ выдать путь. Часть испытаний пишет файл своим кодом: у них свои
    // настройки записи или своя сериализация. Им нужен не способ записи, а разрешённый путь.
    // Сообщение о месте записи показывается здесь же, поэтому уход из опубликованной попытки
    // остаётся заметным и в этом случае тоже.
    public string ResolvePath(string relativePath)
    {
        // Путь проверяется на выход за каталог записи: наружу вести он не имеет права.
        var path = ResolveInsideWriteRoot(relativePath);

        // Каталог под файл создаётся заранее, чтобы вызывающему испытанию осталась только запись.
        Directory.CreateDirectory(Path.GetDirectoryName(path)!);

        // Человек видит род прогона и место записи до того, как файл появится.
        ShowNoticeOnce();

        // Путь возвращается вызывающему испытанию как есть.
        return path;
    }

    /// <summary>Создаёт разрешённый каталог записи и один раз сообщает о месте записи.</summary>
    //
    // Зачем это нужно. Часть испытаний получает КАТАЛОГ показаний и дальше кладёт в него
    // несколько файлов своими способами. Им отдаётся разрешённый каталог, а не назначенный.
    public string EnsureWriteRootDirectory()
    {
        // Каталог записи этого прогона создаётся, если его ещё нет.
        Directory.CreateDirectory(_writeRoot);

        // Человек видит род прогона и место записи до появления первого файла.
        ShowNoticeOnce();

        // Каталог возвращается вызывающему испытанию.
        return _writeRoot;
    }

    /// <summary>Пишет двоичное доказательство как есть: байты не изменяются.</summary>
    /// <param name="relativePath">Имя файла внутри каталога записи этого прогона.</param>
    /// <param name="exactBytes">Готовые байты снимка состояния или указателя.</param>
    public string WriteBytesExactly(string relativePath, byte[] exactBytes)
    {
        // Байты уходят на диск без единого преобразования по тому же однократному пути записи.
        return WriteSingleShotBytes(relativePath, exactBytes);
    }

    /// <summary>Пишет промежуточный статус владельца: этот файл перезаписывать разрешено.</summary>
    /// <param name="exactPayload">Готовый текст статуса; его формирует вызывающее испытание.</param>
    //
    // Почему это отдельная операция, а не та же запись доказательства. Доказательство опыта
    // однократно: его перезапись стирает наблюдение. Промежуточный статус владельца — наоборот,
    // живая величина: «стадия 3 из 7», «обучено 40 строк». Смешивать их в одном методе нельзя,
    // иначе однократность доказательства придётся ослабить ради статуса.
    public string WriteOwnerStatus(string exactPayload)
    {
        // Статус владельца всегда лежит в корне каталога записи под своим постоянным именем.
        var path = ResolveInsideWriteRoot(OwnerStatusFileName);

        // Каталог записи создаётся, если его ещё нет.
        Directory.CreateDirectory(_writeRoot);

        // Статус именно перезаписывается: прежнее значение стадии ценности не имеет.
        File.WriteAllText(path, exactPayload, Utf8WithoutByteOrderMark);

        // Человек видит род прогона и место записи до появления первого доказательства.
        ShowNoticeOnce();

        // Полный путь возвращается для ссылки в журнале прогона.
        return path;
    }

    /// <summary>Дописывает строку в журнал прогона: журнал растёт, а не перезаписывается.</summary>
    /// <param name="exactLine">Готовая строка журнала без перевода строки на конце.</param>
    public string AppendJournalLine(string exactLine)
    {
        // Журнал прогона тоже лежит в корне каталога записи под постоянным именем.
        var path = ResolveInsideWriteRoot(RunJournalFileName);

        // Каталог записи создаётся, если его ещё нет.
        Directory.CreateDirectory(_writeRoot);

        // Строка дописывается с переводом строки, так что прежние строки остаются целыми.
        File.AppendAllText(path, exactLine + "\n", Utf8WithoutByteOrderMark);

        // Человек видит род прогона и место записи до появления первого доказательства.
        ShowNoticeOnce();

        // Полный путь возвращается для ссылки в отчёте.
        return path;
    }

    /// <summary>Помечает попытку завершённой: без этого файла попытка считается прерванной.</summary>
    /// <param name="exactPayload">Готовый текст итога попытки; его формирует вызывающее испытание.</param>
    //
    // Зачем нужен отдельный файл завершения. Маркер владения говорит только «каталог занят». Он
    // появляется ДО подготовки данных, поэтому по нему нельзя отличить работающий прогон от
    // прогона, который убили на середине. Файл завершения ставит точку: он появляется последним,
    // и его отсутствие рядом с маркером — честный признак прерванной попытки.
    public string CompleteAttempt(string exactPayload)
    {
        // Файл завершения однократен: вторая попытка завершить ту же попытку — это ошибка.
        return WriteSingleShotBytes(AttemptCompletionFileName, Utf8WithoutByteOrderMark.GetBytes(exactPayload));
    }

    /// <summary>Пишет однократный файл доказательства: без перезаписи и видимым целиком.</summary>
    /// <param name="relativePath">Имя файла внутри каталога записи этого прогона.</param>
    /// <param name="exactBytes">Готовые байты; приёмник их не преобразует.</param>
    //
    // Почему запись идёт через временный файл и переименование. Читатель может открыть каталог в
    // любой момент. Если писать прямо в итоговый файл, читатель увидит половину файла и примет
    // её за доказательство. Временный файл виден как временный по хвосту имени, а итоговый
    // появляется уже целиком одним переименованием внутри того же каталога.
    //
    // Почему переименование — это ещё и защита от перезаписи. Переименование в существующий путь
    // завершается ошибкой, а не затиранием. Значит однократность итогового файла и его целостность
    // обеспечиваются одной и той же операцией, без отдельной проверки «файл есть?», которая
    // всё равно была бы уязвима для одновременного прогона.
    //
    // Почему перехватываются ДВА рода ошибок, а не только ошибка ввода-вывода. Отказ прав во время
    // записи или переименования приходит отдельным родом ошибки, а не ошибкой ввода-вывода. Пока он
    // перехвачен не был, он уходил наружу необёрнутым: вызывающее испытание видело чужое исключение
    // без пути и опознания прогона, а временный файл оставался лежать в каталоге и притворялся
    // недописанным доказательством. Поэтому отказ прав перехватывается тоже, и уборка своего
    // временного файла делается в обоих случаях.
    //
    // Почему причины отказа разведены по тексту. «Файл уже существует» и «запись заблокирована
    // правами» — это разные события с разными действиями человека. В первом случае попытка уже
    // записана и нужен свободный номер попытки; во втором запись не состоялась вообще и нужно
    // разобраться с правами на путь. Один общий текст «либо то, либо другое» заставлял человека
    // угадывать, поэтому каждое событие теперь называется своим именем. Третий случай — ошибка
    // ввода-вывода без итогового файла на диске — не выдаётся ни за одно из двух и назван честно.
    private string WriteSingleShotBytes(string relativePath, byte[] exactBytes)
    {
        // Путь проверяется на выход за каталог записи: наружу вести он не имеет права.
        var path = ResolveInsideWriteRoot(relativePath);

        // Каталог под файл создаётся, если его ещё нет.
        Directory.CreateDirectory(Path.GetDirectoryName(path)!);

        // Временный файл лежит рядом с итоговым: то же устройство, поэтому переименование дешёвое.
        var temporaryPath = path + "." + Guid.NewGuid().ToString("N") + TemporaryWriteSuffix;

        try
        {
            // Временный файл создаётся только если его ещё нет и никому не отдаётся на чтение.
            using (var stream = new FileStream(
                temporaryPath, FileMode.CreateNew, FileAccess.Write, FileShare.None))
            {
                // Байты уходят в поток как есть, без единого преобразования.
                stream.Write(exactBytes, 0, exactBytes.Length);

                // Буферы сбрасываются до переименования, чтобы итоговый файл был полным.
                stream.Flush();
            }

            // Итоговый файл становится виден целиком; существующий путь даёт ошибку, а не затирание.
            File.Move(temporaryPath, path);
        }
        catch (IOException error)
        {
            // Уборка касается ТОЛЬКО временного файла этой записи: первичные улики не удаляются.
            TryDeleteOwnTemporaryFile(temporaryPath);

            // Два события различаются по одному наблюдаемому признаку: лежит ли итоговый файл уже на диске.
            var finalFileAlreadyOnDisk = File.Exists(path);

            // Отказ виден исключением с точным путём; молчаливого «ничего не записал» не бывает.
            throw new ExperimentAttemptOwnershipRefusedException(string.Join("\n",
                "ОДНОКРАТНЫЙ ФАЙЛ ДОКАЗАТЕЛЬСТВА НЕ ЗАПИСАН.",
                "Файл: " + path,
                finalFileAlreadyOnDisk
                    // Итоговый файл на месте: попытка уже записана, и перезапись стёрла бы наблюдение.
                    ? "Почему нельзя: файл доказательства уже существует," +
                      " однократное доказательство не перезаписывается."
                    // Итогового файла нет: запись не состоялась, и выдавать это за «уже существует» нельзя.
                    : "Почему нельзя: запись файла доказательства не удалась," +
                      " итогового файла на диске нет.",
                "Сообщение файловой системы: " + error.Message,
                "Опознание этого прогона: " + CurrentRunIdentifier), error);
        }
        catch (UnauthorizedAccessException error)
        {
            // Та же уборка: отказ прав тоже не имеет права оставить за собой временный файл.
            TryDeleteOwnTemporaryFile(temporaryPath);

            // Отказ прав называется своим именем: это не «файл уже существует», а запрет доступа.
            throw new ExperimentAttemptOwnershipRefusedException(string.Join("\n",
                "ОДНОКРАТНЫЙ ФАЙЛ ДОКАЗАТЕЛЬСТВА НЕ ЗАПИСАН.",
                "Файл: " + path,
                "Почему нельзя: запись заблокирована правами," +
                " у прогона нет доступа к этому пути.",
                "Сообщение файловой системы: " + error.Message,
                "Опознание этого прогона: " + CurrentRunIdentifier), error);
        }

        // Человек узнаёт о месте записи при первом же записанном файле.
        ShowNoticeOnce();

        // Полный путь возвращается, чтобы испытание могло сослаться на него в журнале.
        return path;
    }

    /// <summary>Удаляет ровно свой временный файл записи и ничего кроме него.</summary>
    /// <param name="temporaryPath">Полный путь временного файла этой записи.</param>
    private static void TryDeleteOwnTemporaryFile(string temporaryPath)
    {
        // Уборка разрешена только для пути с хвостом временной записи: это защита от удаления улик.
        if (!temporaryPath.EndsWith(TemporaryWriteSuffix, StringComparison.Ordinal)) return;

        try
        {
            // Файл удаляется, если он остался после неудачной записи.
            File.Delete(temporaryPath);
        }
        catch (IOException)
        {
            // Незавершённая уборка временного файла не является потерей доказательства.
        }
        catch (UnauthorizedAccessException)
        {
            // Отказ прав на уборку временного файла тоже не является потерей доказательства.
        }
    }

    /// <summary>Приводит относительное имя к полному пути и отвергает выход за каталог записи.</summary>
    /// <param name="relativePath">Имя файла внутри каталога записи этого прогона.</param>
    //
    // Какую беду это закрывает. Склейка каталога записи с относительным именем сама по себе
    // границы не держит: имя `..\..\чужое.json` или абсолютный путь уводят запись наружу, и
    // прогон спокойно пишет в чужую попытку или в произвольное место диска. Поэтому полный путь
    // сверяется с каталогом записи, а выход наружу отклоняется заметным исключением.
    private string ResolveInsideWriteRoot(string relativePath)
    {
        // Пустое имя файла доказательством быть не может и отклоняется сразу.
        if (string.IsNullOrWhiteSpace(relativePath))
            throw new EvidencePathEscapesWriteRootException(string.Join("\n",
                "ИМЯ ФАЙЛА ДОКАЗАТЕЛЬСТВА ПУСТОЕ.",
                "Каталог записи: " + _writeRoot,
                "Что делать: передать имя файла внутри каталога записи."));

        // Абсолютный путь или корневой разделитель — это уже не имя внутри каталога записи.
        if (Path.IsPathRooted(relativePath))
            throw new EvidencePathEscapesWriteRootException(string.Join("\n",
                "ПУТЬ ДОКАЗАТЕЛЬСТВА ВЫВОДИТ ЗА КАТАЛОГ ЗАПИСИ.",
                "Запрошенный путь: " + relativePath,
                "Каталог записи: " + _writeRoot,
                "Почему нельзя: абсолютный путь пишет вне каталога этого прогона.",
                "Что делать: передать относительное имя файла внутри каталога записи."));

        // Полный путь считается от каталога записи и нормализуется вместе с частями `..`.
        var candidate = Path.GetFullPath(Path.Combine(_writeRoot, relativePath));

        // Граница каталога записи задаётся его полным путём с разделителем на конце.
        var boundary = _writeRoot.EndsWith(Path.DirectorySeparatorChar)
            ? _writeRoot
            : _writeRoot + Path.DirectorySeparatorChar;

        // Путь обязан начинаться с этой границы: иначе он лежит вне каталога записи.
        if (!candidate.StartsWith(boundary, StringComparison.OrdinalIgnoreCase))
            throw new EvidencePathEscapesWriteRootException(string.Join("\n",
                "ПУТЬ ДОКАЗАТЕЛЬСТВА ВЫВОДИТ ЗА КАТАЛОГ ЗАПИСИ.",
                "Запрошенный путь: " + relativePath,
                "Он указывает сюда: " + candidate,
                "Каталог записи: " + _writeRoot,
                "Почему нельзя: запись вне каталога прогона затирает чужие наблюдения.",
                "Что делать: передать относительное имя файла внутри каталога записи."));

        // Проверенный полный путь отдаётся вызывающему коду.
        return candidate;
    }

    /// <summary>Отвечает, занят ли каталог записи, и объясняет человеку, кем именно.</summary>
    /// <param name="directory">Проверяемый каталог записи.</param>
    //
    // Возвращает null, когда каталог свободен; иначе человеческую причину занятости.
    private static string? DescribeOccupiedAttempt(string directory)
    {
        // Отсутствующий каталог занят быть не может.
        if (!Directory.Exists(directory)) return null;

        // Маркер владения — прямое доказательство того, что каталог уже кем-то захвачен.
        var markerPath = Path.Combine(directory, AttemptOwnerMarkerFileName);

        if (File.Exists(markerPath))
        {
            // Опознание прогона-владельца читается из маркера для человеческого сообщения.
            var owner = TryReadMarkerRunIdentifier(markerPath);

            // Наличие файла завершения отличает выполненную попытку от прерванной.
            var completed = File.Exists(Path.Combine(directory, AttemptCompletionFileName));

            // Причина называет владельца и состояние попытки, а не просто «занято».
            return completed
                ? "каталог принадлежит прогону " + owner + ", попытка уже завершена"
                : "каталог принадлежит прогону " + owner + ", завершения попытки нет: попытка прервана";
        }

        // Маркера нет, но файлы есть: это попытка, начатая кодом без захвата владения.
        var existingFiles = Directory.GetFiles(directory, "*", SearchOption.AllDirectories).Length;

        // Непустой каталог без маркера трогать нельзя: это чужая или прерванная попытка.
        if (existingFiles > 0)
            return "каталог непустой и без маркера владения, файлов внутри: " + existingFiles;

        // Пустой каталог без маркера свободен: запись туда ничего не стирает.
        return null;
    }

    /// <summary>Читает опознание прогона-владельца из маркера или честно говорит, что не смог.</summary>
    /// <param name="markerPath">Полный путь файла-маркера владения.</param>
    private static string TryReadMarkerRunIdentifier(string markerPath)
    {
        try
        {
            // Маркер читается целиком: он короткий и машинный.
            var node = JsonNode.Parse(File.ReadAllText(markerPath));

            // Поле опознания прогона берётся как текст, если маркер разобрался.
            var value = node?["run_id"]?.GetValue<string>();

            // Пустое или отсутствующее поле честно называется неизвестным.
            return string.IsNullOrWhiteSpace(value) ? "неизвестный (маркер без опознания)" : value;
        }
        catch (Exception)
        {
            // Нечитаемый маркер не делает каталог свободным: он остаётся занятым.
            return "неизвестный (маркер не читается)";
        }
    }

    /// <summary>Неделимо захватывает каталог записи файлом-маркером владения.</summary>
    /// <param name="repositoryRoot">Корень хранилища проекта: нужен для опознания и признака дерева.</param>
    /// <param name="declaredDirectory">Назначенный каталог: он попадает в маркер как источник.</param>
    /// <param name="writeRoot">Каталог записи, который захватывается этим прогоном.</param>
    /// <param name="failureReason">Человеческая причина неудачи, когда захват не удался.</param>
    private static bool TryCaptureAttemptOwnership(
        string repositoryRoot, string declaredDirectory, string writeRoot, out string failureReason)
    {
        // Полный путь файла-маркера владения внутри захватываемого каталога.
        var markerPath = Path.Combine(writeRoot, AttemptOwnerMarkerFileName);

        try
        {
            // Каталог записи создаётся до захвата: сам маркер должен лежать внутри него.
            Directory.CreateDirectory(writeRoot);

            // Содержимое маркера готовится заранее, чтобы захват занимал минимум времени.
            var payload = BuildOwnerMarkerPayload(repositoryRoot, declaredDirectory, writeRoot);

            // Режим «создать только если файла ещё нет» и запрет совместного доступа — это и есть
            // неделимый захват: из двух одновременных прогонов маркер получает ровно один.
            using var stream = new FileStream(markerPath, FileMode.CreateNew, FileAccess.Write, FileShare.None);

            // Маркер пишется без метки порядка байтов и с переводом строки на конце.
            var bytes = Utf8WithoutByteOrderMark.GetBytes(payload + "\n");

            // Байты маркера уходят на диск.
            stream.Write(bytes, 0, bytes.Length);

            // Буферы сбрасываются: другой прогон должен видеть маркер уже полным.
            stream.Flush();

            // Причина неудачи пуста, потому что захват удался.
            failureReason = string.Empty;

            // Владение получено этим прогоном.
            return true;
        }
        catch (IOException error)
        {
            // Чаще всего это проигранная гонка: маркер успел создать другой прогон.
            failureReason = "маркер владения захватить не удалось (" + error.Message + ")";

            // Владение не получено.
            return false;
        }
        catch (UnauthorizedAccessException error)
        {
            // Права на каталог записи тоже отказывают честно, а не молча.
            failureReason = "каталог записи недоступен для захвата (" + error.Message + ")";

            // Владение не получено.
            return false;
        }
    }

    /// <summary>Собирает содержимое маркера владения: чем именно связан этот захват.</summary>
    /// <param name="repositoryRoot">Корень хранилища проекта.</param>
    /// <param name="declaredDirectory">Назначенный каталог опыта.</param>
    /// <param name="writeRoot">Каталог записи этого прогона.</param>
    private static string BuildOwnerMarkerPayload(
        string repositoryRoot, string declaredDirectory, string writeRoot)
    {
        // Маркер связывает прогон с адресом записи и с обстоятельствами запуска.
        var marker = new JsonObject
        {
            ["run_id"] = CurrentRunIdentifier,                                     // Кто владеет каталогом.
            ["declared_directory"] = declaredDirectory,                            // Что назначила карточка опыта.
            ["write_root"] = writeRoot,                                            // Куда прогон фактически пишет.
            ["source"] = ReadEnvironmentOrDefault(                                 // Источник задания: карточка или опыт.
                "XIIGEN_EVIDENCE_SOURCE", () => DescribeSourceFromPath(repositoryRoot, declaredDirectory)),
            ["dirty_worktree"] = TryReadWorktreeDirtyFlag(repositoryRoot),         // Признак грязного рабочего дерева.
            ["build_intent"] = ReadEnvironmentOrDefault(                           // Намерение сборки этого прогона.
                "XIIGEN_EVIDENCE_BUILD_INTENT", () => "не задано"),
            ["test_project"] = ReadEnvironmentOrDefault(                            // Проект проверок этого прогона.
                "XIIGEN_EVIDENCE_TEST_PROJECT", () => "не задано"),
            ["test_filter"] = ReadEnvironmentOrDefault(                             // Фильтр проверок этого прогона.
                "XIIGEN_EVIDENCE_TEST_FILTER", () => "не задано"),
            ["captured_utc"] = DateTime.UtcNow.ToString("yyyy-MM-dd'T'HH:mm:ss.fff'Z'"), // Время захвата в едином времени.
            ["process_id"] = Environment.ProcessId,                                // Какой процесс держит каталог.
            ["пояснение"] = "Этот файл означает исключительное владение каталогом попытки." +
                " Пока он здесь, другой прогон в этот каталог не пишет." +
                " Отсутствие файла завершения рядом означает прерванную попытку." +
                " Стойкость к потере питания не обещается.",
        };

        // Маркер отдаётся как текст с отступами: его читает и человек, и машина.
        return marker.ToJsonString(MarkerJsonOptions);
    }

    /// <summary>Описывает источник задания по относительному пути назначенного каталога.</summary>
    /// <param name="repositoryRoot">Корень хранилища проекта.</param>
    /// <param name="declaredDirectory">Назначенный каталог опыта.</param>
    private static string DescribeSourceFromPath(string repositoryRoot, string declaredDirectory)
    {
        try
        {
            // Относительный путь внутри хранилища и есть опознание карточки или опыта.
            return Path.GetRelativePath(repositoryRoot, declaredDirectory).Replace('\\', '/');
        }
        catch (Exception)
        {
            // Если путь не сводится к относительному, честно отдаётся полный путь.
            return declaredDirectory;
        }
    }

    /// <summary>Спрашивает хранилище, есть ли в рабочем дереве незакоммиченные изменения.</summary>
    /// <param name="repositoryRoot">Корень хранилища проекта.</param>
    //
    // Почему это отдельный запрос, а не часть уже принятого запроса об отслеживаемых файлах.
    // Запрос об отслеживаемых файлах — принятая работа, которая решает вопрос опубликованности.
    // Менять его ради нового поля маркера значит рисковать принятым поведением, поэтому признак
    // грязного дерева спрашивается своим коротким запросом. Неотслеживаемые файлы здесь намеренно
    // не считаются: их перечисление по большому дереву стоит дорого, а для маркера важен факт
    // незакоммиченных правок.
    private static string TryReadWorktreeDirtyFlag(string repositoryRoot)
    {
        try
        {
            // Запрос только читает состояние рабочего дерева и ничего не меняет.
            var startInfo = new ProcessStartInfo("git")
            {
                WorkingDirectory = repositoryRoot,
                RedirectStandardOutput = true,
                RedirectStandardError = true,
                UseShellExecute = false,
                CreateNoWindow = true,
            };

            // Короткий формат состояния без перечисления неотслеживаемых файлов.
            startInfo.ArgumentList.Add("status");
            startInfo.ArgumentList.Add("--porcelain");
            startInfo.ArgumentList.Add("--untracked-files=no");

            // Запуск запроса: отсутствие процесса считается неизвестностью, а не чистотой.
            using var process = Process.Start(startInfo);
            if (process is null) return "не определено";

            // Вывод читается полностью: для грязного дерева он короткий.
            var output = process.StandardOutput.ReadToEnd();

            // Поток ошибок тоже вычитывается, иначе процесс может ждать на заполненном буфере.
            _ = process.StandardError.ReadToEnd();

            // Зависший запрос прекращается, и ответ считается неизвестным.
            if (!process.WaitForExit(RepositoryProbeTimeoutMilliseconds))
            {
                try { process.Kill(entireProcessTree: true); } catch { /* уже завершился */ }
                return "не определено";
            }

            // Ненулевой код возврата означает, что ответ хранилища недействителен.
            if (process.ExitCode != 0) return "не определено";

            // Непустой вывод означает незакоммиченные изменения в рабочем дереве.
            return string.IsNullOrWhiteSpace(output) ? "нет" : "да";
        }
        catch (Exception)
        {
            // Любая неудача запроса — это неизвестность, а не утверждение о чистоте дерева.
            return "не определено";
        }
    }

    /// <summary>Читает переменную окружения или отдаёт значение по умолчанию.</summary>
    /// <param name="name">Имя переменной окружения.</param>
    /// <param name="fallback">Что подставить, когда переменная пуста или отсутствует.</param>
    private static string ReadEnvironmentOrDefault(string name, Func<string> fallback)
    {
        // Значение берётся из окружения процесса.
        var value = Environment.GetEnvironmentVariable(name);

        // Пустая или отсутствующая переменная заменяется значением по умолчанию.
        return string.IsNullOrWhiteSpace(value) ? fallback() : value;
    }

    /// <summary>Отвечает, признан ли каталог опубликованным наблюдением, и почему.</summary>
    /// <param name="repositoryRoot">Корень хранилища проекта.</param>
    /// <param name="directory">Проверяемый каталог доказательств.</param>
    /// <param name="reason">Человеческая причина вердикта.</param>
    public static bool IsPublishedEvidenceDirectory(string repositoryRoot, string directory, out string reason)
    {
        // Сначала спрашиваем само хранилище: это буквальное определение опубликованности.
        if (TryCountTrackedFiles(repositoryRoot, directory, out var trackedCount))
        {
            // Хранилище отслеживает файлы внутри каталога — каталог опубликован.
            if (trackedCount > 0)
            {
                reason = $"хранилище отслеживает внутри каталога файлов: {trackedCount}";
                return true;
            }

            // Хранилище ответило и не отслеживает внутри каталога ничего — каталог свободен.
            reason = "хранилище не отслеживает внутри каталога ни одного файла";
            return false;
        }

        // Хранилище недоступно. Осторожная сторона одна: непустой каталог считается чужим.
        var existingFiles = Directory.Exists(directory)
            ? Directory.GetFiles(directory, "*", SearchOption.AllDirectories).Length
            : 0;

        // Непустой каталог без ответа хранилища трогать нельзя: это может быть наблюдение.
        if (existingFiles > 0)
        {
            reason = "ответ хранилища недоступен, а каталог уже содержит файлов: " + existingFiles;
            return true;
        }

        // Пустого или отсутствующего каталога стереть нельзя — запись туда безопасна.
        reason = "ответ хранилища недоступен, но каталог пуст или отсутствует";
        return false;
    }

    /// <summary>Строит свежий каталог прогона внутри игнорируемых результатов испытаний.</summary>
    /// <param name="repositoryRoot">Корень хранилища проекта.</param>
    /// <param name="declaredDirectory">Назначенный каталог: из него берётся опознавательное имя.</param>
    private static string BuildFreshRunDirectory(string repositoryRoot, string declaredDirectory)
    {
        // Опознавательное имя собирается из относительного пути назначенного каталога.
        var relative = Path.GetRelativePath(repositoryRoot, declaredDirectory);

        // Разделители пути превращаются в дефисы: получается одно читаемое имя папки.
        var marker = relative.Replace(Path.DirectorySeparatorChar, '-').Replace('/', '-');

        // Метка времени в едином времени: порядок прогонов виден по имени.
        var stamp = DateTime.UtcNow.ToString("yyyyMMdd'T'HHmmssfff'Z'");

        // Короткий уникальный хвост: два одновременных прогона не столкнутся.
        var unique = Guid.NewGuid().ToString("N")[..8];

        // Папка результатов испытаний игнорируется хранилищем, поэтому прогон ничего не публикует.
        return Path.Combine(
            repositoryRoot, "Tests", "TestResults", "experiment-evidence", marker, $"run-{stamp}-{unique}");
    }

    /// <summary>Спрашивает хранилище, сколько файлов внутри каталога оно отслеживает.</summary>
    /// <param name="repositoryRoot">Корень хранилища проекта.</param>
    /// <param name="directory">Проверяемый каталог доказательств.</param>
    /// <param name="count">Число отслеживаемых файлов, если ответ получен.</param>
    private static bool TryCountTrackedFiles(string repositoryRoot, string directory, out int count)
    {
        // До получения ответа считаем, что отслеживаемых файлов не найдено.
        count = 0;

        try
        {
            // Путь задаётся относительно корня: так запрос не зависит от буквы диска.
            var relative = Path.GetRelativePath(repositoryRoot, directory).Replace('\\', '/');

            // Выход за корень хранилища означает, что спрашивать хранилище бессмысленно.
            if (relative.StartsWith("..", StringComparison.Ordinal)) return false;

            // Запрос только читает список отслеживаемых файлов и ничего не меняет.
            var startInfo = new ProcessStartInfo("git")
            {
                WorkingDirectory = repositoryRoot,
                RedirectStandardOutput = true,
                RedirectStandardError = true,
                UseShellExecute = false,
                CreateNoWindow = true,
            };

            // Перечисление отслеживаемых путей внутри каталога, разделитель — нулевой байт.
            startInfo.ArgumentList.Add("ls-files");
            startInfo.ArgumentList.Add("-z");
            startInfo.ArgumentList.Add("--");
            startInfo.ArgumentList.Add(relative);

            // Запуск запроса: отсутствие процесса считается недоступностью хранилища.
            using var process = Process.Start(startInfo);
            if (process is null) return false;

            // Вывод читается полностью: список путей короткий.
            var output = process.StandardOutput.ReadToEnd();

            // Поток ошибок тоже вычитывается, иначе процесс может ждать на заполненном буфере.
            _ = process.StandardError.ReadToEnd();

            // Зависший запрос прекращается, и ответ считается неполученным.
            if (!process.WaitForExit(RepositoryProbeTimeoutMilliseconds))
            {
                try { process.Kill(entireProcessTree: true); } catch { /* уже завершился */ }
                return false;
            }

            // Ненулевой код возврата означает, что ответ хранилища недействителен.
            if (process.ExitCode != 0) return false;

            // Пустые части отбрасываются: остаются только реальные отслеживаемые пути.
            count = output.Split('\0', StringSplitOptions.RemoveEmptyEntries).Length;
            return true;
        }
        catch (Exception)
        {
            // Любая неудача запроса — это недоступность ответа, а не разрешение писать.
            return false;
        }
    }

    /// <summary>Показывает сообщение о каталоге записи один раз за прогон.</summary>
    private void ShowNoticeOnce()
    {
        // Защёлка не даёт сообщению повторяться на каждом записанном файле.
        if (Interlocked.Exchange(ref _noticeAlreadyShown, 1) != 0) return;

        // Сообщение попадает в вывод испытания, поэтому молчаливой записи не бывает.
        Console.WriteLine(Notice);

        // То же сообщение остаётся рядом с файлами прогона отдельным файлом-подсказкой.
        try
        {
            Directory.CreateDirectory(_writeRoot);
            File.WriteAllText(
                // Имя берётся у постоянной этого же класса: литерал в дереве один.
                Path.Combine(_writeRoot, EvidenceLocationHintFileName),
                Notice + "\n",
                Utf8WithoutByteOrderMark);
        }
        catch (IOException)
        {
            // Подсказка не является доказательством: её отсутствие не ломает прогон.
        }
    }
