// Постоянное покрытие инварианта «память маршрутизатора наборов данных владеет
// обоими входными массивами урока» (третья работа плана ремонта 102 по позднему
// аудиту двадцать девятого октября, папка
// docs/plans/replanning-possible-diffs/fixes-based-on-experiments).
//
// Что здесь проверяется по-человечески. Маршрутизатор наборов данных запоминает
// уроки: у каждого урока есть признаки запроса и маска корзин данных, которые
// этому запросу подходят. Вопрос простой: после того как урок принят в память,
// принадлежат ли эти два массива самому маршрутизатору — или он продолжает
// смотреть в те же массивы, которые остались на руках у вызывающей стороны.
//
// Что было сломано. Приём партии складывал в память те самые ссылки, которые
// дал вызывающий. Вызывающая сторона могла после обучения изменить свой массив
// признаков или свой массив меток — и обученная память менялась вместе с ним,
// молча. Ни одного урока между двумя чтениями не добавляли, а ответ на тот же
// запрос приходил уже другой. Это тихая порча обученной памяти.
//
// Как это доказывается. Два случая мутации — отдельно массив признаков и
// отдельно массив меток, — и каждый сравнивается с ответом, снятым до мутации.
// Ожидаемые значения выписаны буквально, а не взяты из самого же ответа.
// Чтобы сравнение было чистым, в обоих случаях взят ровно один ближайший сосед
// и расстояния подобраны строго разными: ничья в этих двух случаях невозможна,
// поэтому смена ответа может означать только порчу памяти. Ничья вынесена в
// отдельную заготовку ниже и служит положительным контролем.
//
// Положительные контроли, которые обязаны остаться зелёными. Выходной массив
// чтения и так принадлежит вызывающему — порча этого массива не должна доходить
// до памяти. Действующая политика ширины маски тоже не меняется: короткую маску
// чтение дополняет значениями «нет», элементы сверх числа корзин игнорирует.
//
// Число корзин здесь намеренно не шесть. Договор допускает два и три, и именно
// на таких значениях построены случаи: жёстко вшитая шестёрка проверяла бы не
// договор, а один частный продуктовый список имён.
//
// Бюджет этой проверки. Шесть маленьких памятей из одного-двух уроков прямо в
// оперативной памяти, по одному-двум чтениям ответа на каждой. Ни одного
// обучения с учителем, ни одной пары предпочтений, ни одного обращения к диску.
//
// Чего это покрытие НЕ доказывает. Оно доказывает сохранность состояния
// механизма, а не качество его обобщения: все запросы здесь совпадают с
// признаками выученных строк, поэтому верный ответ — точный возврат выученного.
// Оно не говорит ничего про поведение при отказе новой партии (пустая ссылка,
// ошибка чтения партии) — это отдельная, ещё не выполненная работа ремонта.
// Цена копирования на больших памятях здесь не измеряется.

using LogicExtractor = SemanticCompiler.LogicExtractor;

namespace LlmFromScratch.Tests.ExperimentFixes;

public sealed class DatasetRouterMemoryOwnershipTests
{
    // Ровно один ближайший сосед: сравнение ответов до и после мутации идёт без
    // примеси голосования нескольких соседей.
    private const int ExactNearestNeighbour = 1;

    // Число корзин в случаях владения — два. Договор это допускает, и такой
    // выбор прямо показывает, что проверка не привязана к шести именам продукта.
    private const int TwoBuckets = 2;

    // ГЛАВНЫЙ СЛУЧАЙ ОДИН. После обучения вызывающая сторона меняет СВОЙ массив
    // признаков. Если память хранит ссылку, у ближнего урока портятся признаки,
    // ближайшим становится другой урок и ответ меняется. Если память владеет
    // своей копией, ответ обязан остаться прежним.
    [Fact]
    public void CallerFeatureArrayMutatedAfterTraining_KeepsTheAnswerTheMemoryLearned()
    {
        // Массив признаков ближнего урока остаётся на руках у вызывающей стороны.
        var callerNearFeatures = new[] { LogicExtractor.ITERATE };

        // Второй урок нужен как соперник: при порче ближнего именно он станет ближайшим.
        var rivalFeatures = new[] { LogicExtractor.ITERATE, LogicExtractor.BRANCH };

        // Маршрутизатор с одним ближайшим соседом и двумя корзинами.
        var router = new AgentAlgorithms.PredicateDatasetRouter(
            k: ExactNearestNeighbour, datasetCount: TwoBuckets);

        // Память из двух уроков: ближний голосует за первую корзину, соперник — за вторую.
        router.Train(
        [
            (callerNearFeatures, new[] { true, false }),
            (rivalFeatures, new[] { false, true })
        ]);

        // Запрос буквально совпадает с признаками ближнего урока: расстояние до него ноль,
        // до соперника — половина, поэтому ближайший выбран однозначно, без ничьей.
        var query = new[] { LogicExtractor.ITERATE };

        // Ответ до мутации: ожидание выписано буквально — первая корзина и только она.
        Assert.Equal(new[] { true, false }, router.Predict(query));

        // Вызывающая сторона меняет свой массив признаков на не встречающийся в запросе.
        // На общей ссылке это отодвинуло бы ближний урок за соперника.
        callerNearFeatures[0] = LogicExtractor.CALL;

        // Ответ после мутации обязан совпасть с ответом до неё: память владеет своей копией.
        Assert.Equal(new[] { true, false }, router.Predict(query));
    }

    // ГЛАВНЫЙ СЛУЧАЙ ДВА. После обучения вызывающая сторона меняет СВОЙ массив
    // меток. Если память хранит ссылку, тот же запрос вернёт уже другие корзины.
    [Fact]
    public void CallerLabelArrayMutatedAfterTraining_KeepsTheAnswerTheMemoryLearned()
    {
        // Массив меток урока остаётся на руках у вызывающей стороны.
        var callerLabels = new[] { true, false };

        // Маршрутизатор с одним ближайшим соседом и двумя корзинами.
        var router = new AgentAlgorithms.PredicateDatasetRouter(
            k: ExactNearestNeighbour, datasetCount: TwoBuckets);

        // Память из одного урока: единственный сосед и есть ответ.
        router.Train([(new[] { LogicExtractor.ITERATE }, callerLabels)]);

        // Запрос совпадает с признаками урока.
        var query = new[] { LogicExtractor.ITERATE };

        // Ответ до мутации: ожидание выписано буквально.
        Assert.Equal(new[] { true, false }, router.Predict(query));

        // Вызывающая сторона переворачивает обе метки в своём массиве.
        callerLabels[0] = false;
        callerLabels[1] = true;

        // Ответ после мутации обязан совпасть с ответом до неё: память владеет своей копией.
        Assert.Equal(new[] { true, false }, router.Predict(query));
    }

    // ПОЛОЖИТЕЛЬНЫЙ КОНТРОЛЬ ВЫХОДА. Выданный массив ответа и так принадлежит
    // вызывающему. Эта правка его не трогала, и порча выданного ответа не должна
    // доходить до памяти.
    [Fact]
    public void ReturnedAnswerMutatedByTheCaller_DoesNotReachTheMemory()
    {
        // Маршрутизатор с одним ближайшим соседом и двумя корзинами.
        var router = new AgentAlgorithms.PredicateDatasetRouter(
            k: ExactNearestNeighbour, datasetCount: TwoBuckets);

        // Память из одного урока за первую корзину.
        router.Train([(new[] { LogicExtractor.ITERATE }, new[] { true, false })]);

        // Запрос совпадает с признаками урока.
        var query = new[] { LogicExtractor.ITERATE };

        // Первое чтение ответа.
        bool[] firstAnswer = router.Predict(query);

        // Ожидание первого чтения выписано буквально.
        Assert.Equal(new[] { true, false }, firstAnswer);

        // Получатель портит выданный ему массив целиком.
        firstAnswer[0] = false;
        firstAnswer[1] = true;

        // Второе чтение обязано вернуть прежний выученный ответ.
        Assert.Equal(new[] { true, false }, router.Predict(query));
    }

    // ПОЛОЖИТЕЛЬНЫЙ КОНТРОЛЬ ПОЛИТИКИ ШИРИНЫ, КОРОТКАЯ МАСКА. Маска урока короче
    // числа корзин. Действующая политика принимает её и дополняет недостающие
    // корзины значением «нет». Копирование не вправе подгонять длину под число
    // корзин — иначе этот контроль упадёт.
    [Fact]
    public void LessonWithAMaskShorterThanTheBucketCount_IsStillAcceptedAndPaddedWithNo()
    {
        // Корзин три, а маска урока будет длиной один.
        const int threeBuckets = 3;

        // Маршрутизатор с одним ближайшим соседом и тремя корзинами.
        var router = new AgentAlgorithms.PredicateDatasetRouter(
            k: ExactNearestNeighbour, datasetCount: threeBuckets);

        // Урок с короткой маской: названа только первая корзина.
        router.Train([(new[] { LogicExtractor.ITERATE }, new[] { true })]);

        // Чтение ответа на признаках урока.
        bool[] answer = router.Predict([LogicExtractor.ITERATE]);

        // Ожидание выписано буквально: первая корзина истинна, недостающие две дополнены «нет».
        Assert.Equal(new[] { true, false, false }, answer);
    }

    // ПОЛОЖИТЕЛЬНЫЙ КОНТРОЛЬ ПОЛИТИКИ ШИРИНЫ, ДЛИННАЯ МАСКА. Маска урока длиннее
    // числа корзин. Действующая политика принимает её и игнорирует лишние
    // элементы. Копирование обязано сохранить и эту длину как есть.
    [Fact]
    public void LessonWithAMaskLongerThanTheBucketCount_IsStillAcceptedAndTheExtrasAreIgnored()
    {
        // Маршрутизатор с одним ближайшим соседом и двумя корзинами.
        var router = new AgentAlgorithms.PredicateDatasetRouter(
            k: ExactNearestNeighbour, datasetCount: TwoBuckets);

        // Урок с длинной маской: третий элемент истинен, но корзины с таким номером нет.
        router.Train([(new[] { LogicExtractor.ITERATE }, new[] { true, false, true })]);

        // Чтение ответа на признаках урока.
        bool[] answer = router.Predict([LogicExtractor.ITERATE]);

        // Ожидание выписано буквально: ответ длиной в число корзин, лишний элемент не виден.
        Assert.Equal(new[] { true, false }, answer);
    }

    // ОТДЕЛЬНАЯ ЗАГОТОВКА НА СЛУЧАЙ НИЧЬЕЙ. Она намеренно вынесена из случаев
    // владения: там расстояния строго разные, здесь — наоборот, оба урока
    // одинаково близки и голоса встречные. Правка владения памятью не вправе
    // менять этот исход.
    [Fact]
    public void TwoEquallyCloseOpposingLessons_StayARefusalAfterTheOwnershipRepair()
    {
        // Два соседа, две корзины.
        var router = new AgentAlgorithms.PredicateDatasetRouter(
            k: 2, datasetCount: TwoBuckets);

        // Оба урока имеют одинаковые признаки, значит расстояния равны — это и есть ничья.
        router.Train(
        [
            (new[] { LogicExtractor.ITERATE }, new[] { true, false }),
            (new[] { LogicExtractor.ITERATE }, new[] { false, true })
        ]);

        // Чтение ответа на тех же признаках.
        bool[] answer = router.Predict([LogicExtractor.ITERATE]);

        // Ожидание выписано буквально: по одному голосу на корзину, большинства нет, отказ.
        Assert.Equal(new[] { false, false }, answer);
    }
}
