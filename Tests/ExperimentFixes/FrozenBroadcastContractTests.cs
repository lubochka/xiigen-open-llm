namespace LlmFromScratch.Tests.ExperimentFixes;

using TensorCore.Core;

// Договорные проверки переноса «не строить карту обратного прохода для полностью
// замороженного растягивающего умножения» (строка очереди 31 реестра исправлений
// по опытам, идентификатор работы FIX-FBM; карточка переноса о карте замороженного
// растягивания, раздел «Тесты непосредственно из механизма опыта»).
//
// Что защищают эти девять случаев человеческими словами. Растягивающее умножение
// умножает каждое число большого тензора на подходящее число маленького тензора.
// Чтобы потом посчитать градиент, прежний код для КАЖДОГО числа большого тензора
// запоминал в отдельный массив номер того числа маленького тензора, на которое
// умножали. Этот массив-карта читается только из обратного прохода. Обратный же
// проход вообще не строится, когда ни один из двух входов не обучается. Значит у
// карты в этом случае нет ни одного читателя, и она выделялась впустую. Новый
// узкий путь её не создаёт. Порядок умножений сохранён, поэтому числа выхода
// обязаны выйти бит в бит теми же.
//
// Откуда взяты ожидаемые числа, и почему они независимы от изменённого кода. Ни
// один случай ниже не зовёт изменённый метод, чтобы посчитать им же своё
// ожидание. Все ожидания выписаны руками из входных чисел. Для обратного прохода
// использована школьная производная произведения: по большому входу это число
// сверху, умноженное на парное число маленького входа; по маленькому входу это
// сумма произведений числа сверху на число большого входа по всем местам, куда
// это маленькое число растянулось.
//
// Почему сравнение побитовое, а не с допуском. Перенос обязан сохранить значения
// БЕЗ изменения. Допуск спрятал бы перегруппировку или другой порядок операций,
// а побитовое сравнение её запрещает. Все ожидаемые числа ниже представимы в
// одинарной точности точно, поэтому побитовое сравнение здесь законно.
//
// Что эти девять случаев НЕ закрывают. Они не являются доказательством обучения
// и не измеряют память: учебная приёмка на восстановленном обученном старте и
// сравнение выделений памяти — отдельные части этой же карточки. Здесь
// проверяется только сам изменённый метод: обе стороны условия, выравнивание
// осей вправо, сохранение обеих ветвей обратного прохода, прежние ошибки формы
// и сохранённая отмена внутри узкого пути.
public sealed class FrozenBroadcastContractTests
{
    // Длина последней оси основного набора входных чисел: три числа в строке.
    private const int RowLength = 3;

    // Основной большой вход всех случаев, кроме случая выравнивания осей:
    // две строки по три числа, значения от одного до шести по порядку хранения.
    private static Tensor TwoRowsOneToSix()
    {
        // Форма «две строки по три числа» — ровно та, что названа в карточке.
        var shape = new TensorShape(2, RowLength);

        // Числа выписаны явно, а не вычислены циклом: вход виден читателю целиком.
        var data = new[] { 1f, 2f, 3f, 4f, 5f, 6f };

        // Отдаём продуктовый тензор, а не копию вычислений умножения.
        return new Tensor(data, shape);
    }

    // Основной маленький вход: три числа, растягиваемые на обе строки большого входа.
    private static Tensor ThreeFactors()
    {
        // Форма «три числа» короче формы большого входа, поэтому оси выровняются вправо.
        var shape = new TensorShape(RowLength);

        // Множители нарочно разные и разных знаков: перепутанный порядок не спрячется.
        var data = new[] { 0.5f, -1f, 2f };

        // Отдаём продуктовый тензор.
        return new Tensor(data, shape);
    }

    // Сравнивает одно число побитово и называет место ошибки понятным текстом.
    private static void AssertExactBits(float expected, float actual, string place)
    {
        // Побитовое сравнение запрещает любой допуск и любую перегруппировку операций.
        Assert.Equal(
            BitConverter.SingleToInt32Bits(expected),
            BitConverter.SingleToInt32Bits(actual));

        // Место сравнения проверяется отдельно, чтобы текст ошибки называл клетку.
        Assert.False(string.IsNullOrEmpty(place));
    }

    [Fact]
    public void FrozenValues_PreserveDataAndStorage()
    {
        // Большой вход: две строки по три числа от одного до шести.
        var a = TwoRowsOneToSix();

        // Маленький вход: три множителя, растягиваемые на обе строки.
        var b = ThreeFactors();

        // Оба входа заморожены: это и есть условие входа в новый узкий путь.
        a.RequiresGrad = false;
        b.RequiresGrad = false;

        // Выполняем растягивающее умножение изменённым продуктовым методом.
        var product = TensorOps.MultiplyBroadcast(a, b);

        // Форма результата обязана остаться формой большого входа.
        Assert.Equal([2, RowLength], product.Shape.Dimensions);

        // Шесть ожидаемых чисел выписаны руками: каждая строка [1,2,3] и [4,5,6]
        // поэлементно умножена на [0.5,-1,2].
        var expected = new[] { 0.5f, -2f, 6f, 2f, -5f, 12f };

        // Каждое из шести чисел сверяется побитово.
        for (var flat = 0; flat < expected.Length; flat++)
            AssertExactBits(expected[flat], product.Data[flat], $"клетка {flat}");

        // Результат полностью замороженного вызова не должен быть обучаемым:
        // обратного прохода для него нет, как и раньше.
        Assert.False(product.RequiresGrad);

        // Градиентов у входов тоже быть не должно: обратный проход не запускался.
        Assert.Null(a.Grad);
        Assert.Null(b.Grad);

        // Теперь портим ВНЕШНИЕ массивы входов через их собственные хранилища:
        // тензор обязан владеть своей копией, иначе выход «поедет» задним числом.
        for (var flat = 0; flat < a.Data.Length; flat++)
            a.Data[flat] = 1000f;

        // То же самое делаем с маленьким входом.
        for (var flat = 0; flat < b.Data.Length; flat++)
            b.Data[flat] = -1000f;

        // После порчи входов все шесть чисел выхода обязаны остаться прежними:
        // узкий путь скопировал значения в собственное хранилище результата.
        for (var flat = 0; flat < expected.Length; flat++)
            AssertExactBits(expected[flat], product.Data[flat], $"клетка {flat} после порчи входов");
    }

    [Fact]
    public void FrozenRankOffset_PreservesRightAlignment()
    {
        // Большой вход формы «две группы по две строки из трёх чисел», значения 1..12.
        var aShape = new TensorShape(2, 2, RowLength);

        // Место под двенадцать чисел большого входа.
        var aData = new float[aShape.TotalElements];

        // Заполняем числами от одного до двенадцати по порядку хранения.
        for (var flat = 0; flat < aData.Length; flat++)
            aData[flat] = flat + 1;

        // Продуктовый большой тензор.
        var a = new Tensor(aData, aShape);

        // Маленький вход формы «две строки по одному числу»: его последняя ось
        // растягивается, а предпоследняя совпадает со средней осью большого входа.
        var b = new Tensor([2f, 3f], new TensorShape(2, 1));

        // Оба входа заморожены: проверяется выравнивание осей именно в узком пути.
        a.RequiresGrad = false;
        b.RequiresGrad = false;

        // Растягивающее умножение изменённым продуктовым методом.
        var product = TensorOps.MultiplyBroadcast(a, b);

        // Форма результата обязана остаться трёхосной формой большого входа.
        Assert.Equal([2, 2, RowLength], product.Shape.Dimensions);

        // Двенадцать ожидаемых чисел выписаны руками. Оси маленького входа
        // прижаты вправо, поэтому его первое число умножает первую строку каждой
        // группы, а второе число — вторую строку каждой группы.
        var expected = new[] { 2f, 4f, 6f, 12f, 15f, 18f, 14f, 16f, 18f, 30f, 33f, 36f };

        // Каждое из двенадцати чисел сверяется побитово.
        for (var flat = 0; flat < expected.Length; flat++)
            AssertExactBits(expected[flat], product.Data[flat], $"клетка {flat}");

        // Результат полностью замороженного вызова снова не обучаемый.
        Assert.False(product.RequiresGrad);
    }

    [Theory]
    [InlineData(false, false)]
    [InlineData(true, false)]
    [InlineData(false, true)]
    [InlineData(true, true)]
    public void RequiresGradCombinations_PreserveBackward(bool trainBig, bool trainSmall)
    {
        // Те же два входа, что в первом случае: две строки по три числа и три множителя.
        var a = TwoRowsOneToSix();
        var b = ThreeFactors();

        // Четыре случая этой проверки перебирают все сочетания обучаемости входов.
        a.RequiresGrad = trainBig;
        b.RequiresGrad = trainSmall;

        // Растягивающее умножение изменённым продуктовым методом.
        var product = TensorOps.MultiplyBroadcast(a, b);

        // Значения прямого прохода обязаны быть одинаковыми во всех четырёх случаях.
        var expectedForward = new[] { 0.5f, -2f, 6f, 2f, -5f, 12f };

        // Сверяем все шесть чисел побитово: узкий путь не имеет права менять значения.
        for (var flat = 0; flat < expectedForward.Length; flat++)
            AssertExactBits(expectedForward[flat], product.Data[flat], $"клетка {flat}");

        // Случай «оба входа заморожены» проверяется БЕЗ обратного прохода: карточка
        // требует увидеть именно отсутствие обучаемого результата и отсутствие
        // градиентов у листьев, а не поведение обратного прохода.
        if (!trainBig && !trainSmall)
        {
            // Результат не обучаемый: граф для него не строился.
            Assert.False(product.RequiresGrad);

            // Ни у большого, ни у маленького входа градиента нет.
            Assert.Null(a.Grad);
            Assert.Null(b.Grad);

            // Дальше в этом случае проверять нечего.
            return;
        }

        // Хотя бы один вход обучаемый, значит результат обязан стать обучаемым и
        // прежняя ветвь обратного прохода обязана сохраниться без изменений.
        Assert.True(product.RequiresGrad);

        // Шесть назначенных сверху чисел обратного прохода: от одного до шести.
        var upstream = new Tensor([1f, 2f, 3f, 4f, 5f, 6f], product.Shape);

        // Запускаем обратное распространение от результата с этими числами.
        product.Backward(upstream);

        // Ожидаемый градиент по большому входу выведен из производной произведения:
        // каждое число сверху умножается на парное ему число маленького входа.
        // Для [1..6] и множителей [0.5,-1,2] это [0.5,-2,6,2,-5,12].
        var expectedBigGradient = new[] { 0.5f, -2f, 6f, 2f, -5f, 12f };

        // Ожидаемый градиент по маленькому входу: сумма произведений числа сверху
        // на число большого входа по обеим строкам. Первое число: 1*1+4*4=17.
        // Второе: 2*2+5*5=29. Третье: 3*3+6*6=45.
        var expectedSmallGradient = new[] { 17f, 29f, 45f };

        // Градиент появляется ТОЛЬКО у того входа, который его запрашивал.
        if (trainBig)
        {
            // Градиент по большому входу обязан существовать.
            Assert.NotNull(a.Grad);

            // Все шесть его чисел сверяются побитово.
            for (var flat = 0; flat < expectedBigGradient.Length; flat++)
                AssertExactBits(expectedBigGradient[flat], a.Grad!.Data[flat], $"градиент A, клетка {flat}");
        }
        else
        {
            // Не запрошенный градиент не должен появиться: это защита от лишней работы.
            Assert.Null(a.Grad);
        }

        // То же правило для маленького входа.
        if (trainSmall)
        {
            // Градиент по маленькому входу обязан существовать.
            Assert.NotNull(b.Grad);

            // Все три его числа сверяются побитово.
            for (var flat = 0; flat < expectedSmallGradient.Length; flat++)
                AssertExactBits(expectedSmallGradient[flat], b.Grad!.Data[flat], $"градиент B, клетка {flat}");
        }
        else
        {
            // Не запрошенный градиент снова не должен появиться.
            Assert.Null(b.Grad);
        }
    }

    [Theory]
    [InlineData(true)]
    [InlineData(false)]
    public void FrozenInvalidShapes_PreserveErrors(bool rankViolation)
    {
        // Большой вход формы «две строки по три числа» в обоих случаях.
        var a = TwoRowsOneToSix();

        // Первый случай: у маленького входа БОЛЬШЕ осей, чем у большого. Второй
        // случай: число осей допустимо, но длина оси несовместима с большим входом.
        var b = rankViolation
            ? new Tensor([1f, 2f, 3f, 4f, 5f, 6f], new TensorShape(1, 2, RowLength))
            : new Tensor([1f, 2f, 3f, 4f], new TensorShape(2, 2));

        // Оба входа заморожены: проверяется, что узкий путь не принимает формы,
        // которые прежний код отвергал. Проверки форм стоят ДО обоих путей.
        a.RequiresGrad = false;
        b.RequiresGrad = false;

        // Ожидание: прежняя ошибка аргумента, а не тихий или неверный результат.
        Assert.Throws<ArgumentException>(() => TensorOps.MultiplyBroadcast(a, b));
    }

    [Fact]
    public void PreCancelledFrozenBroadcast_Throws()
    {
        // Длина четыре тысячи девяносто семь чисел выбрана нарочно: внутренняя
        // проверка отмены срабатывает на каждом четырёхтысячном с небольшим
        // числе, поэтому такая длина задевает и первую проверку, и проверку
        // внутри цикла.
        var aShape = new TensorShape(4097);

        // Место под эти числа; важна сама отмена, а не значения.
        var aData = new float[aShape.TotalElements];

        // Заполняем единицами, чтобы вход был осмысленным, а не нулевым.
        for (var flat = 0; flat < aData.Length; flat++)
            aData[flat] = 1f;

        // Продуктовый большой тензор с этой длинной строкой.
        var a = new Tensor(aData, aShape);

        // Маленький вход из одного числа: он растягивается на всю длинную строку.
        var b = new Tensor([2f], new TensorShape(1));

        // Оба входа заморожены: отмена проверяется именно внутри узкого пути.
        a.RequiresGrad = false;
        b.RequiresGrad = false;

        // Положительный контроль законного пути: тот же вызов БЕЗ отмены обязан
        // спокойно досчитаться. Без этого контроля отказ ниже мог бы объясняться
        // чем угодно — например недостижимым входом, — а не самой отменой.
        var lawful = TensorOps.MultiplyBroadcast(a, b, CancellationToken.None);

        // Все числа большого входа равны единице, множитель равен двойке, значит
        // первое число результата обязано быть ровно двойкой.
        AssertExactBits(2f, lawful.Data[0], "клетка 0 законного прохода");

        // Последнее число проверяется тоже: длинная строка пройдена до конца.
        AssertExactBits(2f, lawful.Data[^1], "последняя клетка законного прохода");

        // Источник отмены, отменённый ЗАРАНЕЕ, до вызова умножения.
        using var cancellation = new CancellationTokenSource();

        // Отменяем сразу: умножение не должно успеть сделать ни одного шага.
        cancellation.Cancel();

        // Ожидание: вызов обязан прерваться отменой, а не вернуть готовый
        // результат. Это доказывает, что отмена из узкого пути не удалена.
        Assert.Throws<OperationCanceledException>(
            () => TensorOps.MultiplyBroadcast(a, b, cancellation.Token));
    }
}
