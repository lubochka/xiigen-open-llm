namespace AgentInfrastructure.Logical;

using System.Globalization;
using SemanticCompilerAdapter;

// Описание ответа урока для отпечатка содержимого: ЕСТЬ ли у урока ответ вообще и как
// этот ответ выглядит текстом. Две величины, а не одна, именно потому что одной не
// хватало. Пока описание было голой строкой, три разных случая сводились к одной и той
// же пустой строке: ответа нет вовсе; ответ есть и он — явно заданная пустая строка;
// ответ есть, но его текстовая форма вернула ничего. Поток отпечатка объявляет длину
// каждого поля до его байтов, поэтому знак-разделитель внутри значения границы полей не
// сдвигает, но различить нуль-длину от нуль-длины длина не может. Значит различие
// обязано существовать ДО потока — здесь.
internal readonly record struct LessonOutputDescription(
    bool OutputIsPresent, // Есть ли у урока ответ вообще.
    string? TextForm)     // Как ответ выглядит текстом; ничего — если текстовой формы нет.
{
    // Описание урока, у которого ответа нет вовсе: присутствия нет и текстовой формы нет.
    internal static LessonOutputDescription AbsentOutput { get; } = new(false, null);
}

// Один документ обученной памяти в том виде, в каком его видит словесная статистика:
// опознание строки памяти, её текст и описание её ответа.
// Ответ входит сюда не ради счёта, а ради отпечатка: урок, у которого поменялся
// только ответ, обязан дать другой отпечаток, иначе прежний снимок молча переживёт
// исправление урока.
internal sealed record LexicalCorpusDocument(string ExampleId, string Text, LessonOutputDescription OutputDescription);

// Готовые к чтению статистики одного документа: его приведённые к корням слова и его длина.
// Пара возвращается одним значением, потому что оценка всегда нуждается в обеих величинах сразу.
internal readonly record struct LexicalDocumentStatistics(
    IReadOnlyDictionary<string, int> Tokens,
    int Length);

// Неизменяемый снимок словесной статистики обученного корпуса ОДНОЙ его версии.
//
// Зачем он нужен. Словесная часть оценки кандидатов считает среднюю длину документа и
// частоту документов по каждому слову запроса. До этого переноса обе величины
// пересчитывались внутри оценки КАЖДОГО кандидата, то есть весь корпус приводился к
// корням заново столько раз, сколько у запроса кандидатов, и ещё раз на каждое слово
// запроса. Опыт сто пятнадцать измерил цену на четырёх документах и четырёх запросах:
// 156 приведений текста к корням против 4, символов 1988 против 88, байт 159 344 против
// 28 336, времени 14,2 против 1,0 миллисекунды, при совпадении оценок и порядка
// кандидатов бит в бит (наибольшее расхождение ровно ноль на 16 сравнениях).
//
// Почему снимок нельзя просто запомнить. Прежняя статистика способна пережить своего
// владельца: число документов у исправленного корпуса может остаться прежним, и тогда
// счётчик документов подмену не замечает. Поэтому снимок опознаётся по отпечатку
// фактического СОДЕРЖИМОГО корпуса, по названию правила приведения текста к корням и по
// пробе самого правила, а не по числу документов и не по времени создания.
internal sealed class LexicalCorpusStatistics
{
    // Название правила приведения текста к корням, по которому посчитан этот снимок.
    // Правило живёт в методе Tokenize ниже: приведение к корням плюс отбрасывание слов
    // короче двух символов. Название входит в опознание снимка.
    internal const string PreprocessingVersion = "normalize-roots-min-length-2-v1";

    // Наименьшая длина слова, которое участвует в словесной оценке.
    // Значение повторяет прежний отбор по длине больше единицы дословно.
    internal const int MinimumTokenLength = 2;

    // Назначение потока отпечатка содержимого корпуса. Входит в сам поток, поэтому отпечаток
    // корпуса не совпадёт с отпечатком другого по смыслу потока на тех же строках.
    private const string ContentDigestPurpose = "lexical-corpus-content";

    // Назначение потока отпечатка пробы правила приведения текста к корням.
    private const string ProbeDigestPurpose = "lexical-corpus-normalization-probe";

    // Значение поля присутствия ответа для урока, у которого ответ ЕСТЬ.
    // Это отдельное поле потока, а не знак, приписанный к тексту ответа: приписанный
    // знак был бы вторым владельцем кодировки, которого следующий читатель потока не
    // знает, и текст урока, начинающийся с того же знака, его бы ломал.
    private const string PresentOutputMarker = "output-present";

    // Значение того же поля для урока, у которого ответа НЕТ.
    private const string AbsentOutputMarker = "output-absent";

    // Прежние разделители полей и документов (управляющие знаки U+001F и U+001E) здесь больше
    // не живут, и это не уборка, а исправление ошибки. Они подставлялись в поток БЕЗ
    // экранирования, поэтому тот же знак внутри текста документа сдвигал границы полей: два
    // разных корпуса давали один поток байтов и один отпечаток. Теперь длина каждого поля
    // объявляется до его байтов, и разделитель не нужен вовсе.

    // Отказ: корпус пуст, статистику считать не из чего.
    internal const string EmptyCorpusErrorCode = "CORPUS_STATISTICS_EMPTY_CORPUS";

    // Отказ: в корпусе два документа с одним опознанием, статистика была бы двусмысленной.
    internal const string DuplicateDocumentErrorCode = "CORPUS_STATISTICS_DUPLICATE_DOCUMENT";

    // Отказ: снимок посчитан по другому содержимому корпуса, чем предъявленное.
    internal const string ContentMismatchErrorCode = "CORPUS_STATISTICS_CONTENT_MISMATCH";

    // Пробы правила приведения текста к корням.
    // Они короткие и постоянные, и подобраны так, чтобы задеть сам отбор по длине:
    // одна буква обязана отсеяться целиком, обычные слова обязаны остаться, запись с
    // пунктуацией обязана разобраться по тем же правилам.
    private static readonly string[] NormalizationRuleProbes =
    [
        "a",
        "Cedar status approved",
        "s?.Length ?? 0"
    ];

    // Приведённые к корням документы и их длины по опознанию строки памяти.
    private readonly Dictionary<string, LexicalDocumentStatistics> _documents;

    // Частота документов по слову: в скольких документах корпуса слово встречается.
    private readonly Dictionary<string, int> _documentFrequency;

    private LexicalCorpusStatistics(
        string corpusVersionKey,
        string corpusContentHash,
        string normalizationRuleProbeDigest,
        int documentCount,
        double averageLength,
        int documentNormalizationCallsOnBuild,
        int probeNormalizationCallsOnBuild,
        Dictionary<string, LexicalDocumentStatistics> documents,
        Dictionary<string, int> documentFrequency)
    {
        // Поля снимка заполняются один раз и дальше не меняются.
        CorpusVersionKey = corpusVersionKey;
        CorpusContentHash = corpusContentHash;
        NormalizationRuleProbeDigest = normalizationRuleProbeDigest;
        DocumentCount = documentCount;
        AverageLength = averageLength;
        DocumentNormalizationCallsOnBuild = documentNormalizationCallsOnBuild;
        ProbeNormalizationCallsOnBuild = probeNormalizationCallsOnBuild;
        _documents = documents;
        _documentFrequency = documentFrequency;
    }

    // Полное опознание версии корпуса: название правила, проба правила и отпечаток
    // содержимого в одной строке. Опознание содержательное, а не порядковое: снимок,
    // посчитанный по другому материалу, получает другой ключ сам, без счётчика ревизий.
    // Почему здесь нет счётчика ревизий. В продукте статистика строится ровно в одном
    // месте, при обучении, вместе с записью примеров в память, и отдельно наружу не
    // публикуется. Счётчик в такой постановке всегда равнялся бы единице, то есть был бы
    // постоянным числом, выдающим себя за счётчик. Копия логики в опыте сто пятнадцать
    // счётчик держала потому, что имитировала повторные пересборки одного и того же
    // материала; продукт их не делает.
    internal string CorpusVersionKey { get; }

    // Отпечаток фактического содержимого корпуса: опознание, текст, присутствие ответа и
    // текстовая форма ответа каждого документа, в постоянном порядке сравнения опознаний.
    // Равное ЧИСЛО документов такой отпечаток не обманывает.
    internal string CorpusContentHash { get; }

    // Отпечаток поведения правила приведения текста на постоянных пробах.
    // Граница этой пробы названа прямо: она доказывает согласие правил только на самих
    // пробах. Правило, изменившееся лишь на словах, которых в пробах нет, этой пробой не
    // ловится; поймать такое могла бы только перепроверка всего корпуса, то есть ровно та
    // работа, которую снимок и убирает.
    internal string NormalizationRuleProbeDigest { get; }

    // Сколько документов в корпусе этой версии.
    internal int DocumentCount { get; }

    // Средняя длина документа в словах. Выражение повторяет прежний код дословно, чтобы
    // получить то же самое число: сумма частот слов каждого документа без нижней границы,
    // затем среднее, затем нижняя граница в единицу.
    internal double AverageLength { get; }

    // Разовая цена подготовки, названная отдельной величиной: сколько документов было
    // приведено к корням при сборке снимка. Ровно один раз на документ за всю жизнь этой
    // версии корпуса. На тёплом запросе приведений корпуса нет вовсе.
    internal int DocumentNormalizationCallsOnBuild { get; }

    // Вторая часть той же разовой цены: сколько проб правила было приведено к корням.
    internal int ProbeNormalizationCallsOnBuild { get; }

    // Правило приведения текста к корням, единственный его владелец на оба потребителя:
    // и на сборку снимка, и на разбор самого запроса. Один владелец нужен затем, чтобы
    // статистика и запрос заведомо разбирались одними правилами.
    internal static Dictionary<string, int> Tokenize(string text)
    {
        // Слова складываются с учётом повторов: оценка нуждается в частоте, а не в наличии.
        var tokens = new Dictionary<string, int>(StringComparer.Ordinal);
        // Приведение к корням идёт тем же разборщиком проекта 23, что и обучающие векторы.
        foreach (var token in TrainingVectorBuilder.NormalizeRoots(text).Where(token => token.Length >= MinimumTokenLength))
        {
            // Повтор слова увеличивает его частоту, первое появление заводит запись.
            tokens[token] = tokens.TryGetValue(token, out var count) ? count + 1 : 1;
        }

        // Готовые частоты слов одного текста.
        return tokens;
    }

    // Описание ответа урока для отпечатка содержимого — единственный владелец этого
    // решения на оба продуктовых пути: и на сборку снимка при обучении, и на описание
    // текущей памяти для проверки происхождения снимка.
    //
    // Три случая получают три РАЗНЫХ описания, и это и есть сама починка:
    //   ответа нет вовсе                                  -> присутствия нет,  формы нет;
    //   ответ есть и он — явно заданная пустая строка     -> присутствие есть, форма пустая;
    //   ответ есть, но его текстовая форма вернула ничего -> присутствие есть, формы нет.
    // Первый и третий случай различаются полем присутствия ответа, второй и третий —
    // полем текстовой формы. Прежде все три давали одну пустую строку, и два разных
    // обученных корпуса получали один отпечаток.
    //
    // Названная граница, оставленная будущему читателю: у ответа, чьё приведение к
    // строке возвращает имя его типа, отпечаток увидит это имя, и подмена такого ответа
    // другим объектом того же типа останется незамеченной. Сегодня оба продуктовых пути
    // этой единицы отвечают строкой, у которой текстовая форма есть она сама.
    internal static LessonOutputDescription DescribeOutput<TOutput>(TOutput output)
        => output is null
            // Ответа нет вовсе: отказ здесь не нужен, нужно отличимое описание.
            ? LessonOutputDescription.AbsentOutput
            // Ответ есть; его текстовая форма может сама оказаться отсутствующей, и это
            // уже третий случай, отличимый по полю присутствия ответа.
            : new LessonOutputDescription(true, Convert.ToString(output, CultureInfo.InvariantCulture));

    // Сборка снимка ОДИН раз на версию корпуса: каждый документ приводится к корням ровно однажды.
    internal static OperationResult<LexicalCorpusStatistics> Build(IReadOnlyList<LexicalCorpusDocument> documents)
    {
        // Пустой корпус отвергается общим конвертом: средней длины у него нет.
        if (documents is null || documents.Count == 0)
            return OperationResult<LexicalCorpusStatistics>.Fail("Corpus statistics require at least one document.", EmptyCorpusErrorCode);

        // Приведённые документы по опознанию строки памяти.
        var byId = new Dictionary<string, LexicalDocumentStatistics>(StringComparer.Ordinal);
        // Частота документов по слову.
        var documentFrequency = new Dictionary<string, int>(StringComparer.Ordinal);
        // Длины документов без нижней границы: именно из них прежний код считал среднее.
        var rawLengths = new List<int>(documents.Count);
        // Счётчик фактических приведений документов к корням. Разовая цена именно
        // измеряется, а не пересказывается размером входа: иначе поле однажды соврёт о
        // работе, которой не было.
        var documentNormalizationCalls = 0;

        foreach (var document in documents)
        {
            // Двусмысленный корпус отвергается: два документа с одним опознанием сделали бы
            // статистику зависящей от порядка перебора.
            if (document is null || string.IsNullOrEmpty(document.ExampleId) || byId.ContainsKey(document.ExampleId))
                return OperationResult<LexicalCorpusStatistics>.Fail("Corpus documents require unique identifiers.", DuplicateDocumentErrorCode);

            // Одно приведение к корням на документ за всю жизнь этой версии корпуса.
            var tokens = Tokenize(document.Text ?? string.Empty);
            // Приведение состоялось, и счётчик разовой цены это записал.
            documentNormalizationCalls++;
            // Сумма частот слов документа: та же величина, что прежде шла в среднее.
            var rawLength = tokens.Values.Sum();
            // Длина документа для самой оценки повторяет прежнюю нижнюю границу в единицу.
            byId[document.ExampleId] = new LexicalDocumentStatistics(tokens, Math.Max(1, rawLength));
            // В среднее идёт величина без нижней границы, ровно как в прежнем выражении.
            rawLengths.Add(rawLength);

            foreach (var token in tokens.Keys)
            {
                // Слово засчитывается документу один раз, сколько бы раз он его ни содержал.
                documentFrequency[token] = documentFrequency.TryGetValue(token, out var seen) ? seen + 1 : 1;
            }
        }

        // Среднее по целым числам считается точно: сумма целых, затем одно деление,
        // поэтому значение не зависит от порядка перебора документов.
        var averageLength = Math.Max(1.0, rawLengths.DefaultIfEmpty(1).Average());
        // Проба правила приведения текста считается один раз на снимок и сама сообщает,
        // сколько приведений ей на это понадобилось.
        var probe = ComputeNormalizationRuleProbe();
        // Отпечаток содержимого считается из самого материала, а не из заявленного числа.
        var contentHash = ComputeContentHash(documents);

        // Готовый снимок одной версии корпуса.
        return OperationResult<LexicalCorpusStatistics>.Ok(new LexicalCorpusStatistics(
            ComposeVersionKey(probe.Digest, contentHash),
            contentHash,
            probe.Digest,
            documents.Count,
            averageLength,
            documentNormalizationCalls,
            probe.NormalizationCalls,
            byId,
            documentFrequency));
    }

    // Проверка происхождения: принадлежит ли этот снимок предъявленному корпусу.
    //
    // Отпечаток пересчитывается из фактического материала ДО использования снимка;
    // заявленного отпечатка недостаточно. Проверка не обращается ни к модели, ни к
    // указателю близких векторов: у неё на входе только сами документы, поэтому чужой
    // или устаревший снимок отвергается без единого обращения к модели.
    internal OperationResult<LexicalCorpusStatistics> RequireBelongsTo(IReadOnlyList<LexicalCorpusDocument> documents)
    {
        // Пустой корпус не может владеть статистикой.
        if (documents is null || documents.Count == 0)
            return OperationResult<LexicalCorpusStatistics>.Fail("Corpus statistics require at least one document.", EmptyCorpusErrorCode);

        // Почему здесь НЕТ сверки названия правила и его пробы, хотя они входят в опознание
        // снимка. Правило приведения текста — чистая статическая функция без изменяемого
        // состояния, а снимок никуда не сохраняется и не переживает процесс. Внутри одного
        // процесса и название, и проба — постоянные величины, поэтому такая сверка была бы
        // сравнением значения с самим собой: проверка, которая не может упасть, честной
        // проверкой не является. Опознание правила остаётся в ключе версии корпуса, чтобы
        // будущий сохраняемый снимок можно было отвергнуть по нему; живой проверкой здесь
        // служит отпечаток содержимого.
        // Главная проверка: отпечаток содержимого предъявленного корпуса, посчитанный заново.
        if (!string.Equals(CorpusContentHash, ComputeContentHash(documents), StringComparison.Ordinal))
            return OperationResult<LexicalCorpusStatistics>.Fail("Corpus statistics belong to another corpus version.", ContentMismatchErrorCode);

        // Снимок принадлежит этому корпусу и может быть переиспользован.
        return OperationResult<LexicalCorpusStatistics>.Ok(this);
    }

    // Статистики одного документа по его опознанию.
    // Отсутствие документа сообщается признаком, а не исключением: прежняя оценка на
    // неизвестном документе возвращала ноль, и это поведение сохраняется у вызывающего.
    internal bool TryGetDocument(string exampleId, out LexicalDocumentStatistics document)
        => _documents.TryGetValue(exampleId ?? string.Empty, out document);

    // Частота документов по слову. Слова, которого в корпусе нет, дают ноль документов,
    // ровно как прежний пересчёт по всему корпусу.
    internal int GetDocumentFrequency(string token)
        => _documentFrequency.TryGetValue(token ?? string.Empty, out var known) ? known : 0;

    // Сборка полного опознания версии корпуса из названия правила приведения текста, версии
    // правила КОДИРОВАНИЯ полей, пробы правила и отпечатка содержимого.
    //
    // Версия кодирования входит в опознание отдельной величиной: смена правила кодирования
    // меняет отпечаток, не меняя ни одного документа, и без этой величины такая смена
    // выглядела бы сменой содержимого корпуса.
    //
    // Названная граница этой склейки, оставленная для будущего читателя. Части опознания
    // соединяются двоеточием БЕЗ экранирования — тем самым способом, который в отпечатке
    // содержимого признан дефектом. Здесь он безопасен ровно по одной причине: ни одна из
    // четырёх частей не способна нести двоеточие. Название правила приведения текста и версия
    // правила кодирования — постоянные этого файла и соседнего, оба отпечатка — шестнадцатеричная
    // запись в нижнем регистре. Как только любая часть сможет содержать двоеточие — например
    // появится составное название правила или часть придёт извне, — склейка станет
    // двусмысленной, и её нужно будет перевести на то же однозначное кодирование. Это
    // предупреждение, а не починка: сегодняшнего столкновения здесь нет.
    private static string ComposeVersionKey(string probeDigest, string contentHash)
        => string.Concat(
            PreprocessingVersion,                        // Название правила приведения текста к корням.
            ":",                                         // Разделитель частей опознания.
            UnambiguousFieldEncoding.EncodingVersion,     // Версия правила кодирования полей.
            ":",                                         // Разделитель частей опознания.
            probeDigest,                                 // Отпечаток поведения правила на пробах.
            ":",                                         // Разделитель частей опознания.
            contentHash);                                // Отпечаток фактического содержимого.

    // Отпечаток содержимого корпуса: число документов, а затем по каждому документу его
    // опознание, текст, ПРИСУТСТВИЕ ответа и текстовая форма ответа — четырьмя отдельными
    // полями однозначного кодирования, у каждого из которых длина в байтах объявлена до
    // его байтов. Постоянных разделителей в этом потоке нет вовсе: именно они и были
    // дефектом, который прежний раздел ремонта починил, потому что знак-разделитель внутри
    // значения сдвигал границы полей.
    //
    // Порядок полей одного документа зафиксирован здесь и только здесь:
    //   1) опознание строки памяти;
    //   2) текст документа;
    //   3) присутствие ответа;
    //   4) текстовая форма ответа.
    // Присутствие идёт ДО текстовой формы потому, что отвечает на другой вопрос: «есть ли
    // ответ вообще», а не «как он выглядит». Своим полем, а не приписанным к тексту знаком:
    // приписанный знак был бы вторым владельцем кодировки, и текст урока, начинающийся с
    // того же знака, его бы ломал.
    //
    // Порядок перебора задан сравнением опознаний, а не порядком памяти. Причина: ни одна
    // величина этого снимка от порядка не зависит — средняя длина считается по целым
    // числам и потому точна при любом порядке, частота документов и длины привязаны к
    // опознаниям. Поэтому постоянный порядок делает отпечаток ровно таким же строгим к
    // подмене содержимого и перестаёт зависеть от внутреннего порядка перебора словаря
    // памяти. Это названное отличие от копии логики в опыте сто пятнадцать, где материал
    // собирался в порядке памяти.
    private static string ComputeContentHash(IReadOnlyList<LexicalCorpusDocument> documents)
    {
        // Поток отпечатка: версия правила кодирования и назначение потока записываются сразу.
        var writer = new UnambiguousFieldEncoding.Writer(ContentDigestPurpose);
        // Число документов входит в поток: корпус из трёх документов не сможет дать тот же
        // поток, что корпус из двух, даже если остальные байты сложатся одинаково.
        writer.WriteCount(documents.Count);
        foreach (var document in documents.OrderBy(document => document?.ExampleId ?? string.Empty, StringComparer.Ordinal))
        {
            // Описание ответа берётся один раз: у отсутствующего документа его нет вовсе,
            // и это третий, самый внешний случай отсутствия.
            var output = document?.OutputDescription;
            // Отсутствующий документ и отсутствующее поле записываются своей меткой, а не
            // пустой строкой: «поля нет» и «поле пустое» — разное содержимое, и склеивать их
            // значит молча считать два разных корпуса одним.
            writer.WriteField(document?.ExampleId)          // Опознание строки памяти.
                  .WriteField(document?.Text)               // Текст документа.
                  .WriteField(DescribeOutputPresence(output)) // Присутствие ответа — своё поле.
                  .WriteField(output?.TextForm);            // Текстовая форма ответа урока.
        }

        // Отпечаток считается один раз по всему накопленному потоку.
        return writer.Digest();
    }

    // Присутствие ответа урока в виде значения отдельного поля потока. Три степени
    // отсутствия получают три разных значения этого поля и потому не сливаются:
    //   документа нет вовсе — поля нет, его метку ставит само правило кодирования;
    //   у документа нет ответа — значение «ответа нет»;
    //   у документа есть ответ — значение «ответ есть», а как он выглядит, говорит
    //   уже следующее поле потока.
    private static string? DescribeOutputPresence(LessonOutputDescription? output)
        => output is null
            // Документа нет: описания ответа у него тоже нет, и поле отсутствует целиком.
            ? null
            // Ответ есть или ответа нет — своим постоянным значением, объявленным по длине.
            : output.Value.OutputIsPresent ? PresentOutputMarker : AbsentOutputMarker;

    // Отпечаток поведения правила приведения текста на постоянных пробах и фактическое
    // число приведений, которое на это ушло. Число возвращается рядом с отпечатком, чтобы
    // вторая часть разовой цены тоже была измерена, а не предположена.
    private static (string Digest, int NormalizationCalls) ComputeNormalizationRuleProbe()
    {
        // Поток отпечатка пробы собирается тем же единственным правилом кодирования, что и
        // поток содержимого: одно правило на оба потока, чтобы дефект нельзя было починить в
        // одном месте и оставить в другом.
        var writer = new UnambiguousFieldEncoding.Writer(ProbeDigestPurpose);
        // Число проб входит в поток.
        writer.WriteCount(NormalizationRuleProbes.Length);
        // Счётчик фактических приведений проб к корням.
        var normalizationCalls = 0;
        foreach (var probe in NormalizationRuleProbes)
        {
            // Проба приводится к корням тем же единственным правилом, что и документы.
            var tokens = Tokenize(probe);
            // Приведение пробы состоялось.
            normalizationCalls++;
            // Число найденных слов пробы объявляется до самих слов.
            writer.WriteCount(tokens.Count);
            // Порядок слов внутри пробы задаётся сравнением строк, а не перебором словаря:
            // иначе отпечаток зависел бы от внутреннего порядка словаря.
            foreach (var token in tokens.Keys.OrderBy(token => token, StringComparer.Ordinal))
            {
                writer.WriteField(token)                  // Само слово пробы.
                      .WriteCount(tokens[token]);          // Его частота в этой пробе.
            }
        }

        // Отпечаток поведения правила на этих пробах и цена его получения.
        return (writer.Digest(), normalizationCalls);
    }
}
