namespace AgentInfrastructure.Logical;

using System.Security.Cryptography;
using System.Text;

// Однозначное кодирование полей перед счётом отпечатка — ЕДИНСТВЕННЫЙ владелец этого правила
// на оба продуктовых потребителя: словесную статистику обученного корпуса и сторожа
// происхождения учебного материала.
//
// Что было неправильно. Оба потребителя собирали материал в одну строку через постоянные
// разделители и считали отпечаток от неё. У статистики разделителями служили управляющие знаки
// U+001F и U+001E, у сторожа — перевод строки. Разделитель НЕ экранировался, поэтому то же
// самое значение внутри поля сдвигало границы полей: два РАЗНЫХ материала давали один и тот же
// поток байтов и один отпечаток. Текст с переводом строки внутри вопроса — не редкость, а
// обычное содержание, поэтому у сторожа этот случай достижим без всякой подделки. Вторая
// половина того же дефекта: отсутствующее значение приводилось к пустой строке, то есть «поля
// нет» и «поле пустое» становились одним и тем же материалом.
//
// Что стало. Длина каждого поля объявляется ДО его байтов, поэтому ни одна
// последовательность внутри значения не может быть принята за границу: читателю незачем искать
// разделитель, он берёт ровно столько байтов, сколько объявлено. Отсутствующее значение несёт
// свою отдельную метку и потому никогда не совпадает с пустым. Длина считается в БАЙТАХ
// кодировки, а не в знаках: у знаков вне основной латиницы байтов больше одного, и счёт по
// знакам снова сделал бы границу приблизительной. Число записей потока входит в сам поток, а
// версия правила кодирования — в опознание результата, чтобы смена правила не выглядела сменой
// содержимого.
//
// Чем это не является. Это не шифрование и не защита от подделки: правило открыто и
// воспроизводимо. Его единственная задача — чтобы разный материал давал разные байты, а
// одинаковый материал давал одинаковые.
internal static class UnambiguousFieldEncoding
{
    // Название правила кодирования. Входит в опознание результата: по нему будущий читатель
    // отличит отпечаток, посчитанный этим правилом, от отпечатка другого правила.
    internal const string EncodingVersion = "length-prefixed-utf8-be32-sha256-v1";

    // Метка отсутствующего значения. Отдельная именно затем, чтобы «поля нет» никогда не
    // совпадало с «поле пустое».
    private const byte AbsentFieldTag = 0x00;

    // Метка присутствующего значения: за ней идут длина в байтах и сами байты.
    private const byte PresentFieldTag = 0x01;

    // Метка целого числа: за ней идут четыре байта значения.
    private const byte CountTag = 0x02;

    // Писатель однозначного потока. Обычный класс, а не структура: он накапливает байты, и
    // копия накопителя по значению здесь была бы источником ошибок.
    internal sealed class Writer
    {
        // Накопитель байтов потока. Отпечаток считается от него целиком и один раз.
        private readonly List<byte> _bytes = [];

        // Создание писателя сразу записывает версию правила и назначение потока.
        // Назначение нужно, чтобы одинаковые поля в разных по смыслу потоках не давали один
        // отпечаток: отпечаток корпуса и отпечаток учебного материала остаются разными даже на
        // совпадающем наборе строк.
        internal Writer(string purpose)
        {
            WriteField(EncodingVersion); // Версия правила кодирования идёт первым полем потока.
            WriteField(purpose);         // Назначение потока идёт вторым полем.
        }

        // Запись одного значения, которое может отсутствовать.
        internal Writer WriteField(string? value)
        {
            if (value is null)
            {
                _bytes.Add(AbsentFieldTag); // Отсутствующее значение несёт только свою метку.
                return this;                // Возврат писателя позволяет писать поля цепочкой.
            }

            var utf8 = Encoding.UTF8.GetBytes(value); // Байты значения в кодировке потока.
            _bytes.Add(PresentFieldTag);              // Метка присутствующего значения.
            WriteBigEndian(utf8.Length);              // Длина в БАЙТАХ, объявленная до самих байтов.
            _bytes.AddRange(utf8);                    // Сами байты значения, ровно объявленной длины.
            return this;                              // Писатель возвращается для следующего поля.
        }

        // Запись целого числа: число записей, порядковый номер, любая счётная величина потока.
        internal Writer WriteCount(int value)
        {
            _bytes.Add(CountTag);    // Метка целого числа отличает его от значения-строки.
            WriteBigEndian(value);   // Четыре байта от старшего к младшему: порядок задан явно.
            return this;             // Писатель возвращается для следующего поля.
        }

        // Отпечаток всего накопленного потока. Примитив назван прямо: SHA-256, шестнадцатеричная
        // запись в нижнем регистре. Собственная свёртка платформы здесь не используется: её
        // значение не обязано совпадать между процессами.
        internal string Digest()
            => Convert.ToHexString(SHA256.HashData(_bytes.ToArray())).ToLowerInvariant();

        // Четыре байта целого числа от старшего к младшему. Порядок задан явно и не зависит от
        // того, как хранит числа текущая машина.
        private void WriteBigEndian(int value)
        {
            _bytes.Add((byte)((value >> 24) & 0xFF)); // Старший байт числа.
            _bytes.Add((byte)((value >> 16) & 0xFF)); // Второй байт числа.
            _bytes.Add((byte)((value >> 8) & 0xFF));  // Третий байт числа.
            _bytes.Add((byte)(value & 0xFF));         // Младший байт числа.
        }
    }
}
