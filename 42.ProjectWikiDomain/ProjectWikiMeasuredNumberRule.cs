namespace ProjectWikiDomain;

/// <summary>
/// Нейтральный дом единственного правила «число измерено» для домена страниц
/// знаний о проекте.
///
/// Зачем отдельный файл, если правило уже было написано. Правило родилось
/// внутри двери публикации по метрикам обучения предпочтений
/// (DPO — Direct Preference Optimization, прямая оптимизация по предпочтениям)
/// и жило там. Пока его спрашивали только конвейеры обучения, это было
/// терпимо: они и сами решают вопрос публикации. Но то же правило нужно теперь
/// дверям ВЫБОРА — модели обоснования потока по подсказке, машине плана
/// оркестрации и обучаемой модели маршрутизации запросов. Эти места про
/// публикацию ничего не знают и знать не должны: «можно ли верить этому числу»
/// и «можно ли публиковать эту модель» — разные вопросы, и зависимость выбора
/// от двери публикации направлена неверно. Поэтому правило переехало сюда, в
/// место без собственного мнения о публикации, а дверь публикации стала таким
/// же спрашивающим, как все остальные.
///
/// Что правило утверждает. Измерением считается только настоящее конечное
/// число. «Не-число» и обе бесконечности измерением не являются.
///
/// Почему одного сравнения с порогом недостаточно. В этом языке любое
/// сравнение с «не-числом» ложно. Поэтому дверь вида «отказать, если
/// показатель ниже порога» при неизмеренном числе молча отвечает «порог
/// пройден» и пропускает негодное значение дальше. С плюс бесконечностью беда
/// зеркальная: она больше любого порога, поэтому положительная форма проверки
/// объявляет её успехом. Опереться как на защиту нельзя ни на одну из двух
/// форм, и взятие минимума или ограничение отрезком тоже не защита: минимум
/// единицы и «не-числа» — снова «не-число».
///
/// Что это правило НЕ закрывает. Оно отвергает ровно «не-число» и обе
/// бесконечности. Конечное бессмысленное значение — например точность порядка
/// 1e308 — остаётся измеренным по этому правилу и проходит порог. Это
/// отдельная открытая находка: запрет бессмысленного диапазона меняет смысл
/// приёмки и требует решения владельца, поэтому здесь он не вводится.
/// </summary>
public static class ProjectWikiMeasuredNumberRule
{
    // Общий человеческий хвост названия причины «число не измерено». Живёт
    // здесь, а не в двери публикации, по той же причине, что и само правило:
    // двери выбора обязаны называть эту болезнь, не зная ничего про
    // публикацию. Нужен, чтобы все двери называли её одинаково и человек в
    // отчёте сразу отличал её от «показатель ниже порога»: это разные беды, и
    // лечатся они по-разному — первая починкой измерения или обученного
    // состояния, вторая улучшением модели.
    public const string NotMeasuredReasonSuffix = "not_measured";

    /// <summary>
    /// Единственное определение «число измерено» для всего домена. Все двери
    /// его спрашивают и ни одна не повторяет: копии условия разошлись бы ровно
    /// так, как однажды разошлись три отдельные записи порога публикации.
    /// </summary>
    public static bool IsMeasured(double value)
        // Измерением считается только настоящее конечное число: ни «не-число»,
        // ни плюс или минус бесконечность измерением не являются.
        => !double.IsNaN(value) && !double.IsInfinity(value);

    /// <summary>
    /// Короткий ответ «хотя бы одно из этих чисел не измерено» для дверей,
    /// которые решают проход сразу по нескольким показателям.
    ///
    /// Запас по умолчанию здесь отказывающий, а не разрешающий. Пустая ссылка
    /// означает «подтвердить измеренность нечем», и для двери это отказ:
    /// разрешающий ответ открывал бы дверь ровно тогда, когда проверять
    /// оказалось нечем, то есть повторял бы ту самую болезнь, против которой
    /// стоит всё это правило, — условие, которое при беде не способно дать
    /// отказ. «Не смог подтвердить» никогда не равно «подтвердил».
    /// </summary>
    public static bool AnyNotMeasured(params double[]? values)
        // Пустая ссылка — сразу отказ; иначе каждое значение проверяется тем же
        // единственным правилом измеренности.
        => values is null || values.Any(value => !IsMeasured(value));
}
