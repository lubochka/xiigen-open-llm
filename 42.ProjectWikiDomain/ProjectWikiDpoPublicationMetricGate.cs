namespace ProjectWikiDomain;

using AgentInfrastructure;

/// <summary>
/// Единственная дверь публикации по метрикам обучения предпочтений
/// (DPO — Direct Preference Optimization, прямая оптимизация по предпочтениям).
///
/// Зачем она нужна. До этого порог публикации был записан трижды: один раз в
/// публикаторе манифеста и дважды в конвейере обучения. Выражения разошлись:
/// публикатор отказывал по условию «меньше порога», а конвейер разрешал по
/// условию «не меньше порога». Противоположно эти две формы ведут себя только
/// в случае «НЕ-ЧИСЛО»: сравнение с не-числом всегда ложно, поэтому
/// «отказать, если меньше» не срабатывало и публикация шла дальше, а
/// «разрешить, если не меньше» отказывало верно. А на ПЛЮС БЕСКОНЕЧНОСТИ
/// права не была ни одна из двух форм: бесконечность больше любого порога,
/// поэтому положительная форма конвейера её РАЗРЕШАЛА, а отрицательная форма
/// публикатора по-прежнему не отказывала — публиковали обе. Один общий текст
/// правила убирает и расхождение на не-числе, и общий пропуск бесконечности
/// по построению.
///
/// Что именно проверяется. Утверждение порога — это утверждение о том, чему
/// модель научилась К КОНЦУ обучения, поэтому читаются только поля конечного
/// состояния: конечная точность на обучающем наборе, конечный запас
/// предпочтения на обучающем наборе и конечная точность на отложенной выборке.
/// Средние по всей траектории обучения живут в отдельных диагностических полях
/// и в решение о публикации не входят.
/// </summary>
public static class ProjectWikiDpoPublicationMetricGate
{
    // Код отказа для случая, когда хотя бы одно из читаемых чисел не измерено:
    // не-число или бесконечность. Отдельный код нужен, чтобы человек в отчёте
    // отличил «модель не дотянула до порога» от «мы вообще не получили числа».
    public const string MetricsNotMeasuredErrorCode =
        "DPO_GATE_METRICS_NOT_MEASURED";

    // Исторический код отказа «метрики не прошли порог». Сохранён дословно,
    // потому что по нему уже могут опираться отчёты и внешние читатели.
    public const string MetricsBelowGateErrorCode = "DPO_GATE_NOT_PASSED";

    // Минимальная конечная точность на обучающем наборе. Число не меняется этой
    // правкой: 0,75 стоял в публикаторе и в двух местах конвейера.
    public const double MinimumFinalTrainingAccuracy = 0.75;

    // Минимальная конечная точность на отложенной выборке. То же число 0,75.
    public const double MinimumFinalHeldOutAccuracy = 0.75;

    // Нижняя строгая граница конечного запаса предпочтения: требуется строго
    // больше нуля. Ноль и отрицательное значение означают, что модель к концу
    // обучения не предпочитает правильный ответ неправильному.
    public const double ExclusiveFloorForFinalTrainingRewardMargin = 0.0;

    // Общий человеческий хвост названия причины «число не измерено». Нужен,
    // чтобы все двери приёмки называли эту болезнь одинаково и чтобы человек
    // в отчёте сразу отличал её от «показатель ниже порога»: это разные беды,
    // и лечатся они по-разному. Значение дословно то же, что раньше, и этой
    // правкой не меняется; теперь оно взято из нейтрального дома правила,
    // потому что ту же болезнь обязаны называть и двери выбора, которым про
    // публикацию знать нечего.
    public const string NotMeasuredReasonSuffix =
        ProjectWikiMeasuredNumberRule.NotMeasuredReasonSuffix;

    /// <summary>
    /// Единственное определение «число измерено», которое спрашивают все двери
    /// приёмки обучения предпочтений в этом домене.
    ///
    /// Зачем это имя осталось здесь и к кому оно обращается. Проверка
    /// «не-число или бесконечность» нужна не только этой двери: конвейеры
    /// обучения читают ещё десяток показателей, каждый своим сравнением с
    /// порогом, и все четырнадцать уже опубликованных дверей спрашивают именно
    /// это имя. Поэтому имя остаётся на месте, но само условие здесь больше не
    /// записано: это обращённая к публикации форма единственного правила,
    /// которое живёт в нейтральном доме домена. Одно понятие, два обращения,
    /// ни одной копии условия. Переехало правило потому, что его же спрашивают
    /// теперь двери выбора, а им про публикацию знать нечего: зависимость
    /// выбора от двери публикации направлена неверно.
    ///
    /// Почему недостаточно сравнения с порогом. Сравнение с «не-числом» в C#
    /// всегда ложно, поэтому проверка «отказать, если показатель ниже порога»
    /// при неизмеренном числе молча отвечает «порог пройден». С плюс
    /// бесконечностью беда обратная: она больше любого порога, поэтому
    /// положительная форма проверки объявляет её успехом.
    ///
    /// Где это вероятнее всего. Запас предпочтения и начальное расхождение
    /// обучаемой и справочной модели — разности логарифмов вероятностей, их
    /// область значений не ограничена по смыслу, нулевая вероятность даёт
    /// бесконечность, а вычитание бесконечностей — не-число. Показатели
    /// точности по смыслу должны лежать на отрезке от нуля до единицы, но
    /// проверки диапазона в этом домене нет ни здесь, ни в конвейерах, поэтому
    /// «точность не бывает большой» — это ожидание, а не гарантия кода.
    ///
    /// Что это правило НЕ закрывает. Оно отвергает ровно «не-число» и обе
    /// бесконечности. Конечное бессмысленное значение — например точность на
    /// отложенной выборке порядка 1e308 — остаётся измеренным по этому правилу
    /// и проходит порог. Это отдельная открытая находка: запрет
    /// бессмысленного диапазона меняет смысл приёмки и требует решения
    /// владельца, поэтому здесь он не вводится.
    /// </summary>
    public static bool IsMeasured(double value)
        // Условие не повторяется, а спрашивается у нейтрального дома правила:
        // так у этой двери и у дверей выбора остаётся ровно одно понятие
        // измеренности, которое не может разойтись по копиям.
        => ProjectWikiMeasuredNumberRule.IsMeasured(value);

    /// <summary>
    /// Короткий ответ «хотя бы одно из этих чисел не измерено» для дверей,
    /// которые решают проход сразу по нескольким показателям.
    ///
    /// Запас по умолчанию здесь отказывающий, а не разрешающий. Пустая ссылка
    /// означает «подтвердить измеренность нечем», и для двери приёмки это
    /// отказ: разрешающий ответ открывал бы дверь ровно тогда, когда проверять
    /// оказалось нечем, то есть повторял бы ту самую болезнь, против которой
    /// стоит всё это правило, — условие, которое при беде не способно дать
    /// отказ. Для двери приёмки «не смог подтвердить» никогда не равно
    /// «подтвердил».
    /// </summary>
    public static bool AnyNotMeasured(params double[]? values)
        // Та же обращённая к публикации форма: короткий ответ целиком берётся
        // из нейтрального дома правила — вместе с отказывающим запасом по
        // умолчанию на пустой ссылке, описанным выше.
        => ProjectWikiMeasuredNumberRule.AnyNotMeasured(values);

    /// <summary>
    /// Решает, пускают ли конечные метрики обучения предпочтений эту модель в
    /// публикацию. Успех означает «порог пройден»; отказ несёт человеку причину
    /// и код: либо числа не измерены, либо они ниже порога.
    /// </summary>
    public static OperationResult<bool> Evaluate(
        ProjectWikiDpoMetricRunResult? metrics)
    {
        // Отсутствие результата прогона — это не «ноль» и не «прошло»: мерить
        // было нечего, поэтому дверь закрыта по причине «не измерено».
        if (metrics is null)
        {
            return OperationResult<bool>.Fail(
                "DPO metrics are required before publishing: no metric run result was supplied.",
                MetricsNotMeasuredErrorCode);
        }

        // Все три читаемых числа должны быть настоящими измерениями. Проверка
        // стоит ДО сравнения с порогом, потому что сравнение с не-числом
        // молча даёт ложь и тем самым пропускает негодную модель дальше.
        // Спрашивается та же короткая форма, что и у дверей конвейеров: прежде
        // три отрицания стояли здесь вручную и делали её работу повторно.
        if (AnyNotMeasured(
                metrics.FinalAccuracy,
                metrics.FinalRewardMargin,
                metrics.HeldOutAccuracy))
        {
            return OperationResult<bool>.Fail(
                "DPO metrics must be measured and finite before publishing: final training accuracy, final training reward margin, and final held-out accuracy cannot be NaN or infinity.",
                MetricsNotMeasuredErrorCode);
        }

        // Собственно порог приёмки, записанный один раз: конечная точность на
        // обучающем наборе и на отложенной выборке не ниже 0,75, а конечный
        // запас предпочтения строго положителен.
        if (metrics.FinalAccuracy < MinimumFinalTrainingAccuracy ||
            metrics.HeldOutAccuracy < MinimumFinalHeldOutAccuracy ||
            metrics.FinalRewardMargin <= ExclusiveFloorForFinalTrainingRewardMargin)
        {
            return OperationResult<bool>.Fail(
                "DPO metrics must pass before publishing.",
                MetricsBelowGateErrorCode);
        }

        // Все условия конечного состояния выполнены: дверь открыта.
        return OperationResult<bool>.Ok(true);
    }

    /// <summary>
    /// Короткий ответ «да или нет» для мест, где решение публикации собирается
    /// из нескольких условий и код отказа там не формируется.
    /// </summary>
    public static bool Allows(ProjectWikiDpoMetricRunResult? metrics)
        // Переиспользуем ровно то же правило, чтобы «да/нет» и код отказа
        // никогда не могли разойтись между собой.
        => Evaluate(metrics).IsSuccess;

    // Число считается измеренным, когда оно не «не-число» и не бесконечность.
    // Именно этих двух случаев не хватало прежней проверке публикатора.
    // Прежнее имя сохранено, потому что по нему читается условие в Evaluate,
    // но само правило теперь спрашивается у общедоступного определения выше:
    // так у этой двери и у четырнадцати дверей конвейеров обучения остаётся
    // ровно одно понятие измеренности, которое не может разойтись по копиям.
    private static bool IsMeasuredAndFinite(double value)
        => IsMeasured(value);
}
