using System.Text.Json.Serialization;

namespace DPO.Models;

/// <summary>
/// Квитанция одного шага обучения предпочтению. Здесь лежат только те величины,
/// которые тренер действительно вычислил на обработанном наборе пар. Ни одно поле
/// этой записи не является долей правильных ответов, которые модель выдаёт
/// обычному потребителю: правильность ответа измеряется отдельной панелью
/// считывания, а не этой квитанцией.
/// </summary>
public record DpoMetrics
{
    /// <summary>Номер шага обучения, которым подписана эта квитанция.</summary>
    public int    Step          { get; init; }

    /// <summary>Значение целевой функции шага; для точных пар это softplus(-запас).</summary>
    public float  Loss          { get; init; }

    /// <summary>Бета, умноженная на разность логарифмических вероятностей предпочитаемой стороны у политики и у замороженного эталона.</summary>
    public float  ChosenReward  { get; init; }

    /// <summary>Бета, умноженная на ту же разность для отвергаемой стороны.</summary>
    public float  RejectedReward { get; init; }

    /// <summary>
    /// Запас вознаграждения: <see cref="ChosenReward"/> минус <see cref="RejectedReward"/>.
    /// Это сдвиг политики относительно эталона, а не норма градиента и не сила
    /// обновления: называть его нормой или силой градиента без отдельного измерения
    /// этой величины запрещено.
    /// </summary>
    public float  RewardMargin  { get; init; }

    /// <summary>
    /// Историческое имя поля, сохранённое ради совместимости уже записанных квитанций.
    /// Хранит долю обработанных пар, у которых <see cref="RewardMargin"/> строго больше
    /// нуля, то есть долю пар, где политика сместилась в сторону предпочитаемого ответа
    /// СИЛЬНЕЕ, ЧЕМ неизменный эталон. В путях одиночного шага, группового шага и
    /// оценивания это обычное среднее по парам набора; в векторном пути это среднее,
    /// взвешенное по весам пар, которые нормированы на единицу. В векторном пути вес
    /// каждой пары дополнительно ограничен снизу значением 0,01 — и в числителе, и в
    /// знаменателе нормировки, — поэтому пара с весом ноль вносит в эту долю не ноль,
    /// а 0,01, делённое на сумму ограниченных снизу весов набора.
    /// Эта величина НЕ равна доле пар, у которых логарифмическая вероятность
    /// предпочитаемой стороны выше отвергаемой у самой политики, и НЕ равна доле
    /// правильных ответов обычного потребителя. Явное имя той же величины —
    /// <see cref="ReferenceRelativeImprovementRate"/>.
    /// </summary>
    public float  Accuracy      { get; init; }

    /// <summary>
    /// Явно названный вывод той же величины, что лежит в историческом поле
    /// <see cref="Accuracy"/>: доля пар с положительным запасом вознаграждения
    /// относительно замороженного эталона. Поле добавлено, чтобы читатель квитанции
    /// видел смысл числа из его имени и не принимал его за правильность ответа.
    /// Значение намеренно совпадает с <see cref="Accuracy"/>: это переименование
    /// подписи, а не новое измерение и не улучшение обучения.
    /// Поле намеренно не попадает в саму квитанцию: действующий сторож совместимости
    /// требует, чтобы записанная квитанция читалась и записывалась обратно теми же
    /// байтами. Явное имя предназначено потребителям в коде и писателям отчётов,
    /// которые обязаны выводить его вместо исторического имени.
    /// </summary>
    [JsonIgnore]
    public float ReferenceRelativeImprovementRate => Accuracy;

    /// <summary>Имя версии целевой функции, когда пара прошла точный паспорт материала.</summary>
    [JsonIgnore(Condition = JsonIgnoreCondition.WhenWritingNull)]
    public string? ObjectiveVersion { get; init; }

    /// <summary>
    /// Та же целевая функция шага, накопленная БЕЗ множителя плотности обучающего
    /// вектора: вклад каждой строки умножается только на её нормированный вес.
    ///
    /// Зачем это поле нужно. Поле <see cref="Loss"/> в векторном пути домножается
    /// на плотность обучающего вектора, и только на ветви точных пар. При этом
    /// <see cref="ChosenReward"/>, <see cref="RejectedReward"/>,
    /// <see cref="RewardMargin"/> и <see cref="Accuracy"/> копятся на чистом
    /// нормированном весе. Значит потеря масштабирована иначе, чем каждая
    /// величина, рядом с которой её печатают, и иначе, чем она же на соседнем
    /// пути. Сторож остановки обучения сравнивает именно потерю с НЕПОДВИЖНЫМ
    /// порогом, поэтому порог оказывался зависящим от плотности вектора — свойства
    /// данных, а не хода обучения.
    ///
    /// Как эта величина накапливается, и почему именно так. Построчно, ДО
    /// индивидуального масштабирования каждой строки: сумма произведений потери
    /// строки на её нормированный вес. Получить её делением общей взвешенной
    /// потери на среднюю плотность НЕЛЬЗЯ — при разных значениях плотности в одном
    /// пакете такое деление даёт другое число. Контрпример, записанный в договоре
    /// ремонта: веса строк по половине, плотности один и два, потери две десятых и
    /// восемь десятых дают взвешенную потерю девять десятых, правильную
    /// немасштабированную половину, а деление на среднюю плотность — шесть
    /// десятых.
    ///
    /// Пустое значение против нуля. Пусто означает «не считалось» — например, у
    /// квитанции, записанной до появления этого поля. Ноль означает «посчитано и
    /// равно нулю». Это разные вещи, и смешивать их нельзя: ноль вместо
    /// неизвестного читается как измеренный факт.
    ///
    /// Поле необязательное и пропускается при записи, когда его нет, — тем же
    /// приёмом, что <see cref="ObjectiveVersion"/>. Поэтому уже записанные
    /// квитанции читаются и записываются обратно теми же байтами, и действующий
    /// сторож совместимости не нарушается. Существующее поле <see cref="Loss"/>
    /// не меняется ни именем, ни значением: это добавление рядом, а не замена.
    /// </summary>
    [JsonIgnore(Condition = JsonIgnoreCondition.WhenWritingNull)]
    public float? UnscaledLoss { get; init; }

    /// <summary>
    /// Было ли на этом шаге применено обновление весов.
    ///
    /// Зачем это поле нужно. У векторного пути появился случай, в котором набор пар прочитан,
    /// допущен и годен, но ни одна его пара не просит себя учесть: сырой вес каждой пары равен
    /// ровно нулю. Такой набор не обучает ничему, обновитель весов не вызывается, имя
    /// контрольной точки не резервируется и квитанция завершённого шага не публикуется. Без
    /// отдельного поля этот случай был бы неотличим от обычного шага, у которого все накопленные
    /// величины просто оказались нулями, — а это разные вещи, и читатель квитанции обязан их
    /// различать.
    ///
    /// Пустое значение против ложного. Пусто означает «не сказано»: так выглядят все остальные
    /// пути шага и все квитанции, записанные до появления этого поля. Ложное значение означает
    /// «обновления не было», и его выставляет ровно один случай — пустой активный набор
    /// векторного пути. Истинное значение это поле не принимает нигде: обычный путь оставляет
    /// его пустым, чтобы уже записанные квитанции и квитанции обычных шагов читались и
    /// записывались обратно теми же байтами.
    ///
    /// Чего это поле НЕ означает. Оно не говорит ничего о качестве обучения, о правильности
    /// ответов и о величине обновления. Оно отвечает ровно на один вопрос: состоялся ли шаг
    /// изменения весов вообще.
    ///
    /// Поле необязательное и пропускается при записи, когда его нет, — тем же приёмом, что
    /// <see cref="ObjectiveVersion"/> и <see cref="UnscaledLoss"/>. Существующие поля не
    /// меняются ни именем, ни значением: это добавление рядом, а не замена.
    /// </summary>
    [JsonIgnore(Condition = JsonIgnoreCondition.WhenWritingNull)]
    public bool? UpdateApplied { get; init; }
}
